#!/bin/sh
# titian-pipe.sh — Pipe intent (BIRD `protocol pipe`) untuk Titian/klish.
# Pola sama seperti titian-bfd.sh: intent di /etc/titian/pipe.conf
# (tmpfs, dipersistenkan via titian-cfg.sh), generate menulis section
# BIRD /etc/titian/bird.d/pipe.conf lalu memanggil titian-bird.sh
# generate pipe (render + validasi + birdc). Section ditulis ulang
# UTUH tiap apply.
#
# Sintaks BIRD 2.16.1 yang dipakai (docs resmi bird.network,
# User's Guide 2.16.1, §6.13 Pipe):
#   protocol pipe <name> {
#       table <primary>;
#       peer table <secondary>;
#       export <all|none|filter <name>>;
#       import <all|none|filter <name>>;
#   }
# Pipe menghubungkan dua routing table (nettype harus sama): primary
# (`table`) <-> secondary (`peer table`), dua arah sesuai filter.
# Export filter = primary -> secondary; import filter = secondary ->
# primary. Route diteruskan dengan source + atribut asli. Blok Pipe
# LANGSUNG berisi opsi channel standar (tidak ada sub-blok ipv4/ipv6).
# Satu-satunya opsi khusus Pipe adalah `peer table`.
# Kegunaan utama: policy routing (tabel ganda + aturan kernel di luar
# BIRD) dan workaround batasan Kernel (dua Kernel tidak bisa ke tabel
# sama; export filter Kernel tidak bisa ubah gateway).
# Pipe tidak mendefinisikan atribut route.
#
# Filter bernama (`import/export filter <name>`) merujuk filter yang
# didefinisikan lewat perintah filter BIRD yang sudah ada
# (`filter <NAME>` di bird-view / titian-bgp.sh filter-add). Filter
# INLINE (`export filter { ... }`) TIDAK diekspos — keputusan B13 (P4/P5):
# filter inline hanyalah syntactic sugar atas filter bernama (preseden B11:
# "Filter inline murni tidak diekspos"); bentuk bernama + `where` (B11)
# menutupi semua isi inline; bird -p membuktikan inline valid (probe B13
# C2). Bila import/export tidak diset, opsi itu DIHILANGKAN dari blok
# (default BIRD berlaku; jangan ditebak — docs tidak menyatakan
# default import/export Pipe, dan channel default export adalah none).
#
# Format pipe.conf (satu baris per fakta):
#   pipe <name> table <table>
#   pipe <name> peer-table <table>
#   pipe <name> import all|none|filter <name>
#   pipe <name> export all|none|filter <name>

STATE_ROOT="${TITIAN_STATE_ROOT:-/etc/titian}"
CONF="$STATE_ROOT/pipe.conf"
SECTION_DIR="$STATE_ROOT/bird.d"
# Pager global: output show >1 layar lewat less (titian-page.sh).
# Prologue dipanggil SESUDAH setup warna/TTY bila ada, SEBELUM output pertama.
SBIN_DIR=$(dirname "$0")
. "$SBIN_DIR/titian-page.sh"
# Hanya subcommand baca yang dipager: set/generate/commit TIDAK —
# output-nya harus tetap streaming/langsung, bukan tertahan sampai EXIT.
case "${1:-}" in show) titian_page_begin ;; esac

SECTION="$SECTION_DIR/pipe.conf"
PROG="titian-pipe"
err() { echo "Error($PROG): $*" >&2; exit 33; }
die() { echo "$PROG: $*" >&2; exit 1; }

touch_conf() {
    if [ ! -f "$CONF" ]; then
        mkdir -p "$(dirname "$CONF")" 2>/dev/null
        printf '# pipe.conf - generated by klish, do not edit by hand\n' > "$CONF" \
            || die "cannot create $CONF"
        chmod 600 "$CONF" 2>/dev/null || true
    fi
}

# upsert <regex-untuk-hapus> <baris-baru>
upsert() {
    _re="$1"; _line="$2"
    touch_conf
    _tmp="$CONF.tmp.$$"
    grep -v "$_re" "$CONF" > "$_tmp" 2>/dev/null || true
    printf '%s\n' "$_line" >> "$_tmp"
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
    chmod 600 "$CONF" 2>/dev/null || true
}

dellines() {
    _re="$1"
    touch_conf
    _tmp="$CONF.tmp.$$"
    grep -v "$_re" "$CONF" > "$_tmp" 2>/dev/null || true
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
}

has_facts() {
    [ -f "$CONF" ] || return 1
    grep -v '^[[:space:]]*#' "$CONF" 2>/dev/null | grep -q '[^[:space:]]'
}

valid_name() {
    # $1=nama $2=konteks: [A-Za-z0-9_]+ (nama pipe/tabel/filter BIRD).
    case "$1" in
        ''|*[!A-Za-z0-9_]*) err "$2 harus nama BIRD [A-Za-z0-9_]: $1" ;;
    esac
}

get_field() {
    # get_field <pipe> <field> -> nilai (kolom ke-4; untuk import/export
    # filter, kolom ke-5 adalah nama filter — ditangani pemanggil).
    grep "^pipe $1 $2 " "$CONF" 2>/dev/null | head -1 | awk '{print $4}'
}

cond_validate() {
    # cond_validate <COND> — validasi ekspresi filter bentuk ringkas
    # (mis. net~10.0.0.0/8) via titian-bgp.sh cond-to-bird. Bila script
    # itu tidak ada (deploy parsial), fallback validasi ringan.
    _bgpsh="$(dirname "$0")/titian-bgp.sh"
    if [ -x "$_bgpsh" ]; then
        "$_bgpsh" cond-to-bird "$1" >/dev/null
    else
        case "$1" in *[\;\{\}]* ) err "where: ekspresi mengandung karakter terlarang (; { })" ;; esac
    fi
}

cond_translate() {
    # cond_translate <COND> -> terjemahan BIRD (stdout); gagal rc=33.
    # Dipakai di generate untuk bentuk `import/export where <COND>`.
    _bgpsh="$(dirname "$0")/titian-bgp.sh"
    if [ -x "$_bgpsh" ]; then
        "$_bgpsh" cond-to-bird "$1" || exit 33
    else
        err "penerjemah kondisi tidak tersedia (titian-bgp.sh tidak ditemukan di $(dirname "$0"))"
    fi
}

# table_nettype <nama> — tipe tabel (ipv4|ipv6|ipv6-sadr|...) dari
# intent global, atau built-in master4/master6. Gagal (return 1) bila
# tidak diketahui — pemanggil jangan gagalkan generate untuk tabel
# yang tidak bisa dilacak (mungkin didefinisikan di luar intent).
table_nettype() {
    _n="$1"
    case "$_n" in
        master4) printf 'ipv4'; return 0 ;;
        master6) printf 'ipv6'; return 0 ;;
    esac
    _g="$STATE_ROOT/bird-global.conf"
    if [ -f "$_g" ]; then
        _t=$(grep "^table .* $_n\$" "$_g" 2>/dev/null | head -1 | awk '{print $2}')
        [ -n "$_t" ] && { printf '%s' "$_t"; return 0; }
    fi
    return 1
}

cmd_pipe_touch() {
    _n="$1"
    [ -n "$_n" ] || err "pipe-touch butuh NAMA pipe"
    valid_name "$_n" "nama pipe"
    touch_conf
    echo "Pipe $_n"
}

cmd_pipe_add() {
    _n="$1"
    [ -n "$_n" ] || err "pipe-add butuh NAMA pipe"
    valid_name "$_n" "nama pipe"
    touch_conf
    echo "Pipe $_n"
}

cmd_pipe_del() {
    _n="$1"
    [ -n "$_n" ] || err "pipe-del butuh NAMA pipe"
    _tmp="$CONF.tmp.$$"
    awk -v n="$_n" '$1!="pipe" || $2!=n' "$CONF" 2>/dev/null > "$_tmp" || true
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
    echo "Pipe $_n dihapus"
}

# valid_spec <SPEC> <debug|mrtdump> — validasi daftar kelas koma (Bab 3.4-2/3,
# salinan _rip_valid_spec; B9).
valid_spec() {
    _vs_spec="$1"; _vs_kind="$2"
    [ -n "$_vs_spec" ] || err "$_vs_kind butuh all|off|kelas,kelas,..."
    case "$_vs_spec" in all|off) return 0 ;; esac
    _vs_rest="$_vs_spec"
    while [ -n "$_vs_rest" ]; do
        case "$_vs_rest" in *,*) _vs_done=${_vs_rest%%,*}; _vs_rest=${_vs_rest#*,} ;; *) _vs_done="$_vs_rest"; _vs_rest="" ;; esac
        if [ "$_vs_kind" = "debug" ]; then
            case "$_vs_done" in states|routes|filters|interfaces|events|packets) ;; *) err "debug kelas tidak dikenal: $_vs_done (boleh: states|routes|filters|interfaces|events|packets)" ;; esac
        else
            case "$_vs_done" in states|messages) ;; *) err "mrtdump kelas tidak dikenal: $_vs_done (boleh: states|messages)" ;; esac
        fi
    done
}
# emit_dbg <SPEC> <debug|mrtdump> — satu baris debug/mrtdump (indent 4 spasi).
emit_dbg() {
    case "$1" in all|off) echo "    $2 $1;" ;; *) echo "    $2 { $(printf '%s' "$1" | sed 's/,/, /g') };" ;; esac
}

cmd_debug_set() { # B9: debug-set NAME SPEC (Bab 3.4-2, per-instance)
    _n="$1"; _v="$2"
    [ -n "$_n" ] && [ -n "$_v" ] || err "debug-set butuh NAMA SPEC"
    valid_name "$_n" "nama pipe"
    valid_spec "$_v" debug
    upsert "^pipe $_n debug " "pipe $_n debug $_v"
    echo "Pipe $_n debug = $_v"
}
cmd_debug_del() { # B9: debug-del NAME
    [ -n "$1" ] || err "debug-del butuh NAMA"
    valid_name "$1" "nama pipe"
    dellines "^pipe $1 debug "
    echo "Pipe $1 debug dihapus (default BIRD off)"
}
cmd_mrtdump_set() { # B9: mrtdump-set NAME SPEC (Bab 3.4-3, per-instance)
    _n="$1"; _v="$2"
    [ -n "$_n" ] && [ -n "$_v" ] || err "mrtdump-set butuh NAMA SPEC"
    valid_name "$_n" "nama pipe"
    valid_spec "$_v" mrtdump
    upsert "^pipe $_n mrtdump " "pipe $_n mrtdump $_v"
    echo "Pipe $_n mrtdump = $_v"
}
cmd_mrtdump_del() { # B9: mrtdump-del NAME
    [ -n "$1" ] || err "mrtdump-del butuh NAMA"
    valid_name "$1" "nama pipe"
    dellines "^pipe $1 mrtdump "
    echo "Pipe $1 mrtdump dihapus (default BIRD off)"
}

cmd_pipe_unset() { # pipe-unset <NAME> <field> — hapus satu field (kembali ke default BIRD)
    _n="$1"; _f="$2"
    [ -n "$_n" ] && [ -n "$_f" ] || err "pipe-unset butuh NAMA FIELD"
    valid_name "$_n" "nama pipe"
    case "$_f" in
        table|peer-table|import|export|disabled|from) dellines "^pipe $_n $_f " ;;
        *) err "field pipe tidak dikenal: $_f (table|peer-table|import|export|disabled|from)" ;;
    esac
    echo "Pipe $_n $_f dihapus (default BIRD)"
}

cmd_pipe_set() {
    # pipe-set <NAME> <field> <value...>
    # field: table|peer-table|import|export|disabled|from
    # (Bab 3.4-1 disabled; Bab 3.2-15/16 from; Bab 3.5-4/5 import/export
    # where = filter inline bentuk ringkas, mis. net~10.0.0.0/8.)
    _n="$1"; _f="$2"; shift 2
    [ -n "$_n" ] && [ -n "$_f" ] && [ -n "$1" ] || \
        err "pipe-set butuh NAMA FIELD VALUE"
    valid_name "$_n" "nama pipe"
    _val="$*"
    case "$_f" in
        table)
            valid_name "$1" "table"
            upsert "^pipe $_n table " "pipe $_n table $1" ;;
        peer-table)
            valid_name "$1" "peer table"
            upsert "^pipe $_n peer-table " "pipe $_n peer-table $1" ;;
        disabled)
            case "$1" in
                on|off) upsert "^pipe $_n disabled " "pipe $_n disabled $1" ;;
                *) err "disabled harus on|off: $1" ;;
            esac ;;
        from)
            valid_name "$1" "from"
            upsert "^pipe $_n from " "pipe $_n from $1" ;;
        import|export)
            case "$1" in
                all|none) upsert "^pipe $_n $_f " "pipe $_n $_f $1" ;;
                filter)
                    [ -n "$2" ] || err "$_f filter butuh nama filter"
                    valid_name "$2" "nama filter"
                    upsert "^pipe $_n $_f " "pipe $_n $_f filter $2" ;;
                where)
                    shift
                    [ -n "$*" ] || err "$_f where butuh ekspresi filter bentuk ringkas (mis. where net~10.0.0.0/8)"
                    cond_validate "$*" || exit 33
                    upsert "^pipe $_n $_f " "pipe $_n $_f where $*" ;;
                *) err "$_f harus all|none|filter <nama>|where <ekspresi>: $1" ;;
            esac ;;
        *) err "field pipe tidak dikenal: $_f (table|peer-table|import|export|disabled|from)" ;;
    esac
    echo "Pipe $_n $_f = $_val"
}

cmd_generate() {
    touch_conf
    set -f
    mkdir -p "$SECTION_DIR" 2>/dev/null || die "cannot mkdir $SECTION_DIR"
    _tmp="$SECTION.tmp.$$"
    if has_facts; then
        {
            echo "# pipe.conf - generated by titian-pipe.sh, do not edit by hand"
            for _n in $(grep '^pipe ' "$CONF" 2>/dev/null | awk '{print $2}' | awk '!s[$0]++'); do
                _tab=$(get_field "$_n" table)
                _peer=$(get_field "$_n" peer-table)
                [ -n "$_tab" ] || err "pipe $_n belum punya table (pipe <nama> -> table <nama>)"
                [ -n "$_peer" ] || err "pipe $_n belum punya peer table (pipe <nama> -> peer-table <nama>)"
                # Guard: primary dan peer table HARUS satu tipe (BIRD:
                # "Primary table and peer table must have the same type").
                # Hanya ditegakkan bila kedua tipe bisa dilacak.
                _tt=$(table_nettype "$_tab" 2>/dev/null) || _tt=""
                _pt=$(table_nettype "$_peer" 2>/dev/null) || _pt=""
                if [ -n "$_tt" ] && [ -n "$_pt" ] && [ "$_tt" != "$_pt" ]; then
                    err "pipe $_n: table $_tab ($_tt) dan peer table $_peer ($_pt) beda tipe — BIRD menolak (Primary table and peer table must have the same type)"
                fi
                _from=$(get_field "$_n" from)
                if [ -n "$_from" ]; then
                    _gf="$STATE_ROOT/bird-global.conf"
                    [ -f "$_gf" ] && grep -q "^template pipe $_from\( \|$\)" "$_gf" 2>/dev/null || \
                        err "pipe $_n: from template pipe $_from tidak ada di bird-global.conf (template-add pipe $_from dulu)"
                    echo "protocol pipe $_n from $_from {"
                else
                    echo "protocol pipe $_n {"
                fi
                _dis=$(get_field "$_n" disabled)
                case "$_dis" in on) echo "    disabled;" ;; esac
                echo "    table $_tab;"
                echo "    peer table $_peer;"
                _pdbg=$(grep "^pipe $_n debug " "$CONF" 2>/dev/null | head -1 | awk '{print $4}')
                _pmrt=$(grep "^pipe $_n mrtdump " "$CONF" 2>/dev/null | head -1 | awk '{print $4}')
                [ -n "$_pdbg" ] && emit_dbg "$_pdbg" debug
                [ -n "$_pmrt" ] && emit_dbg "$_pmrt" mrtdump
                _imp=$(grep "^pipe $_n import " "$CONF" 2>/dev/null | head -1)
                _exp=$(grep "^pipe $_n export " "$CONF" 2>/dev/null | head -1)
                if [ -n "$_imp" ]; then
                    case "$_imp" in
                        *' filter '*) echo "    import filter $(echo "$_imp" | awk '{print $5}');" ;;
                        *' where '*) _wcond=$(echo "$_imp" | awk '{print $5}'); _wbird=$(cond_translate "$_wcond") || exit 33; echo "    import where $_wbird;" ;;
                        *) echo "    import $(echo "$_imp" | awk '{print $4}');" ;;
                    esac
                fi
                if [ -n "$_exp" ]; then
                    case "$_exp" in
                        *' filter '*) echo "    export filter $(echo "$_exp" | awk '{print $5}');" ;;
                        *' where '*) _wcond=$(echo "$_exp" | awk '{print $5}'); _wbird=$(cond_translate "$_wcond") || exit 33; echo "    export where $_wbird;" ;;
                        *) echo "    export $(echo "$_exp" | awk '{print $4}');" ;;
                    esac
                fi
                echo "}"
                echo ""
            done
        } > "$_tmp" || die "cannot write $_tmp"
    else
        {
            echo "# pipe.conf - generated by titian-pipe.sh, do not edit by hand"
            echo "# (tidak ada config pipe — protocol pipe tidak dibuat)"
        } > "$_tmp" || die "cannot write $_tmp"
    fi
    mv "$_tmp" "$SECTION" || die "cannot write $SECTION"
    chmod 644 "$SECTION" 2>/dev/null || true
    set +f
    echo "Pipe section ditulis: $SECTION"
    _birdsh="$(dirname "$0")/titian-bird.sh"
    if [ -x "$_birdsh" ]; then
        "$_birdsh" generate pipe || exit 33
    else
        echo "Warning: $_birdsh tidak ditemukan; section hanya ditulis, belum di-apply" >&2
    fi
}

birdc_bin() {
    command -v birdc 2>/dev/null || { [ -x /usr/sbin/birdc ] && echo /usr/sbin/birdc; } || \
        { [ -x /usr/local/sbin/birdc ] && echo /usr/local/sbin/birdc; } || echo birdc
}
# birdc_sock — salinan titian-birdc.sh (BC8, B13): cetak "-s <path>" bila
# socket utama dikonfigurasi via klish ($STATE_ROOT/birdc.conf), kosong bila
# default. Dipakai semua pemanggilan birdc di file ini.
birdc_sock() {
    _s=$(grep '^socket ' "$STATE_ROOT/birdc.conf" 2>/dev/null | head -1 | cut -d' ' -f2-)
    [ -n "$_s" ] && printf '%s' "-s $_s"
}


cmd_show() {
    touch_conf
    echo "--- pipe.conf (intent) ---"
    cat "$CONF"
    echo "--- bird.d/pipe.conf (section, bila ada) ---"
    [ -f "$SECTION" ] && cat "$SECTION" || echo "(belum di-generate)"
    echo "--- birdc show protocol (pipe) ---"
    _birdc=$(birdc_bin)
    _done=0
    set -f
    for _n in $(grep '^pipe ' "$CONF" 2>/dev/null | awk '{print $2}' | awk '!s[$0]++'); do
        if _out=$("$_birdc" $(birdc_sock) show protocol "$_n" 2>&1); then
            echo "$_out" | grep -v '^BIRD'
            _done=1
        fi
    done
    set +f
    [ "$_done" = "0" ] && echo "(BIRD tidak jalan / belum ada pipe — birdc show protocol gagal)"
    return 0
}

case "$1" in
    pipe-touch) shift; cmd_pipe_touch "$@" ;;
    has-facts) has_facts ;;
    pipe-add) shift; cmd_pipe_add "$@" ;;
    pipe-del) shift; cmd_pipe_del "$@" ;;
    pipe-set) shift; cmd_pipe_set "$@" ;;
    pipe-unset) shift; cmd_pipe_unset "$@" ;;
    debug-set) shift; cmd_debug_set "$@" ;;
    debug-del) shift; cmd_debug_del "$@" ;;
    mrtdump-set) shift; cmd_mrtdump_set "$@" ;;
    mrtdump-del) shift; cmd_mrtdump_del "$@" ;;
    generate) cmd_generate ;;
    show) cmd_show ;;
    *) echo "Usage: $0 {pipe-touch NAME|has-facts|pipe-add NAME|pipe-del NAME|pipe-set NAME table|peer-table|import|export|disabled|from VALUE|pipe-unset NAME table|peer-table|import|export|disabled|from|debug-set NAME SPEC|debug-del NAME|mrtdump-set NAME SPEC|mrtdump-del NAME|generate|show}" >&2; exit 2 ;;
esac
