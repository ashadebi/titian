#!/bin/sh
# titian-babel.sh — Babel intent (BIRD `protocol babel`) untuk Titian/klish.
# Batch B9 program BIRD (P3).
# Pola sama seperti titian-rip.sh (satu instance tetap + interface view):
# intent di /etc/titian/babel.conf (tmpfs, dipersistenkan via
# titian-cfg.sh), generate menulis section BIRD
# /etc/titian/bird.d/babel.conf lalu memanggil titian-bird.sh generate
# babel (render + validasi + birdc). Section ditulis ulang UTUH tiap
# apply.
#
# Sintaks BIRD 2.16.1 yang dipakai (docs resmi bird.network,
# User's Guide 2.16.1, §6.2 Babel — RFC 8966):
#   protocol babel {
#       interface "eth*" { type wired; };
#       interface "wlan0", "wlan1" {
#           type wireless;
#           hello interval 1;
#           rxcost 512;
#       };
#       interface "tap0";
#       ipv4 {
#           export where (source = RTS_DEVICE) || (source = RTS_BABEL);
#       };
#       ipv6 { ... };
#   }
# Dual stack: IPv4 + IPv6 lewat transport IPv6 yang sama; kirim/terima
# paket Babel hanya butuh link-local IPv6. Ekstensi IPv6 source-specific
# routing (SADR/SSR) didukung. BUTUH peer Babel di link yang sama
# (multicast/UDP) — tanpa peer, protokol jalan tapi tidak ada route
# yang dipertukarkan. Channel: ipv4, ipv6, ipv6 sadr.
# Default BIRD (docs §6.2): randomize router id no; type wired;
# rxcost 96 (wired) / 256 (wireless); limit 12; hello interval 4s;
# update interval 4x hello; port 6696; rx/tx buffer/length = MTU
# interface (min 512 + overhead); check link yes; next hop ipv4 =
# preferred IPv4 interface; next hop ipv6 = link-local source;
# extended next hop yes; rtt cost 0 (disabled; 96 untuk tunnel);
# rtt min 10ms; rtt max 120ms; rtt decay 42 (1..256); send timestamps
# yes; authentication none (mac wajib ada password).
# Atribut route babel_metric (1..65535, 65535 = infinity) READ-ONLY —
# diekspos sebagai atribut filter di titian-bgp.sh/titian-function.sh
# (B9), bukan perintah di sini.
# TIDAK ADA perintah birdc `show babel` (Bab 4.3 terkonfirmasi) —
# status dilihat lewat `show protocols [all]`.
# TIDAK diimplementasi di batch ini:
#   - `tx priority` (BB11): Linux-specific (Bab 3.4-10); tidak ada
#     padanan FreeBSD.
#   - Validasi panjang password per algoritma: docs TIDAK memberi
#     tabel panjang key per algoritma (hmac sha1/256/384/512 —
#     blake2s/blake2b TIDAK ada di BIRD 2.20, ditolak setter) —
#     panjang HARUS cocok key size algoritma; `bird -p` yang
#     memutuskan saat generate.
#   - Bentuk `export where ...` / `import where ...` bebas: channel
#     hanya all|none|filter bernama (pola klish RIP/OSPF); ekspresi
#     `where` mentah tidak diekspos.
#
# Format babel.conf (satu baris per fakta):
#   randomize-router-id <on|off>
#   ipv4-table <TAB> | ipv4-import <all|none|filter NAME> | ipv4-export <...>
#   ipv6-table <TAB> | ipv6-import <...> | ipv6-export <...>
#   ipv6-sadr <on|off>
#   debug <SPEC> | mrtdump <SPEC>
#   interface <PAT> <field> <value>
#     field: type|rxcost|limit|hello-interval|update-interval|port|
#       tx-class|tx-dscp|rx-buffer|tx-length|check-link|
#       next-hop-ipv4|next-hop-ipv6|extended-next-hop|rtt-cost|
#       rtt-min|rtt-max|rtt-decay|send-timestamps|authentication
#   interface <PAT> password <TEXT>
#   interface <PAT> pw-<field> <value>
#     field password: id|generate-from|generate-to|accept-from|
#       accept-to|from|to|algorithm (algorithm ditulis hmac-sha256
#       dst, diubah jadi `hmac sha256` saat generate; tanggal
#       YYYY-MM-DD saja — B24, BIRD menolak tanggal+jam di password)

STATE_ROOT="${TITIAN_STATE_ROOT:-/etc/titian}"
CONF="$STATE_ROOT/babel.conf"
GLOBAL_CONF="$STATE_ROOT/bird-global.conf"
SECTION_DIR="$STATE_ROOT/bird.d"
SECTION="$SECTION_DIR/babel.conf"
PROG="titian-babel"
err() { echo "Error($PROG): $*" >&2; exit 33; }
die() { echo "$PROG: $*" >&2; exit 1; }

touch_conf() {
    if [ ! -f "$CONF" ]; then
        mkdir -p "$(dirname "$CONF")" 2>/dev/null
        printf '# babel.conf - generated by klish, do not edit by hand\n' > "$CONF" \
            || die "cannot create $CONF"
        chmod 600 "$CONF" 2>/dev/null || true
    fi
}

upsert() {
    _re="$1"; _line="$2"
    touch_conf
    _tmp="$CONF.tmp.$$"
    grep -v "$_re" "$CONF" > "$_tmp" 2>/dev/null || true
    printf '%s\n' "$_line" >> "$_tmp"
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
    chmod 600 "$CONF" 2>/dev/null || true
}

dellines() {
    _re="$1"
    touch_conf
    _tmp="$CONF.tmp.$$"
    grep -v "$_re" "$CONF" > "$_tmp" 2>/dev/null || true
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
}

has_facts() {
    [ -f "$CONF" ] || return 1
    grep -v '^[[:space:]]*#' "$CONF" 2>/dev/null | grep -q '[^[:space:]]'
}

valid_name() {
    case "$1" in
        ''|*[!A-Za-z0-9_]*) err "$2 harus nama BIRD [A-Za-z0-9_]: $1" ;;
    esac
    case "$1" in [A-Za-z_]*) ;; *) err "$2 harus diawali huruf/underscore: $1" ;; esac
}

valid_num() { # <nilai> <min> <max> <label>
    case "$1" in ''|*[!0-9]*) err "$4 harus bilangan $2..$3: $1" ;; esac
    [ "$1" -ge "$2" ] 2>/dev/null || err "$4 harus $2..$3: $1"
    [ "$1" -le "$3" ] 2>/dev/null || err "$4 harus $2..$3: $1"
}

valid_onoff() {
    case "$1" in on|off) ;; *) err "$2 harus on|off: $1" ;; esac
}

valid_time() { # waktu BIRD: angka + satuan opsional ms|us|s|m|h|d
    _v="$1"; _l="$2"
    _n="$_v"
    case "$_n" in *ms|*us) _n=${_n%??} ;; *s|*m|*h|*d) _n=${_n%?} ;; esac
    case "$_n" in ''|*[!0-9.]*) err "$_l harus waktu BIRD (mis. 4, 4s, 500ms, 1.5s): $_v" ;; esac
    case "$_n" in *.*.*) err "$_l harus waktu BIRD (satu titik desimal saja): $_v" ;; esac
}

valid_ipv4() {
    _v="$1"; _l="$2"
    case "$_v" in *:*|*[!0-9.]*) err "$_l harus alamat IPv4: $_v" ;; esac
    [ "$(printf '%s' "$_v" | awk -F. '{print NF}')" = "4" ] || err "$_l harus alamat IPv4 (4 oktet): $_v"
    for _o in $(printf '%s' "$_v" | tr '.' ' '); do
        case "$_o" in ''|*[!0-9]*) err "$_l harus alamat IPv4: $_v" ;; esac
        [ "$_o" -le 255 ] 2>/dev/null || err "$_l harus alamat IPv4 (oktet 0..255): $_v"
    done
}

valid_ipv6() {
    _v="$1"; _l="$2"
    case "$_v" in *:*) ;; *) err "$_l harus alamat IPv6: $_v" ;; esac
    case "$_v" in *[!0-9A-Fa-f:.]*) err "$_l harus alamat IPv6 (karakter tidak valid): $_v" ;; esac
    case "$_v" in *[!:]:) err "$_l harus alamat IPv6 (':' tunggal di akhir): $_v" ;; esac
    case "$_v" in :[!:]*) err "$_l harus alamat IPv6 (':' di awal tanpa '::'): $_v" ;; esac
    _t=${_v#*::}
    case "$_t" in *::*) err "$_l harus alamat IPv6 ('::' hanya boleh sekali): $_v" ;; esac
}

valid_pattern() { # pola interface shell-like: tanpa spasi/;/kutip
    case "$1" in ''|*' '*|*\;*|*\"*|*\'*) err "$2 tidak boleh kosong/mengandung spasi/;/kutip: $1" ;; esac
}

re_esc() { printf '%s' "$1" | sed 's/[][\\.*^$]/\\&/g'; }

_bbl_valid_spec() {
    _bb_spec="$1"; _bb_kind="$2"
    [ -n "$_bb_spec" ] || err "$_bb_kind butuh all|off|kelas,kelas,..."
    case "$_bb_spec" in all|off) return 0 ;; esac
    _bb_rest="$_bb_spec"
    while [ -n "$_bb_rest" ]; do
        case "$_bb_rest" in *,*) _bb_done=${_bb_rest%%,*}; _bb_rest=${_bb_rest#*,} ;; *) _bb_done="$_bb_rest"; _bb_rest="" ;; esac
        if [ "$_bb_kind" = "debug" ]; then
            case "$_bb_done" in states|routes|filters|interfaces|events|packets) ;; *) err "debug kelas tidak dikenal: $_bb_done (boleh: states|routes|filters|interfaces|events|packets)" ;; esac
        else
            case "$_bb_done" in states|messages) ;; *) err "mrtdump kelas tidak dikenal: $_bb_done (boleh: states|messages)" ;; esac
        fi
    done
}

cmd_babel_touch() {
    touch_conf
    echo "Babel"
}

cmd_top_set() { # top-set <randomize-router-id|ipv6-sadr> <on|off>
    _f="$1"; _v="$2"
    case "$_f" in randomize-router-id|ipv6-sadr) ;; *) err "field harus randomize-router-id|ipv6-sadr: $_f" ;; esac
    valid_onoff "$_v" "$_f"
    upsert "^$_f " "$_f $_v"
    echo "Babel $_f = $_v"
}

cmd_top_del() {
    _f="$1"
    case "$_f" in randomize-router-id|ipv6-sadr) ;; *) err "field harus randomize-router-id|ipv6-sadr: $_f" ;; esac
    dellines "^$_f "
    echo "Babel $_f dihapus (default BIRD: randomize no / ipv6 tanpa sadr)"
}

cmd_chan_set() { # chan-set <ipv4|ipv6> <table|import|export> <VALUE> [FILTER-NAME]
    _c="$1"; _f="$2"; _v="$3"; _fn="$4"
    case "$_c" in ipv4|ipv6) ;; *) err "channel harus ipv4|ipv6: $_c" ;; esac
    case "$_f" in
        table)
            valid_name "$_v" "tabel channel $_c"
            case "$_c" in
                ipv4) [ -f "$GLOBAL_CONF" ] && grep -q "^table ipv4 $_v\$" "$GLOBAL_CONF" 2>/dev/null || [ "$_v" = "master4" ] || err "tabel $_v belum didefinisikan (global -> table-add ipv4 $_v)" ;;
                ipv6) { grep -q "^table ipv6 $_v\$" "$GLOBAL_CONF" 2>/dev/null || grep -q "^table ipv6-sadr $_v\$" "$GLOBAL_CONF" 2>/dev/null || [ "$_v" = "master6" ]; } || err "tabel $_v belum didefinisikan (global -> table-add ipv6|ipv6-sadr $_v)" ;;
            esac
            upsert "^$_c-table " "$_c-table $_v" ;;
        import|export)
            case "$_v" in
                all|none) upsert "^$_c-$_f " "$_c-$_f $_v" ;;
                filter)
                    [ -n "$_fn" ] || err "$_c $_f filter butuh NAMA filter"
                    valid_name "$_fn" "nama filter"
                    upsert "^$_c-$_f " "$_c-$_f filter $_fn" ;;
                *) err "$_c $_f harus all|none|filter NAMA: $_v" ;;
            esac ;;
        *) err "field channel harus table|import|export: $_f" ;;
    esac
    echo "Babel $_c $_f = $_v${_fn:+ $_fn}"
}

cmd_chan_del() {
    _c="$1"; _f="$2"
    case "$_c" in ipv4|ipv6) ;; *) err "channel harus ipv4|ipv6: $_c" ;; esac
    case "$_f" in table|import|export) ;; *) err "field channel harus table|import|export: $_f" ;; esac
    dellines "^$_c-$_f "
    echo "Babel $_c $_f dihapus"
}

cmd_debug_set() {
    _bbl_valid_spec "$1" debug
    upsert '^debug ' "debug $1"
    echo "Babel debug = $1"
}

cmd_debug_del() {
    dellines '^debug '
    echo "Babel debug dihapus (default BIRD off)"
}

cmd_mrtdump_set() {
    _bbl_valid_spec "$1" mrtdump
    upsert '^mrtdump ' "mrtdump $1"
    echo "Babel mrtdump = $1"
}

cmd_mrtdump_del() {
    dellines '^mrtdump '
    echo "Babel mrtdump dihapus (default BIRD off)"
}

# --- interface ---
cmd_interface_add() {
    # interface-add <PAT>: tulis BARIS TELANJANG ke intent (B.4:
    # interface-add lama hanya touch file — interface tanpa field
    # tidak pernah ter-render; generate mengiterasi baris `interface `
    # dan emit_iface mencetak blok, kosong pun, ber-default BIRD).
    # Bila sudah ada baris interface itu, jangan duplikasi.
    _pat="$1"
    valid_pattern "$_pat" "interface"
    touch_conf
    _re=$(re_esc "$_pat")
    if ! grep -q "^interface $_re " "$CONF" 2>/dev/null && \
       ! grep -q "^interface $_re\$" "$CONF" 2>/dev/null; then
        printf 'interface %s\n' "$_pat" >> "$CONF"
    fi
    echo "Babel interface $_pat"
}

cmd_interface_del() {
    _pat="$1"
    valid_pattern "$_pat" "interface"
    # JANGAN pakai nama `_re`: dellines() menimpa `_re` global — panggilan
    # kedua akan memakai pola pertama (bug yang sama dengan B3 di RIP
    # password-del; di sini baris telanjang `interface X` tidak pernah
    # terhapus — ketahuan mock B10).
    _patre=$(re_esc "$_pat")
    dellines "^interface $_patre "
    dellines "^interface $_patre\$"
    echo "Babel interface $_pat dihapus"
}

cmd_interface_set() { # interface-set <PAT> <FIELD> <VALUE>
    _pat="$1"; _f="$2"; _v="$3"
    valid_pattern "$_pat" "interface"
    [ -n "$_v" ] || err "interface $_pat $_f butuh nilai"
    case "$_f" in
        type) case "$_v" in wired|wireless|tunnel) ;; *) err "type harus wired|wireless|tunnel: $_v" ;; esac ;;
        rxcost) valid_num "$_v" 0 65535 "rxcost" ;;
        limit) valid_num "$_v" 0 16 "limit (0..16 Hello terakhir)" ;;
        hello-interval|update-interval) valid_time "$_v" "$_f" ;;
        port) valid_num "$_v" 1 65535 "port" ;;
        tx-class) valid_num "$_v" 0 255 "tx-class" ;;
        tx-dscp) valid_num "$_v" 0 63 "tx-dscp" ;;
        rx-buffer|tx-length) valid_num "$_v" 512 65535 "$_f (min 512 byte + overhead)" ;;
        check-link|extended-next-hop|send-timestamps) valid_onoff "$_v" "$_f" ;;
        next-hop-ipv4) valid_ipv4 "$_v" "next-hop-ipv4" ;;
        next-hop-ipv6) valid_ipv6 "$_v" "next-hop-ipv6" ;;
        rtt-cost) valid_num "$_v" 0 65535 "rtt-cost" ;;
        rtt-min|rtt-max) valid_time "$_v" "$_f" ;;
        rtt-decay) valid_num "$_v" 1 256 "rtt-decay (1..256)" ;;
        authentication) case "$_v" in none|mac|mac-permissive) ;; *) err "authentication harus none|mac|mac-permissive: $_v" ;; esac ;;
        *) err "field interface tidak dikenal: $_f" ;;
    esac
    upsert "^interface $(re_esc "$_pat") $_f " "interface $_pat $_f $_v"
    echo "Babel interface $_pat $_f = $_v"
}

cmd_interface_unset() {
    _pat="$1"; _f="$2"
    valid_pattern "$_pat" "interface"
    case "$_f" in type|rxcost|limit|hello-interval|update-interval|port|tx-class|tx-dscp|rx-buffer|tx-length|check-link|next-hop-ipv4|next-hop-ipv6|extended-next-hop|rtt-cost|rtt-min|rtt-max|rtt-decay|send-timestamps|authentication) ;; *) err "field interface tidak dikenal: $_f" ;; esac
    dellines "^interface $(re_esc "$_pat") $_f "
    echo "Babel interface $_pat $_f dihapus"
}

cmd_password_add() { # password-add <PAT> <TEXT>
    _pat="$1"; _v="$2"
    valid_pattern "$_pat" "interface"
    [ -n "$_v" ] || err "password butuh teks (tanpa spasi)"
    case "$_v" in *' '*|*\"*|*\\*|*\`*|*'$'*) err "password tidak boleh mengandung spasi/kutip/\\\\/\$/\`: $_v" ;; esac
    upsert "^interface $(re_esc "$_pat") password " "interface $_pat password $_v"
    echo "Babel interface $_pat password = (diset, tidak ditampilkan)"
}

cmd_password_del() {
    _pat="$1"
    valid_pattern "$_pat" "interface"
    dellines "^interface $(re_esc "$_pat") password "
    dellines "^interface $(re_esc "$_pat") pw-"
    echo "Babel interface $_pat password dihapus (sub-opsi password ikut dihapus)"
}

cmd_password_set() { # password-set <PAT> <TEXT> <FIELD> <VALUE>
    _pat="$1"; _pw="$2"; _f="$3"; _v="$4"
    valid_pattern "$_pat" "interface"
    [ -n "$_pw" ] && [ -n "$_v" ] || err "password-set butuh PATTERN PASSWORD FIELD VALUE"
    case "$_f" in
        id) valid_num "$_v" 0 255 "password id" ;;
        generate-from|generate-to|accept-from|accept-to|from|to)
            # B24 (17 Nov 2026): BIRD 2.20.0 password dates = TANGGAL SAJA —
            # datetime (T maupun spasi) DITOLAK bird -p "Invalid date/time"
            # (B24 t8/t9). Cermin valid_bfd_date titian-bfd.sh.
            case "$_v" in *' '*|*\;*|*\"*) err "tanggal $_f tanpa spasi/;/kutip (YYYY-MM-DD saja): $_v" ;; esac
            case "$_v" in [0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]) ;; *) err "password $_f harus tanggal YYYY-MM-DD saja (BIRD 2.20.0 menolak tanggal+jam di password): $_v" ;; esac ;;
        algorithm) case "$_v" in hmac-sha1|hmac-sha256|hmac-sha384|hmac-sha512) ;; *) err "algorithm harus hmac-sha1|hmac-sha256|hmac-sha384|hmac-sha512 (blake2s/blake2b TIDAK ada di BIRD 2.20 — ditolak bird -p; keyed md5/sha1 TIDAK ada di Babel): $_v" ;; esac ;;
        *) err "field password harus id|generate-from|generate-to|accept-from|accept-to|from|to|algorithm: $_f" ;;
    esac
    _cur=$(grep "^interface $(re_esc "$_pat") password " "$CONF" 2>/dev/null | head -1 | awk '{print $4}')
    if [ -n "$_cur" ] && [ "$_cur" != "$_pw" ]; then
        err "password-set: password interface $_pat sudah '$_cur' — hapus dulu (password-del) bila mau ganti password"
    fi
    upsert "^interface $(re_esc "$_pat") password " "interface $_pat password $_pw"
    upsert "^interface $(re_esc "$_pat") pw-$_f " "interface $_pat pw-$_f $_v"
    echo "Babel interface $_pat password $_f = $_v"
}

cmd_password_unset() {
    _pat="$1"; _f="$2"
    valid_pattern "$_pat" "interface"
    case "$_f" in id|generate-from|generate-to|accept-from|accept-to|from|to|algorithm) ;; *) err "field password harus id|generate-from|generate-to|accept-from|accept-to|from|to|algorithm: $_f" ;; esac
    dellines "^interface $(re_esc "$_pat") pw-$_f "
    echo "Babel interface $_pat password $_f dihapus"
}

# --- getters (untuk generate) ---
get_field() { # <PAT> <FIELD> -> nilai (kolom 4)
    _re=$(re_esc "$1")
    grep "^interface $_re $2 " "$CONF" 2>/dev/null | head -1 | awk '{print $4}'
}

get_top() { # <FIELD> -> nilai (kolom 2)
    grep "^$1 " "$CONF" 2>/dev/null | head -1 | awk '{print $2}'
}

get_chan() { # <ipv4|ipv6>-<FIELD> -> nilai (kolom 2, atau kolom 3 bila filter)
    grep "^$1 " "$CONF" 2>/dev/null | head -1 | sed "s/^$1 //"
}

# bird_time <nilai> — angka polos -> "<n>s"; bersatuan dipertahankan.
# BIRD 2.20 menolak angka polos di posisi TIME (hello/update interval,
# rtt min/max: "expecting S or MS or US"). Koreksi F3.2.
bird_time() {
    case "$1" in *ms|*us|*s|*m|*h|*d) printf '%s' "$1" ;; *) printf '%ss' "$1" ;; esac
}

# date_to_bird <nilai> — pertahanan intent lama: tanggal+jam yang tersimpan
# sebelum B24 dipangkas ke tanggal saja saat emit (BIRD menolak datetime
# apa pun di password — B24 t8/t9). Cermin titian-ospf.sh/titian-rip.sh.
date_to_bird() {
    _d="${1%%T*}"; _d="${_d%% *}"; printf '%s' "$_d"
}
emit_iface_field() { # <PAT> <FIELD> <BIRD-NAME> [transform]
    _pat="$1"; _f="$2"; _bn="$3"
    _v=$(get_field "$_pat" "$_f")
    [ -n "$_v" ] || return 0
    case "$_f" in
        check-link|extended-next-hop|send-timestamps)
            case "$_v" in on) echo "        $_bn yes;" ;; off) echo "        $_bn no;" ;; esac ;;
        type|rxcost|limit|port|tx-class|tx-dscp|rx-buffer|tx-length|rtt-cost|rtt-decay)
            echo "        $_bn $_v;" ;;
        hello-interval) echo "        hello interval $(bird_time "$_v");" ;;
        update-interval) echo "        update interval $(bird_time "$_v");" ;;
        next-hop-ipv4) echo "        next hop ipv4 $_v;" ;;
        next-hop-ipv6) echo "        next hop ipv6 $_v;" ;;
        rtt-min) echo "        rtt min $(bird_time "$_v");" ;;
        rtt-max) echo "        rtt max $(bird_time "$_v");" ;;
        authentication)
            case "$_v" in
                none) echo "        authentication none;" ;;
                mac) echo "        authentication mac;" ;;
                mac-permissive) echo "        authentication mac permissive;" ;;
            esac ;;
    esac
}

emit_iface() {
    _pat="$1"
    _auth=$(get_field "$_pat" authentication)
    _pw=$(get_field "$_pat" password)
    case "$_auth" in
        mac|mac-permissive)
            [ -n "$_pw" ] || err "interface $_pat authentication $_auth tanpa password — tambah dulu password" ;;
    esac
    # B24 (17 Nov 2026, temuan live): BIRD 2.20.0 menolak password tanpa
    # authentication mac — "Authentication and password options should be
    # used together" (bird -p t13: auth none + password rc=1; uji live
    # vlan99: password tanpa auth -> commit gagal di section babel).
    # Simetris dengan guard di atas (auth tanpa password): gagal LOUD di
    # generate dengan pesan jelas, bukan error BIRD saat commit.
    case "$_auth" in
        ""|none)
            [ -z "$_pw" ] || err "interface $_pat password tanpa authentication mac — set dulu authentication mac (BIRD 2.20.0 menolak password tanpa authentication)" ;;
    esac
    if grep -q "^interface $(re_esc "$_pat") pw-" "$CONF" 2>/dev/null && [ -z "$_pw" ]; then
        err "interface $_pat punya sub-opsi password tanpa password — tambah dulu password"
    fi
    echo "    interface \"$_pat\" {"
    emit_iface_field "$_pat" type "type"
    emit_iface_field "$_pat" rxcost "rxcost"
    emit_iface_field "$_pat" limit "limit"
    emit_iface_field "$_pat" hello-interval "hello interval"
    emit_iface_field "$_pat" update-interval "update interval"
    emit_iface_field "$_pat" port "port"
    emit_iface_field "$_pat" tx-class "tx class"
    emit_iface_field "$_pat" tx-dscp "tx dscp"
    emit_iface_field "$_pat" rx-buffer "rx buffer"
    emit_iface_field "$_pat" tx-length "tx length"
    emit_iface_field "$_pat" check-link "check link"
    emit_iface_field "$_pat" next-hop-ipv4 "next hop ipv4"
    emit_iface_field "$_pat" next-hop-ipv6 "next hop ipv6"
    emit_iface_field "$_pat" extended-next-hop "extended next hop"
    emit_iface_field "$_pat" rtt-cost "rtt cost"
    emit_iface_field "$_pat" rtt-min "rtt min"
    emit_iface_field "$_pat" rtt-max "rtt max"
    emit_iface_field "$_pat" rtt-decay "rtt decay"
    emit_iface_field "$_pat" send-timestamps "send timestamps"
    emit_iface_field "$_pat" authentication "authentication"
    if [ -n "$_pw" ]; then
        _pwlines=$(grep "^interface $(re_esc "$_pat") pw-" "$CONF" 2>/dev/null)
        if [ -n "$_pwlines" ]; then
            echo "        password \"$_pw\" {"
            printf '%s\n' "$_pwlines" | awk '{f=$3; sub(/^pw-/,"",f); print f" "$4}' | while IFS= read -r _pl; do
                _pf=${_pl%% *}
                _pv=${_pl#* }
                case "$_pf" in
                    id) echo "            id $_pv;" ;;
                    generate-from) echo "            generate from \"$(date_to_bird "$_pv")\";" ;;
                    generate-to) echo "            generate to \"$(date_to_bird "$_pv")\";" ;;
                    accept-from) echo "            accept from \"$(date_to_bird "$_pv")\";" ;;
                    accept-to) echo "            accept to \"$(date_to_bird "$_pv")\";" ;;
                    from) echo "            from \"$(date_to_bird "$_pv")\";" ;;
                    to) echo "            to \"$(date_to_bird "$_pv")\";" ;;
                    algorithm) case "$_pv" in
                        hmac-sha1) _alg="hmac sha1" ;; hmac-sha256) _alg="hmac sha256" ;;
                        hmac-sha384) _alg="hmac sha384" ;; hmac-sha512) _alg="hmac sha512" ;;
                        *) _alg="$_pv" ;; esac
                        echo "            algorithm $_alg;" ;;
                esac
            done
            echo "        };"
        else
            echo "        password \"$_pw\";"
        fi
    fi
    echo "    };"
}

emit_chan() { # <ipv4|ipv6> [sadr]
    _c="$1"
    _tab=$(get_chan "$_c-table")
    _imp=$(get_chan "$_c-import")
    _exp=$(get_chan "$_c-export")
    if [ -z "$_tab" ] && [ -z "$_imp" ] && [ -z "$_exp" ]; then
        return 0
    fi
    if [ "$_c" = "ipv6" ] && [ "$(get_top ipv6-sadr)" = "on" ]; then
        # ipv6 sadr channel WAJIB pakai tabel ipv6-sadr (master6 / tabel
        # ipv6 biasa DITOLAK BIRD: "Incompatible table type").
        if [ -n "$_tab" ]; then
            _is_sadr=0
            [ -f "$GLOBAL_CONF" ] && grep -q "^table ipv6-sadr $_tab\$" "$GLOBAL_CONF" 2>/dev/null && _is_sadr=1
            [ "$_is_sadr" = "0" ] && err "Babel ipv6-sadr on tapi tabel channel ipv6 = $_tab (bukan tabel ipv6-sadr) — BIRD menolak (Incompatible table type); buat tabel ipv6-sadr dulu (global -> table-add ipv6-sadr <nama>) lalu chan-set ipv6 table <nama>"
        fi
        echo "    ipv6 sadr {"
    else
        echo "    $_c {"
    fi
    [ -n "$_tab" ] && echo "        table $_tab;"
    [ -n "$_imp" ] && echo "        import $_imp;"
    [ -n "$_exp" ] && echo "        export $_exp;"
    echo "    };"
}

cmd_generate() {
    touch_conf
    set -f
    mkdir -p "$SECTION_DIR" 2>/dev/null || die "cannot mkdir $SECTION_DIR"
    _tmp="$SECTION.tmp.$$"
    if has_facts; then
        _dbg=$(get_top debug)
        _mrt=$(get_top mrtdump)
        _rrid=$(get_top randomize-router-id)
        {
            echo "# babel.conf - generated by titian-babel.sh, do not edit by hand"
            echo "protocol babel {"
            if [ -n "$_dbg" ]; then
                case "$_dbg" in all|off) echo "    debug $_dbg;" ;; *) echo "    debug { $(echo "$_dbg" | sed 's/,/, /g') };" ;; esac
            fi
            if [ -n "$_mrt" ]; then
                case "$_mrt" in all|off) echo "    mrtdump $_mrt;" ;; *) echo "    mrtdump { $(echo "$_mrt" | sed 's/,/, /g') };" ;; esac
            fi
            case "$_rrid" in
                on) echo "    randomize router id yes;" ;;
                off) echo "    randomize router id no;" ;;
            esac
            for _pat in $(grep '^interface ' "$CONF" 2>/dev/null | awk '{print $2}' | awk '!s[$0]++'); do
                emit_iface "$_pat"
            done
            emit_chan ipv4
            emit_chan ipv6
            echo "}"
            echo ""
        } > "$_tmp" || die "cannot write $_tmp"
    else
        {
            echo "# babel.conf - generated by titian-babel.sh, do not edit by hand"
            echo "# (tidak ada config Babel — protocol babel tidak dibuat)"
        } > "$_tmp" || die "cannot write $_tmp"
    fi
    mv "$_tmp" "$SECTION" || die "cannot write $SECTION"
    chmod 644 "$SECTION" 2>/dev/null || true
    set +f
    echo "Babel section ditulis: $SECTION"
    _birdsh="$(dirname "$0")/titian-bird.sh"
    if [ -x "$_birdsh" ]; then
        "$_birdsh" generate babel || exit 33
    else
        echo "Warning: $_birdsh tidak ditemukan; section hanya ditulis, belum di-apply" >&2
    fi
}

birdc_bin() {
    command -v birdc 2>/dev/null || { [ -x /usr/sbin/birdc ] && echo /usr/sbin/birdc; } || \
        { [ -x /usr/local/sbin/birdc ] && echo /usr/local/sbin/birdc; } || echo birdc
}
# birdc_sock — salinan titian-birdc.sh (BC8, B13): cetak "-s <path>" bila
# socket utama dikonfigurasi via klish ($STATE_ROOT/birdc.conf), kosong bila
# default. Dipakai semua pemanggilan birdc di file ini.
birdc_sock() {
    _s=$(grep '^socket ' "$STATE_ROOT/birdc.conf" 2>/dev/null | head -1 | cut -d' ' -f2-)
    [ -n "$_s" ] && printf '%s' "-s $_s"
}


cmd_show() {
    touch_conf
    echo "--- babel.conf (intent) ---"
    cat "$CONF"
    echo "--- bird.d/babel.conf (section, bila ada) ---"
    [ -f "$SECTION" ] && cat "$SECTION" || echo "(belum di-generate)"
    echo "--- birdc show protocol (babel; TIDAK ADA show babel khusus — via show protocols) ---"
    _birdc=$(birdc_bin)
    if _out=$("$_birdc" $(birdc_sock) show protocol babel 2>&1); then
        echo "$_out" | grep -v '^BIRD'
    else
        echo "(BIRD tidak jalan / protocol babel belum ada — birdc show protocol babel gagal)"
    fi
    return 0
}

