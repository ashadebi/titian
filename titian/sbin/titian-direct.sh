#!/bin/sh
# titian-direct.sh — Direct routes intent (BIRD `protocol direct`) untuk Titian/klish.
# Pola sama seperti titian-bfd.sh: intent di /etc/titian/direct.conf
# (tmpfs, dipersistenkan via titian-cfg.sh), generate menulis section
# BIRD /etc/titian/bird.d/direct.conf lalu memanggil titian-bird.sh
# generate direct (render + validasi + birdc). Section ditulis ulang
# UTUH tiap apply.
#
# Sintaks BIRD 2.16.1 yang dipakai (docs resmi bird.network,
# User's Guide 2.16.1, §6.7 Direct):
#   protocol direct {
#       ipv4;
#       ipv6;
#       ipv6 sadr;
#       interface "-arc*", "*";
#       check link;
#   }
# Direct membuat device route untuk semua jaringan directly-connected
# (dari daftar interface kernel via Device). Channel IPv4 + IPv6 bisa
# simultan; `ipv6 sadr` sebagai ganti IPv6 reguler (untuk Babel SADR —
# SADR TIDAK diimplementasi di batch ini, opsi hanya dicatat sebagai
# channel; pemakaian nyata butuh Babel).
# Default BIRD: check link no; tanpa `interface` = semua interface.
# Default klish bila belum ada channel yang diset: `ipv4;` saja — SAMA
# seperti perilaku lama `redistribute direct enable` (titian-redist.sh)
# yang menulis `protocol direct direct1 { interface ...; ipv4; }`.
# (Instance kini tanpa nama, sesuai contoh docs; `direct1` hanya nama
# lama dari redist — tidak ada yang bergantung padanya selain grep
# "protocol direct" di titian-redist.sh.)
#
# PERHATIAN: kernel OS biasanya sudah menangani device route sendiri,
# jadi ekspor route Direct ke Kernel umumnya TIDAK diinginkan; OSPF
# membuat device route interfacenya sendiri; Direct diperlukan agar
# protokol distance-vector (RIP/Babel) bisa mengumumkan jaringan lokal.
#
# Format direct.conf (satu baris per fakta):
#   interface <pattern>        (boleh banyak; pola dukung `*`, `?`,
#                               pengecualian `-pattern`, mis. `-arc*`)
#   check-link on|off
#   channel ipv4|ipv6|ipv6-sadr
#
# Interaksi dengan titian-redist.sh: `redistribute direct enable
# [iface]` kini mendaftarkan interface-nya ke intent ini
# (interface-add) lalu generate; `redistribute direct disable`
# mengosongkan intent (clear). bird.d/direct.conf TANPA intent yang
# menyertainya (keadaan lama pra-B4) TIDAK ditimpa oleh commit —
# apply_direct hanya jalan bila direct.conf ada.

STATE_ROOT="${TITIAN_STATE_ROOT:-/etc/titian}"
CONF="$STATE_ROOT/direct.conf"
SECTION_DIR="$STATE_ROOT/bird.d"
SECTION="$SECTION_DIR/direct.conf"
PROG="titian-direct"
err() { echo "Error($PROG): $*" >&2; exit 33; }
die() { echo "$PROG: $*" >&2; exit 1; }

touch_conf() {
    if [ ! -f "$CONF" ]; then
        mkdir -p "$(dirname "$CONF")" 2>/dev/null
        printf '# direct.conf - generated by klish, do not edit by hand\n' > "$CONF" \
            || die "cannot create $CONF"
        chmod 600 "$CONF" 2>/dev/null || true
    fi
}

# re_esc <teks> — escape karakter regex (pola interface boleh
# mengandung `*`, mis. "ge*") agar grep -v tidak salah hapus.
re_esc() {
    printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/\./\\./g' -e 's/\*/\\*/g' \
        -e 's/\[/\\[/g' -e 's/\]/\\]/g' -e 's/\^/\\^/g' -e 's/\$/\\$/g'
}

# upsert <regex-untuk-hapus> <baris-baru>
upsert() {
    _re="$1"; _line="$2"
    touch_conf
    _tmp="$CONF.tmp.$$"
    grep -v "$_re" "$CONF" > "$_tmp" 2>/dev/null || true
    printf '%s\n' "$_line" >> "$_tmp"
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
    chmod 600 "$CONF" 2>/dev/null || true
}

dellines() {
    _re="$1"
    touch_conf
    _tmp="$CONF.tmp.$$"
    grep -v "$_re" "$CONF" > "$_tmp" 2>/dev/null || true
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
}

has_facts() {
    [ -f "$CONF" ] || return 1
    grep -v '^[[:space:]]*#' "$CONF" 2>/dev/null | grep -q '[^[:space:]]'
}

cmd_direct_touch() {
    touch_conf
    echo "Direct"
}

cmd_interface_add() {
    _pat="$1"
    [ -n "$_pat" ] || err "interface-add butuh pola interface (mis. ge* atau bridge0)"
    case "$_pat" in *' '*) err "pola interface tidak boleh mengandung spasi: $_pat" ;; esac
    touch_conf
    # Default channel: bila belum ada channel apa pun, catat ipv4
    # (perilaku lama redist direct enable). Setelah itu channel
    # eksplisit berlaku apa adanya; `no ipv4` benar-benar mematikan ipv4.
    grep -q '^channel ' "$CONF" 2>/dev/null || \
        printf 'channel ipv4\n' >> "$CONF"
    # Idempotent: pola yang sama sudah ada -> tidak duplikat.
    if grep -q "^interface $(re_esc "$_pat")\$" "$CONF" 2>/dev/null; then
        echo "Direct interface $_pat sudah ada"
        return 0
    fi
    printf 'interface %s\n' "$_pat" >> "$CONF"
    echo "Direct interface $_pat"
}

cmd_interface_del() {
    _pat="$1"
    [ -n "$_pat" ] || err "interface-del butuh pola interface"
    _re=$(re_esc "$_pat")
    dellines "^interface $_re\$"
    echo "Direct interface $_pat dihapus"
}

cmd_check_link_set() {
    case "$1" in
        on|off) upsert '^check-link ' "check-link $1" ;;
        *) err "check-link harus on|off: $1" ;;
    esac
    echo "Direct check-link = $1"
}

cmd_channel_add() {
    case "$1" in
        ipv4|ipv6|ipv6-sadr) ;;
        *) err "channel harus ipv4|ipv6|ipv6-sadr: $1" ;;
    esac
    if [ "$1" = "ipv6-sadr" ] && grep -q '^channel ipv6$' "$CONF" 2>/dev/null; then
        err "ipv6-sadr tidak bisa bersama channel ipv6 (SADR menggantikan IPv6 reguler)"
    fi
    if [ "$1" = "ipv6" ] && grep -q '^channel ipv6-sadr$' "$CONF" 2>/dev/null; then
        err "ipv6 tidak bisa bersama channel ipv6-sadr (SADR menggantikan IPv6 reguler)"
    fi
    upsert "^channel $1\$" "channel $1"
    echo "Direct channel $1"
}

cmd_channel_del() {
    case "$1" in
        ipv4|ipv6|ipv6-sadr) ;;
        *) err "channel harus ipv4|ipv6|ipv6-sadr: $1" ;;
    esac
    dellines "^channel $1\$"
    echo "Direct channel $1 dihapus"
}

cmd_clear() {
    # Kosongkan SEMUA fakta direct (dipakai `redistribute direct disable`).
    touch_conf
    _tmp="$CONF.tmp.$$"
    grep -v '^[[:space:]]*#' "$CONF" 2>/dev/null | grep -q '[^[:space:]]' || true
    printf '# direct.conf - generated by klish, do not edit by hand\n' > "$_tmp"
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
    chmod 600 "$CONF" 2>/dev/null || true
    echo "Direct config dikosongkan"
}

# valid_spec <SPEC> <debug|mrtdump> — validasi daftar kelas koma (Bab 3.4-2/3,
# salinan _rip_valid_spec; B9).
valid_spec() {
    _vs_spec="$1"; _vs_kind="$2"
    [ -n "$_vs_spec" ] || err "$_vs_kind butuh all|off|kelas,kelas,..."
    case "$_vs_spec" in all|off) return 0 ;; esac
    _vs_rest="$_vs_spec"
    while [ -n "$_vs_rest" ]; do
        case "$_vs_rest" in *,*) _vs_done=${_vs_rest%%,*}; _vs_rest=${_vs_rest#*,} ;; *) _vs_done="$_vs_rest"; _vs_rest="" ;; esac
        if [ "$_vs_kind" = "debug" ]; then
            case "$_vs_done" in states|routes|filters|interfaces|events|packets) ;; *) err "debug kelas tidak dikenal: $_vs_done (boleh: states|routes|filters|interfaces|events|packets)" ;; esac
        else
            case "$_vs_done" in states|messages) ;; *) err "mrtdump kelas tidak dikenal: $_vs_done (boleh: states|messages)" ;; esac
        fi
    done
}
# emit_dbg <SPEC> <debug|mrtdump> — satu baris debug/mrtdump (indent 4 spasi).
emit_dbg() {
    case "$1" in all|off) echo "    $2 $1;" ;; *) echo "    $2 { $(printf '%s' "$1" | sed 's/,/, /g') };" ;; esac
}

cmd_debug_set() { # B9: debug-set SPEC (Bab 3.4-2)
    [ -n "$1" ] || err "debug butuh all|off|kelas,kelas,..."
    valid_spec "$1" debug
    upsert '^debug ' "debug $1"
    echo "Direct debug = $1"
}
cmd_debug_del() {
    dellines '^debug '
    echo "Direct debug dihapus (default BIRD off)"
}
cmd_mrtdump_set() { # B9: mrtdump-set SPEC (Bab 3.4-3)
    [ -n "$1" ] || err "mrtdump butuh all|off|states,messages"
    valid_spec "$1" mrtdump
    upsert '^mrtdump ' "mrtdump $1"
    echo "Direct mrtdump = $1"
}
cmd_mrtdump_del() {
    dellines '^mrtdump '
    echo "Direct mrtdump dihapus (default BIRD off)"
}

cmd_generate() {
    touch_conf
    set -f
    mkdir -p "$SECTION_DIR" 2>/dev/null || die "cannot mkdir $SECTION_DIR"
    _tmp="$SECTION.tmp.$$"
    if has_facts; then
        {
            echo "# direct.conf - generated by titian-direct.sh, do not edit by hand"
            echo "protocol direct {"
            _dbg=$(grep '^debug ' "$CONF" 2>/dev/null | head -1 | awk '{print $2}')
            _mrt=$(grep '^mrtdump ' "$CONF" 2>/dev/null | head -1 | awk '{print $2}')
            [ -n "$_dbg" ] && emit_dbg "$_dbg" debug
            [ -n "$_mrt" ] && emit_dbg "$_mrt" mrtdump
            grep -q '^channel ipv4$' "$CONF" 2>/dev/null && echo "    ipv4;"
            grep -q '^channel ipv6$' "$CONF" 2>/dev/null && echo "    ipv6;"
            grep -q '^channel ipv6-sadr$' "$CONF" 2>/dev/null && echo "    ipv6 sadr;"
            _ifs=$(grep '^interface ' "$CONF" 2>/dev/null | awk '{print $2}')
            if [ -n "$_ifs" ]; then
                _list=""
                for _p in $_ifs; do
                    if [ -z "$_list" ]; then _list="\"$_p\""; else _list="$_list, \"$_p\""; fi
                done
                echo "    interface $_list;"
            fi
            [ "$(grep '^check-link ' "$CONF" 2>/dev/null | head -1 | awk '{print $2}')" = "on" ] && \
                echo "    check link;"
            echo "}"
        } > "$_tmp" || die "cannot write $_tmp"
    else
        {
            echo "# direct.conf - generated by titian-direct.sh, do not edit by hand"
            echo "# (tidak ada config direct — protocol direct tidak dibuat)"
        } > "$_tmp" || die "cannot write $_tmp"
    fi
    mv "$_tmp" "$SECTION" || die "cannot write $SECTION"
    chmod 644 "$SECTION" 2>/dev/null || true
    set +f
    echo "Direct section ditulis: $SECTION"
    _birdsh="$(dirname "$0")/titian-bird.sh"
    if [ -x "$_birdsh" ]; then
        "$_birdsh" generate direct || exit 33
    else
        echo "Warning: $_birdsh tidak ditemukan; section hanya ditulis, belum di-apply" >&2
    fi
}

birdc_bin() {
    command -v birdc 2>/dev/null || { [ -x /usr/sbin/birdc ] && echo /usr/sbin/birdc; } || \
        { [ -x /usr/local/sbin/birdc ] && echo /usr/local/sbin/birdc; } || echo birdc
}

cmd_show() {
    touch_conf
    echo "--- direct.conf (intent) ---"
    cat "$CONF"
    echo "--- bird.d/direct.conf (section, bila ada) ---"
    [ -f "$SECTION" ] && cat "$SECTION" || echo "(belum di-generate)"
    echo "--- birdc show protocol direct ---"
    _birdc=$(birdc_bin)
    if _out=$("$_birdc" show protocol direct 2>&1); then
        echo "$_out" | grep -v '^BIRD'
    else
        echo "(BIRD tidak jalan / protocol direct belum ada — birdc show protocol direct gagal)"
    fi
}

case "$1" in
    direct-touch) cmd_direct_touch ;;
    has-facts) has_facts ;;
    interface-add) shift; cmd_interface_add "$@" ;;
    interface-del) shift; cmd_interface_del "$@" ;;
    check-link-set) shift; cmd_check_link_set "$@" ;;
    channel-add) shift; cmd_channel_add "$@" ;;
    channel-del) shift; cmd_channel_del "$@" ;;
    clear) cmd_clear ;;
    debug-set) shift; cmd_debug_set "$@" ;;
    debug-del) cmd_debug_del ;;
    mrtdump-set) shift; cmd_mrtdump_set "$@" ;;
    mrtdump-del) cmd_mrtdump_del ;;
    generate) cmd_generate ;;
    show) cmd_show ;;
    *) echo "Usage: $0 {direct-touch|has-facts|interface-add PATTERN|interface-del PATTERN|check-link-set on|off|debug-set SPEC|debug-del|mrtdump-set SPEC|mrtdump-del|channel-add ipv4|ipv6|ipv6-sadr|channel-del ipv4|ipv6|ipv6-sadr|clear|generate|show}" >&2; exit 2 ;;
esac
