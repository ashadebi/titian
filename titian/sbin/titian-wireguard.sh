#!/bin/sh
# TITIAN BSDRP — WireGuard native (if_wg).
# State klish: $ROOT/etc/netstate/wireguard/<nama>.conf (satu baris
# per item); private key: $ROOT/etc/wireguard/<nama>.key (mode 600,
# TIDAK PERNAH dicetak ulang — generate-key hanya menampilkan public
# key sekali).
# Format state:
#   enable yes|no
#   address <cidr>
#   listen-port <n>
#   public-key <base64>
#   peer <pubkey> allowed-ips <cidr|-> endpoint <host:port|-> keepalive <n>
# `enable`/perubahan peer hanya mencatat niat + dirty; interface
# dibuat + peer dipasang saat `commit` (apply-all di sini) atau boot
# (titian-boot.sh -> apply-all).
# Sintaks ifconfig wg (wgkey/wgport/wgpeer/wgaip/wgendpoint/wgpka)
# ditulis dari dokumentasi FreeBSD if_wg/ifconfig — verifikasi live
# di guest wajib sebelum produksi.
# POSIX sh.
ROOT=${TITIAN_ROOT:-/opt/titian}
STATE_DIR="$ROOT/etc/netstate/wireguard"
KEY_DIR="$ROOT/etc/wireguard"
DIRTY=/var/run/wireguard.dirty
PROG="titian-wireguard"
err() { echo "Error($PROG): $*" >&2; exit 33; }
die() { echo "$PROG: $*" >&2; exit 1; }

state_file() { printf '%s/%s.conf' "$STATE_DIR" "$1"; }

valid_wg() {
    case "$1" in wg[0-9]) ;; wg[0-9][0-9]) ;; *) die "nama interface WireGuard harus wg<N>: $1" ;; esac
}

touch_state() {
    valid_wg "$1"
    mkdir -p "$STATE_DIR" 2>/dev/null || die "cannot mkdir $STATE_DIR"
    _f=$(state_file "$1")
    if [ ! -f "$_f" ]; then
        printf '# wireguard %s - generated by klish, do not edit by hand\nenable no\n' "$1" > "$_f" \
            || die "cannot create $_f"
    fi
}

mark_dirty() { touch "$DIRTY" 2>/dev/null || true; }

upsert() {
    # $1=iface $2=regex $3=line
    touch_state "$1"
    _f=$(state_file "$1"); _tmp="$_f.tmp.$$"
    grep -v "$2" "$_f" > "$_tmp" 2>/dev/null || true
    printf '%s\n' "$3" >> "$_tmp"
    mv "$_tmp" "$_f" || die "cannot write $_f"
    mark_dirty
}

dellines() {
    # $1=iface $2=regex $3=what
    touch_state "$1"
    _f=$(state_file "$1")
    grep -q "$2" "$_f" 2>/dev/null || die "$3 not found"
    _tmp="$_f.tmp.$$"
    grep -v "$2" "$_f" > "$_tmp" || true
    mv "$_tmp" "$_f" || die "cannot write $_f"
    mark_dirty
}

valid_v4_cidr() {
    case "$1" in */*) ;; *) return 1 ;; esac
    _ip=${1%%/*}; _n=${1##*/}
    case "$_n" in ''|*[!0-9]*) return 1 ;; esac
    [ "$_n" -ge 0 ] 2>/dev/null && [ "$_n" -le 32 ] 2>/dev/null || return 1
    _a="$_ip"
    case "$_a" in *.*.*.*) ;; *) return 1 ;; esac
    _o1=${_a%%.*}; _r=${_a#*.}; _o2=${_r%%.*}; _r=${_r#*.}; _o3=${_r%%.*}; _o4=${_r#*.}
    case "$_o4" in *.*) return 1 ;; esac
    for _o in "$_o1" "$_o2" "$_o3" "$_o4"; do
        case "$_o" in ''|*[!0-9]*) return 1 ;; esac
        [ "$_o" -ge 0 ] 2>/dev/null && [ "$_o" -le 255 ] 2>/dev/null || return 1
    done
    return 0
}

# --- read-only ---
cmd_check() { touch_state "${1:-wg0}"; exit 0; }

cmd_show() {
    _any=0
    for _f in "$STATE_DIR"/wg*.conf; do
        [ -f "$_f" ] || continue
        _any=1
        _n=$(basename "$_f" .conf)
        _en=$(sed -n 's/^enable //p' "$_f" | head -1)
        _addr=$(sed -n 's/^address //p' "$_f" | head -1)
        _port=$(sed -n 's/^listen-port //p' "$_f" | head -1)
        _peers=$(grep -c '^peer ' "$_f" 2>/dev/null || echo 0)
        if ifconfig "$_n" >/dev/null 2>&1; then _live="up (interface ada)"; else _live="down (interface belum dibuat)"; fi
        echo "$_n: ${_en:-no}, addr ${_addr:-unset}, port ${_port:-51820}, peers $_peers, $_live"
    done
    [ "$_any" = "1" ] || echo "(no WireGuard interfaces configured)"
    if command -v wg >/dev/null 2>&1; then
        echo "-- wg show:"
        wg show 2>&1 | sed 's/^/  /'
    fi
    exit 0
}

cmd_show_one() {
    touch_state "$1"
    _f=$(state_file "$1")
    cat "$_f" | grep -v '^public-key' | sed 's/^/  /'
    echo "-- live:"
    if command -v wg >/dev/null 2>&1; then wg show "$1" 2>&1 | sed 's/^/  /'
    elif ifconfig "$1" >/dev/null 2>&1; then ifconfig "$1" 2>&1 | sed 's/^/  /'
    else echo "  (interface $1 belum dibuat / wg tidak ada)"; fi
    exit 0
}

# --- mutations ---
cmd_set_enable() {
    case "$2" in yes|no) upsert "$1" '^enable ' "enable $2" ;; *) die "enable takes yes|no" ;; esac
    echo "wireguard $1 $2 (pending commit)"
    exit 0
}

cmd_set_address() {
    valid_v4_cidr "$2" || die "address harus CIDR IPv4: $2"
    upsert "$1" '^address ' "address $2"
    echo "wireguard $1 address $2 (pending commit)"
    exit 0
}

cmd_del_address() { dellines "$1" '^address ' "address"; echo "wireguard $1 address dihapus"; exit 0; }

cmd_set_listen_port() {
    case "$2" in ''|*[!0-9]*) die "port harus 1-65535: $2" ;; esac
    [ "$2" -ge 1 ] 2>/dev/null && [ "$2" -le 65535 ] 2>/dev/null || die "port harus 1-65535: $2"
    upsert "$1" '^listen-port ' "listen-port $2"
    echo "wireguard $1 listen-port $2 (pending commit)"
    exit 0
}

cmd_del_listen_port() { dellines "$1" '^listen-port ' "listen-port"; echo "wireguard $1 listen-port dihapus (default 51820)"; exit 0; }

cmd_generate_key() {
    touch_state "$1"
    command -v wg >/dev/null 2>&1 || die "wg tidak ditemukan (WireGuard belum terpasang?)"
    mkdir -p "$KEY_DIR" 2>/dev/null || die "cannot mkdir $KEY_DIR"
    _priv=$(wg genkey 2>/dev/null) || die "wg genkey gagal"
    _pub=$(printf '%s' "$_priv" | wg pubkey 2>/dev/null) || die "wg pubkey gagal"
    umask 077
    printf '%s\n' "$_priv" > "$KEY_DIR/$1.key" || die "cannot write key"
    chmod 600 "$KEY_DIR/$1.key" 2>/dev/null || true
    upsert "$1" '^public-key ' "public-key $_pub"
    echo "wireguard $1: keypair baru dibuat (private key tersimpan mode 600, tidak ditampilkan)"
    echo "public key: $_pub"
    exit 0
}

peer_exists() { grep -q "^peer $2 " "$(state_file "$1")" 2>/dev/null; }

cmd_peer_add() {
    touch_state "$1"
    case "$2" in ''|*' '*) die "public key tidak valid" ;; esac
    peer_exists "$1" "$2" && { echo "wireguard $1 peer sudah ada"; exit 0; }
    printf 'peer %s allowed-ips - endpoint - keepalive 0\n' "$2" >> "$(state_file "$1")" \
        || die "cannot write state"
    mark_dirty
    echo "wireguard $1 peer ditambah (pending commit — set allowed-ips dulu)"
    exit 0
}

cmd_peer_del() {
    dellines "$1" "^peer $2 " "peer $2"
    echo "wireguard $1 peer dihapus"
    exit 0
}

cmd_peer_set() {
    # $1=iface $2=pubkey $3=field $4=value — simpan dulu sebelum set --
    _if="$1"; _pub="$2"; _field="$3"; _val="$4"
    touch_state "$_if"
    peer_exists "$_if" "$_pub" || die "peer $_pub tidak ada di $_if"
    _line=$(grep "^peer $_pub " "$(state_file "$_if")" | head -1)
    set -- $_line
    # $1=peer $2=pubkey $3=allowed-ips $4=aip $5=endpoint $6=ep $7=keepalive $8=n
    _aip="$4"; _ep="$6"; _ka="$8"
    case "$_field" in
        allowed-ips)
            valid_v4_cidr "$_val" || die "allowed-ips harus CIDR IPv4: $_val"
            _aip="$_val" ;;
        endpoint)
            case "$_val" in *:* ) ;; *) die "endpoint harus host:port: $_val" ;; esac
            _ep="$_val" ;;
        keepalive)
            case "$_val" in ''|*[!0-9]*) die "keepalive harus detik (angka): $_val" ;; esac
            _ka="$_val" ;;
        *) die "field tidak dikenal: $_field (allowed-ips|endpoint|keepalive)" ;;
    esac
    upsert "$_if" "^peer $_pub " "peer $_pub allowed-ips $_aip endpoint $_ep keepalive $_ka"
    echo "wireguard $_if peer $_pub: $_field = $_val"
    exit 0
}

cmd_peer_del_field() {
    # $1=iface $2=pubkey $3=field — simpan dulu sebelum set --
    _if="$1"; _pub="$2"; _field="$3"
    touch_state "$_if"
    peer_exists "$_if" "$_pub" || die "peer $_pub tidak ada di $_if"
    _line=$(grep "^peer $_pub " "$(state_file "$_if")" | head -1)
    set -- $_line
    _aip="$4"; _ep="$6"; _ka="$8"
    case "$_field" in
        allowed-ips) _aip="-" ;;
        endpoint) _ep="-" ;;
        keepalive) _ka="0" ;;
        *) die "field tidak dikenal: $_field" ;;
    esac
    upsert "$_if" "^peer $_pub " "peer $_pub allowed-ips $_aip endpoint $_ep keepalive $_ka"
    echo "wireguard $_if peer $_pub: $_field dihapus"
    exit 0
}

cmd_del_iface() {
    valid_wg "$1"
    _f=$(state_file "$1")
    [ -f "$_f" ] || { echo "wireguard $1 tidak ada"; exit 0; }
    rm -f "$_f" "$KEY_DIR/$1.key"
    if ifconfig "$1" >/dev/null 2>&1; then ifconfig "$1" destroy 2>/dev/null || true; fi
    mark_dirty
    echo "wireguard $1 dihapus (config + key + interface)"
    exit 0
}

# --- apply ---
apply_one() {
    # $1 = nama iface; buat + konfigurasi dari state. Idempotent.
    _n="$1"; _f=$(state_file "$_n")
    [ -f "$_f" ] || return 0
    _en=$(sed -n 's/^enable //p' "$_f" | head -1)
    if [ "$_en" != "yes" ]; then
        ifconfig "$_n" >/dev/null 2>&1 && ifconfig "$_n" destroy 2>/dev/null || true
        echo "wireguard $_n: disabled (interface dihancurkan bila ada)"
        return 0
    fi
    _addr=$(sed -n 's/^address //p' "$_f" | head -1)
    _port=$(sed -n 's/^listen-port //p' "$_f" | head -1)
    _keyf="$KEY_DIR/$_n.key"
    [ -f "$_keyf" ] || die "wireguard $_n enable tapi belum punya key (generate-key dulu)"
    _priv=$(cat "$_keyf")
    if ! ifconfig "$_n" >/dev/null 2>&1; then
        ifconfig "$_n" create || die "ifconfig $_n create gagal"
    fi
    ifconfig "$_n" wgkey "$_priv" || die "ifconfig $_n wgkey gagal"
    if [ -n "$_port" ]; then ifconfig "$_n" wgport "$_port" || die "ifconfig $_n wgport gagal"; fi
    if [ -n "$_addr" ]; then ifconfig "$_n" inet "$_addr" alias || die "ifconfig $_n inet gagal"; fi
    grep '^peer ' "$_f" 2>/dev/null | while read -r _p _pub _a _aip _e _ep _k _ka; do
        _args="wgpeer $_pub"
        [ "$_aip" != "-" ] && _args="$_args wgaip $_aip"
        [ "$_ep" != "-" ] && _args="$_args wgendpoint $_ep"
        [ "$_ka" != "0" ] && [ -n "$_ka" ] && _args="$_args wgpka $_ka"
        # shellcheck disable=SC2086 (word-splitting disengaja)
        ifconfig "$_n" $_args || echo "wireguard $_n: peer $_pub gagal dipasang" >&2
    done
    echo "wireguard $_n: applied (addr ${_addr:-unset}, port ${_port:-51820})"
    return 0
}

cmd_apply_all() {
    _any=0
    for _f in "$STATE_DIR"/wg*.conf; do
        [ -f "$_f" ] || continue
        _any=1
        apply_one "$(basename "$_f" .conf)" || exit 33
    done
    [ "$_any" = "1" ] || echo "wireguard: tidak ada interface terkonfigurasi"
    rm -f "$DIRTY"
    exit 0
}

case "${1:-}" in
    check) cmd_check "${2:-wg0}" ;;
    show) cmd_show ;;
    show-one) cmd_show_one "${2:-}" ;;
    set-enable) cmd_set_enable "${2:-}" "${3:-}" ;;
    set-address) cmd_set_address "${2:-}" "${3:-}" ;;
    del-address) cmd_del_address "${2:-}" ;;
    set-listen-port) cmd_set_listen_port "${2:-}" "${3:-}" ;;
    del-listen-port) cmd_del_listen_port "${2:-}" ;;
    generate-key) cmd_generate_key "${2:-}" ;;
    peer-add) cmd_peer_add "${2:-}" "${3:-}" ;;
    peer-del) cmd_peer_del "${2:-}" "${3:-}" ;;
    peer-set) cmd_peer_set "${2:-}" "${3:-}" "${4:-}" "${5:-}" ;;
    peer-del-field) cmd_peer_del_field "${2:-}" "${3:-}" "${4:-}" ;;
    del-iface) cmd_del_iface "${2:-}" ;;
    apply-all) cmd_apply_all ;;
    *) echo "Usage: $0 {check|show|show-one|set-enable|set-address|del-address|set-listen-port|del-listen-port|generate-key|peer-add|peer-del|peer-set|peer-del-field|del-iface|apply-all} ..." >&2; exit 2 ;;
esac
