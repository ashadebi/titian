# function_vars <NAMA> -> "nama:tipe ..." (param + var lokal + var for)
function_vars() {
    grep "^function $1 param " "$INTENT" 2>/dev/null | awk '{printf "%s:%s ", $5, $4}'
    grep "^function $1 " "$INTENT" 2>/dev/null | awk '$3 == "var" {printf "%s:%s ", $5, $4} $3 == "var-set" {printf "%s:%s ", $5, $4} $3 == "for-block" {printf "%s:%s ", $5, $4}'
}
valid_fn_type() { # valid_fn_type <TIPE> <label> — tipe fungsi/param/return
    case "$1" in int|bool|pair|ip|prefix|string|bgppath|clist|eclist|lclist) ;; *) err "$2 tipe harus int|bool|pair|ip|prefix|string|bgppath|clist|eclist|lclist: $1" ;; esac
}
valid_return_expr() { # valid_return_expr <EKSPRESI> <VARLIST>
    _e="$1"; _vl="$2"
    case "$_e" in
        true|false) return 0 ;;
        '('*','*')') valid_var_value pair "$_e" "return"; return 0 ;;
    esac
    case "$_e" in ''|*[!0-9]*) ;; *) valid_u32 "$_e" "return"; return 0 ;; esac
    var_type "$_vl" "$_e" >/dev/null && return 0
    cond_to_bird "$_e" "$_vl" >/dev/null || exit 33
    return 0
}
return_to_bird() { # return_to_bird <EKSPRESI> <VARLIST> -> ekspresi BIRD
    _e="$1"; _vl="$2"
    case "$_e" in
        true|false) printf '%s' "$_e"; return 0 ;;
        '('*','*')')
            _pa=${_e#(}; _pa=${_pa%)}
            printf '(%s, %s)' "${_pa%%,*}" "${_pa#*,}"; return 0 ;;
    esac
    case "$_e" in ''|*[!0-9]*) ;; *) printf '%s' "$_e"; return 0 ;; esac
    if var_type "$_vl" "$_e" >/dev/null; then printf '%s' "$_e"; return 0; fi
    cond_to_bird "$_e" "$_vl"
}

