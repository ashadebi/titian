                        _Lckind=${_Lck%%:*}; _Lcexpr=${_Lck#*:}
                        printf '%scase %s {\n' "$_Lpad" "$_Lcexpr"
                        _Lstack="${_Lstack:+$_Lstack }case:$_Lckind:0"; _Lpad="$_Lpad    "; _Ldepth=$((_Ldepth + 1))
                        ;;
                    when)
                        _Ltop=${_Lstack##* }
                        case "$_Ltop" in 'case:'*':0'|'case:'*':1') _Lkind=${_Ltop#case:}; _Lkind=${_Lkind%:*} ;; *) err "fungsi $_Lfn when tanpa case-block yang terbuka (atas stack: ${_Lstack:-kosong})" ;; esac
                        _Llb=${_Lv%% *}; _Lst=${_Lv#* }
                        valid_case_label "$_Lkind" "$_Llb"
                        _Lbs=$(stmt_to_bird "$_Lst" "$_Lvars") || exit 33
                        case "$_Lstack" in *' '*) _Ls=${_Lstack% *} ;; *) _Ls="" ;; esac
                        _Lstack="${_Ls:+$_Ls }case:$_Lkind:1"
                        printf '%s%s: %s;\n' "$_Lpad" "$_Llb" "$_Lbs"
                        ;;
                    otherwise)
                        _Ltop=${_Lstack##* }
                        case "$_Ltop" in 'case:'*':0'|'case:'*':1') _Lkind=${_Ltop#case:}; _Lkind=${_Lkind%:*} ;; *) err "fungsi $_Lfn otherwise tanpa case-block yang terbuka (atas stack: ${_Lstack:-kosong})" ;; esac
                        _Lbs=$(stmt_to_bird "$_Lv" "$_Lvars") || exit 33
                        case "$_Lstack" in *' '*) _Ls=${_Lstack% *} ;; *) _Ls="" ;; esac
                        _Lstack="${_Ls:+$_Ls }case:$_Lkind:1"
                        printf '%selse: %s;\n' "$_Lpad" "$_Lbs"
                        ;;
                    close-block)
                        [ -n "$_Lstack" ] || err "fungsi $_Lfn close-block tanpa blok yang terbuka"
                        _Ltop=${_Lstack##* }
                        case "$_Ltop" in 'case:'*':0') err "fungsi $_Lfn case tanpa cabang (butuh minimal satu when/otherwise)" ;; esac
                        case "$_Lstack" in *' '*) _Lstack=${_Lstack% *} ;; *) _Lstack="" ;; esac
                        _Lpad=${_Lpad%    }; _Ldepth=$((_Ldepth - 1))
                        printf '%s}\n' "$_Lpad"
                        ;;
                    *) err "fungsi $_Lfn: baris intent tidak dikenal: $_La" ;;
                esac
            done < "$_Lftmp"
            rm -f "$_Lftmp"
            [ -z "$_Lstack" ] || err "fungsi $_Lfn: blok tidak ditutup: $_Lstack"
            printf '}\n'
        done
    } > "$_tmp" || die "cannot write $_tmp"
    mv "$_tmp" "$SECTION" || die "cannot write $SECTION"
    chmod 644 "$SECTION" 2>/dev/null || true
    echo "function section ditulis: $SECTION"
    _birdsh="$(dirname "$0")/titian-bird.sh"
    if [ -x "$_birdsh" ]; then
        "$_birdsh" generate function || exit 33
    else
        echo "Warning: $_birdsh tidak ditemukan; section hanya ditulis, belum di-apply" >&2
    fi
}

