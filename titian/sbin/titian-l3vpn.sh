#!/bin/sh
# titian-l3vpn.sh — L3VPN intent (BIRD `protocol l3vpn`) untuk Titian/klish.
# Batch B9 program BIRD (P3).
# CATATAN F3.2: `protocol l3vpn` TIDAK ada di BIRD 2.20.0 (bird -p
# menolak: CF_SYM_UNDEFINED) — fitur BIRD 3. Generator ini dipertahankan
# untuk BIRD 3; JANGAN dipakai di BIRD 2.20 (config yang dihasilkan
# ditolak bird -p). L3VPN di BIRD 2.20 dilakukan via channel vpn4/vpn6
# BGP (B6, terverifikasi bird -p). Item VPN1-VPN10 di BIRD-COVERAGE.md
# = N/A untuk BIRD 2.20.
# Pola sama seperti titian-mrt.sh: intent di /etc/titian/l3vpn.conf
# (tmpfs, dipersistenkan via titian-cfg.sh), generate menulis section
# BIRD /etc/titian/bird.d/l3vpn.conf lalu memanggil titian-bird.sh
# generate l3vpn (render + validasi + birdc). Section ditulis ulang
# UTUH tiap apply.
#
# Sintaks BIRD 2.16.1 yang dipakai (docs resmi bird.network,
# User's Guide 2.16.1, §6.9 L3VPN — BGP/MPLS IP VPN RFC 4364):
#   mpls domain mdom;
#   mpls table  mtab;
#   vpn4 table vpntab4;
#   vpn6 table vpntab6;
#   ipv4 table vrf0v4;
#   ipv6 table vrf0v6;
#   protocol l3vpn l3vpn0 {
#       vrf "vrf0";
#       ipv4 { table vrf0v4; };
#       ipv6 { table vrf0v6; };
#       vpn4 { table vpntab4; };
#       vpn6 { table vpntab6; };
#       mpls { label policy vrf; };
#       rd 10:12;
#       import target [(rt, 10, 32..40)];
#       export target [(rt, 10, 30), (rt, 10, 31)];
#   }
# Translator antara route IP dan route VPN. Arah import (VPN -> IP):
# route VPN yang cocok import target dilepas RD + label MPLS-nya.
# Arah export (IP -> VPN): route IP ditambah RD, export target
# community, dan label MPLS. HANYA mempropagasi best route per network
# (beda dari Pipe). Selalu MPLS-aware — channel `mpls` MANDATORY.
# Default export filter channel L3VPN adalah `all` (kontrol utama
# lewat import/export target, bukan filter).
# BUTUH: peer BGP VPN (vpn4/vpn6), MPLS (domain + table + kernel mpls),
# dan VRF kernel — bukan protokol mandiri. `vrf "vrf0"` di contoh adalah
# opsi UMUM protokol (Bab 3.4-6) yang N/A Linux-only di Titian — TIDAK
# diekspos di sini (FreeBSD tidak punya VRF Linux; pemetaan ke FIB/VNET
# belum diputuskan koordinator). `kernel table` di contoh juga N/A.
# Prasyarat global MPLS domain + mpls table SUDAH ada di global view
# (B6/B7: titian-global.sh mpls-domain-add / table-add mpls).
# `route target` adalah shorthand import+export sekaligus; docs TIDAK
# menegaskan apakah boleh dicampur dengan target terpisah — klish
# MENOLAK kombinasi itu di generate (pilih salah satu bentuk) agar
# tidak ada override diam-diam.
# TIDAK ADA perintah birdc `show l3vpn` (Bab 4.3 terkonfirmasi) —
# status dilihat lewat `show protocols [all]`.
#
# Format l3vpn.conf (satu baris per fakta):
#   instance <NAME> rd <RD>
#   instance <NAME> import-target <EC|EC-SET>
#   instance <NAME> export-target <EC|EC-SET>
#   instance <NAME> route-target <EC|EC-SET>
#   instance <NAME> <ipv4|ipv6|vpn4|vpn6>-table <TAB>
#   instance <NAME> <ipv4|ipv6|vpn4|vpn6>-import <all|none|filter NAME>
#   instance <NAME> <ipv4|ipv6|vpn4|vpn6>-export <all|none|filter NAME>
#   instance <NAME> mpls-label-policy <vrf|aggregate>
#   instance <NAME> debug <SPEC>
#   instance <NAME> mrtdump <SPEC>

STATE_ROOT="${TITIAN_STATE_ROOT:-/etc/titian}"
CONF="$STATE_ROOT/l3vpn.conf"
GLOBAL_CONF="$STATE_ROOT/bird-global.conf"
SECTION_DIR="$STATE_ROOT/bird.d"
SECTION="$SECTION_DIR/l3vpn.conf"
PROG="titian-l3vpn"
err() { echo "Error($PROG): $*" >&2; exit 33; }
die() { echo "$PROG: $*" >&2; exit 1; }

touch_conf() {
    if [ ! -f "$CONF" ]; then
        mkdir -p "$(dirname "$CONF")" 2>/dev/null
        printf '# l3vpn.conf - generated by klish, do not edit by hand\n' > "$CONF" \
            || die "cannot create $CONF"
        chmod 600 "$CONF" 2>/dev/null || true
    fi
}

upsert() {
    _re="$1"; _line="$2"
    touch_conf
    _tmp="$CONF.tmp.$$"
    grep -v "$_re" "$CONF" > "$_tmp" 2>/dev/null || true
    printf '%s\n' "$_line" >> "$_tmp"
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
    chmod 600 "$CONF" 2>/dev/null || true
}

dellines() {
    _re="$1"
    touch_conf
    _tmp="$CONF.tmp.$$"
    grep -v "$_re" "$CONF" > "$_tmp" 2>/dev/null || true
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
}

has_facts() {
    [ -f "$CONF" ] || return 1
    grep -v '^[[:space:]]*#' "$CONF" 2>/dev/null | grep -q '[^[:space:]]'
}

valid_name() {
    case "$1" in
        ''|*[!A-Za-z0-9_]*) err "$2 harus nama BIRD [A-Za-z0-9_]: $1" ;;
    esac
    case "$1" in [A-Za-z_]*) ;; *) err "$2 harus diawali huruf/underscore: $1" ;; esac
}

valid_rd() { # RD: ASN:u32 | ASN4:u16 | IP:u32 (satu token, tanpa spasi)
    _v="$1"; _l="$2"
    case "$_v" in *:* ) ;; *) err "$_l harus RD (ASN:u32 | ASN4:u16 | IP:u32): $_v" ;; esac
    _a=${_v%%:*}; _b=${_v#*:}
    case "$_a" in *.*)
        for _o in $(printf '%s' "$_a" | tr '.' ' '); do
            case "$_o" in ''|*[!0-9]*) err "$_l bagian IP RD harus oktet 0..255: $_v" ;; esac
            [ "$_o" -le 255 ] 2>/dev/null || err "$_l bagian IP RD harus oktet 0..255: $_v"
        done ;;
        *) case "$_a" in ''|*[!0-9]*) err "$_l bagian ASN RD harus bilangan: $_v" ;; esac
           [ "$_a" -le 4294967295 ] 2>/dev/null || err "$_l bagian ASN RD harus 0..4294967295: $_v" ;;
    esac
    case "$_b" in ''|*[!0-9]*) err "$_l bagian kedua RD harus bilangan: $_v" ;; esac
    [ "$_b" -le 4294967295 ] 2>/dev/null || err "$_l bagian kedua RD harus 0..4294967295: $_v"
}

valid_rt_target() { # EC tunggal (rt|ro, A, B) atau EC-set [(rt, A, B), ...] — satu token
    _v="$1"; _l="$2"
    case "$_v" in '['*']'|'('*')') ;; *) err "$_l harus EC (rt|ro, A, B) atau EC-set [(rt, A, B), ...] satu token tanpa spasi: $_v" ;; esac
    case "$_v" in *' '*|*\;*|*\"*|*\\*|*'$'*) err "$_l tidak boleh mengandung spasi/;/\"/\\/\\$: $_v" ;; esac
    _inner=${_v#\[}; _inner=${_inner%\]}
    # Pisah elemen top-level pada "),(" — tiap elemen (rt|ro, A, B).
    for _e in $(printf '%s' "$_inner" | sed 's/),(/\n/g'); do
        _e2=${_e#(}; _e2=${_e2%)}
        case "$_e2" in rt,*|ro,*) ;; *) err "$_l elemen EC harus diawali rt|ro: $_v" ;; esac
        _erest=${_e2#*,}
        case "$_erest" in *,*) _ea=${_erest%%,*}; _eb=${_erest#*,} ;; *) err "$_l elemen EC harus (rt|ro, A, B): $_v" ;; esac
        case "$_eb" in *,*) err "$_l elemen EC harus tepat 3 komponen: $_v" ;; esac
        for _ec in "$_ea" "$_eb"; do
            case "$_ec" in
                '*') ;;
                *..*) _elo=${_ec%%..*}; _ehi=${_ec#*..}
                    case "$_elo$_ehi" in ''|*[!0-9]*) err "$_l range EC harus N..M bilangan: $_v" ;; esac ;;
                *) case "$_ec" in ''|*[!0-9]*) err "$_l komponen EC harus bilangan/*/range: $_v" ;; esac ;;
            esac
        done
    done
}

valid_table() { # $1=nettype $2=tabel — master4/master6 sah; selain itu global
    _nt="$1"; _t="$2"
    case "$_t" in master4|master6) return 0 ;; esac
    valid_name "$_t" "tabel $_nt"
    [ -f "$GLOBAL_CONF" ] || err "tabel $_t belum didefinisikan (bird-global.conf belum ada — definisikan dulu: global -> table-add $_nt $_t)"
    grep -q "^table $_nt $_t\$" "$GLOBAL_CONF" 2>/dev/null || \
        err "tabel $_t belum didefinisikan sebagai $_nt (definisikan dulu: global -> table-add $_nt $_t)"
}

inst_has() {
    grep -q "^instance $1 " "$CONF" 2>/dev/null
}

get_inst_field() {
    grep "^instance $1 $2 " "$CONF" 2>/dev/null | head -1 | awk '{print $4}'
}

_l3_valid_spec() {
    _l3_spec="$1"; _l3_kind="$2"
    [ -n "$_l3_spec" ] || err "$_l3_kind butuh all|off|kelas,kelas,..."
    case "$_l3_spec" in all|off) return 0 ;; esac
    _l3_rest="$_l3_spec"
    while [ -n "$_l3_rest" ]; do
        case "$_l3_rest" in *,*) _l3_done=${_l3_rest%%,*}; _l3_rest=${_l3_rest#*,} ;; *) _l3_done="$_l3_rest"; _l3_rest="" ;; esac
        if [ "$_l3_kind" = "debug" ]; then
            case "$_l3_done" in states|routes|filters|interfaces|events|packets) ;; *) err "debug kelas tidak dikenal: $_l3_done (boleh: states|routes|filters|interfaces|events|packets)" ;; esac
        else
            case "$_l3_done" in states|messages) ;; *) err "mrtdump kelas tidak dikenal: $_l3_done (boleh: states|messages)" ;; esac
        fi
    done
}

cmd_l3vpn_touch() {
    _n="$1"
    [ -n "$_n" ] || err "l3vpn butuh NAMA instance"
    valid_name "$_n" "l3vpn"
    touch_conf
    echo "L3VPN $_n"
}

cmd_rd_set() {
    _n="$1"; _v="$2"
    valid_name "$_n" "l3vpn"
    valid_rd "$_v" "route distinguisher"
    upsert "^instance $_n rd " "instance $_n rd $_v"
    echo "L3VPN $_n rd = $_v"
}

cmd_rd_del() {
    _n="$1"; valid_name "$_n" "l3vpn"
    dellines "^instance $_n rd "
    echo "L3VPN $_n rd dihapus (rd MANDATORY — generate akan menolak)"
}

cmd_target_set() { # target-set <NAME> <import-target|export-target|route-target> <EC|EC-SET>
    _n="$1"; _f="$2"; _v="$3"
    valid_name "$_n" "l3vpn"
    case "$_f" in import-target|export-target|route-target) ;; *) err "target harus import-target|export-target|route-target: $_f" ;; esac
    valid_rt_target "$_v" "$_f"
    upsert "^instance $_n $_f " "instance $_n $_f $_v"
    echo "L3VPN $_n $_f = $_v"
}

cmd_target_del() {
    _n="$1"; _f="$2"
    valid_name "$_n" "l3vpn"
    case "$_f" in import-target|export-target|route-target) ;; *) err "target harus import-target|export-target|route-target: $_f" ;; esac
    dellines "^instance $_n $_f "
    echo "L3VPN $_n $_f dihapus"
}

cmd_chan_set() { # chan-set <NAME> <ipv4|ipv6|vpn4|vpn6> <table|import|export> <VALUE> [FILTER]
    _n="$1"; _c="$2"; _f="$3"; _v="$4"; _fn="$5"
    valid_name "$_n" "l3vpn"
    case "$_c" in ipv4|ipv6|vpn4|vpn6) ;; *) err "channel harus ipv4|ipv6|vpn4|vpn6: $_c" ;; esac
    case "$_f" in
        table)
            valid_table "$_c" "$_v"
            upsert "^instance $_n $_c-table " "instance $_n $_c-table $_v" ;;
        import|export)
            case "$_v" in
                all|none) upsert "^instance $_n $_c-$_f " "instance $_n $_c-$_f $_v" ;;
                filter)
                    [ -n "$_fn" ] || err "$_c $_f filter butuh NAMA filter"
                    valid_name "$_fn" "nama filter"
                    upsert "^instance $_n $_c-$_f " "instance $_n $_c-$_f filter $_fn" ;;
                *) err "$_c $_f harus all|none|filter NAMA: $_v" ;;
            esac ;;
        *) err "field channel harus table|import|export: $_f" ;;
    esac
    echo "L3VPN $_n $_c $_f = $_v${_fn:+ $_fn}"
}

cmd_chan_del() {
    _n="$1"; _c="$2"; _f="$3"
    valid_name "$_n" "l3vpn"
    case "$_c" in ipv4|ipv6|vpn4|vpn6) ;; *) err "channel harus ipv4|ipv6|vpn4|vpn6: $_c" ;; esac
    case "$_f" in table|import|export) ;; *) err "field channel harus table|import|export: $_f" ;; esac
    dellines "^instance $_n $_c-$_f "
    echo "L3VPN $_n $_c $_f dihapus"
}

cmd_mpls_set() {
    _n="$1"; _v="$2"
    valid_name "$_n" "l3vpn"
    case "$_v" in vrf|aggregate) ;; *) err "mpls label-policy harus vrf|aggregate: $_v" ;; esac
    upsert "^instance $_n mpls-label-policy " "instance $_n mpls-label-policy $_v"
    echo "L3VPN $_n mpls-label-policy = $_v"
}

cmd_mpls_del() {
    _n="$1"; valid_name "$_n" "l3vpn"
    dellines "^instance $_n mpls-label-policy "
    echo "L3VPN $_n mpls-label-policy dihapus (mpls channel MANDATORY — generate akan menolak)"
}

cmd_debug_set() {
    _n="$1"; _v="$2"
    valid_name "$_n" "l3vpn"
    _l3_valid_spec "$_v" debug
    upsert "^instance $_n debug " "instance $_n debug $_v"
    echo "L3VPN $_n debug = $_v"
}

cmd_debug_del() {
    _n="$1"; valid_name "$_n" "l3vpn"
    dellines "^instance $_n debug "
    echo "L3VPN $_n debug dihapus (default BIRD off)"
}

cmd_mrtdump_set() {
    _n="$1"; _v="$2"
    valid_name "$_n" "l3vpn"
    _l3_valid_spec "$_v" mrtdump
    upsert "^instance $_n mrtdump " "instance $_n mrtdump $_v"
    echo "L3VPN $_n mrtdump = $_v"
}

cmd_mrtdump_del() {
    _n="$1"; valid_name "$_n" "l3vpn"
    dellines "^instance $_n mrtdump "
    echo "L3VPN $_n mrtdump dihapus (default BIRD off)"
}

# emit_chan <NAME> <ipv4|ipv6|vpn4|vpn6>
emit_chan() {
    _n="$1"; _c="$2"
    _tab=$(get_inst_field "$_n" "$_c-table")
    _imp=$(grep "^instance $_n $_c-import " "$CONF" 2>/dev/null | head -1 | sed "s/^instance $_n $_c-import //")
    _exp=$(grep "^instance $_n $_c-export " "$CONF" 2>/dev/null | head -1 | sed "s/^instance $_n $_c-export //")
    if [ -z "$_tab" ] && [ -z "$_imp" ] && [ -z "$_exp" ]; then
        return 0
    fi
    echo "    $_c {"
    [ -n "$_tab" ] && echo "        table $_tab;"
    [ -n "$_imp" ] && echo "        import $_imp;"
    [ -n "$_exp" ] && echo "        export $_exp;"
    echo "    };"
}

emit_instance() {
    _n="$1"
    inst_has "$_n" || return 0
    _rd=$(get_inst_field "$_n" rd)
    _it=$(get_inst_field "$_n" import-target)
    _et=$(get_inst_field "$_n" export-target)
    _rt=$(get_inst_field "$_n" route-target)
    _mlp=$(get_inst_field "$_n" mpls-label-policy)
    _dbg=$(get_inst_field "$_n" debug)
    _mrt=$(get_inst_field "$_n" mrtdump)
    [ -n "$_rd" ] || err "l3vpn $_n tanpa rd — route distinguisher MANDATORY (docs §6.9, VPN1/VPN2)"
    if [ -n "$_rt" ] && { [ -n "$_it" ] || [ -n "$_et" ]; }; then
        err "l3vpn $_n: route-target (shorthand) tidak boleh dicampur import-target/export-target terpisah — pilih salah satu bentuk"
    fi
    if [ -z "$_rt" ]; then
        [ -n "$_it" ] || err "l3vpn $_n tanpa import-target — import target MANDATORY (docs §6.9, VPN3)"
        [ -n "$_et" ] || err "l3vpn $_n tanpa export-target — export target MANDATORY (docs §6.9, VPN4)"
    fi
    [ -n "$_mlp" ] || err "l3vpn $_n tanpa mpls label-policy — channel mpls MANDATORY (docs §6.9, VPN10)"
    echo "protocol l3vpn $_n {"
    if [ -n "$_dbg" ]; then
        case "$_dbg" in all|off) echo "    debug $_dbg;" ;; *) echo "    debug { $(echo "$_dbg" | sed 's/,/, /g') };" ;; esac
    fi
    if [ -n "$_mrt" ]; then
        case "$_mrt" in all|off) echo "    mrtdump $_mrt;" ;; *) echo "    mrtdump { $(echo "$_mrt" | sed 's/,/, /g') };" ;; esac
    fi
    emit_chan "$_n" ipv4
    emit_chan "$_n" ipv6
    emit_chan "$_n" vpn4
    emit_chan "$_n" vpn6
    echo "    mpls { label policy $_mlp; };"
    echo "    rd $_rd;"
    if [ -n "$_rt" ]; then
        echo "    route target $_rt;"
    else
        echo "    import target $_it;"
        echo "    export target $_et;"
    fi
    echo "}"
    echo ""
}

cmd_generate() {
    touch_conf
    set -f
    mkdir -p "$SECTION_DIR" 2>/dev/null || die "cannot mkdir $SECTION_DIR"
    _tmp="$SECTION.tmp.$$"
    if has_facts; then
        {
            echo "# l3vpn.conf - generated by titian-l3vpn.sh, do not edit by hand"
            for _n in $(grep '^instance ' "$CONF" 2>/dev/null | awk '{print $2}' | awk '!s[$0]++'); do
                emit_instance "$_n"
            done
        } > "$_tmp" || die "cannot write $_tmp"
    else
        {
            echo "# l3vpn.conf - generated by titian-l3vpn.sh, do not edit by hand"
            echo "# (tidak ada config L3VPN — protocol l3vpn tidak dibuat)"
        } > "$_tmp" || die "cannot write $_tmp"
    fi
    mv "$_tmp" "$SECTION" || die "cannot write $SECTION"
    chmod 644 "$SECTION" 2>/dev/null || true
    set +f
    echo "L3VPN section ditulis: $SECTION"
    _birdsh="$(dirname "$0")/titian-bird.sh"
    if [ -x "$_birdsh" ]; then
        "$_birdsh" generate l3vpn || exit 33
    else
        echo "Warning: $_birdsh tidak ditemukan; section hanya ditulis, belum di-apply" >&2
    fi
}

birdc_bin() {
    command -v birdc 2>/dev/null || { [ -x /usr/sbin/birdc ] && echo /usr/sbin/birdc; } || \
        { [ -x /usr/local/sbin/birdc ] && echo /usr/local/sbin/birdc; } || echo birdc
}

cmd_show() {
    touch_conf
    echo "--- l3vpn.conf (intent) ---"
    cat "$CONF"
    echo "--- bird.d/l3vpn.conf (section, bila ada) ---"
    [ -f "$SECTION" ] && cat "$SECTION" || echo "(belum di-generate)"
    echo "--- birdc show protocol (l3vpn; TIDAK ADA show l3vpn khusus — via show protocols) ---"
    _birdc=$(birdc_bin)
    _done=0
    for _n in $(grep '^instance ' "$CONF" 2>/dev/null | awk '{print $2}' | awk '!s[$0]++'); do
        if grep -q "protocol l3vpn $_n" "$SECTION" 2>/dev/null; then
            if _out=$("$_birdc" show protocol "$_n" 2>&1); then
                echo "$_out" | grep -v '^BIRD'
                _done=1
            fi
        fi
    done
    [ "$_done" = "0" ] && echo "(BIRD tidak jalan / belum ada instance L3VPN — birdc show protocol gagal)"
    return 0
}

case "$1" in
    l3vpn-touch) shift; cmd_l3vpn_touch "$@" ;;
    has-facts) has_facts ;;
    rd-set) shift; cmd_rd_set "$@" ;;
    rd-del) shift; cmd_rd_del "$@" ;;
    target-set) shift; cmd_target_set "$@" ;;
    target-del) shift; cmd_target_del "$@" ;;
    chan-set) shift; cmd_chan_set "$@" ;;
    chan-del) shift; cmd_chan_del "$@" ;;
    mpls-label-policy-set) shift; cmd_mpls_set "$@" ;;
    mpls-label-policy-del) shift; cmd_mpls_del "$@" ;;
    debug-set) shift; cmd_debug_set "$@" ;;
    debug-del) shift; cmd_debug_del "$@" ;;
    mrtdump-set) shift; cmd_mrtdump_set "$@" ;;
    mrtdump-del) shift; cmd_mrtdump_del "$@" ;;
    generate) cmd_generate ;;
    show) cmd_show ;;
    *) echo "Usage: $0 {l3vpn-touch NAME|has-facts|rd-set NAME RD|rd-del NAME|target-set NAME import-target|export-target|route-target EC|target-del NAME import-target|export-target|route-target|chan-set NAME ipv4|ipv6|vpn4|vpn6 table|import|export VALUE [FILTER]|chan-del NAME ipv4|ipv6|vpn4|vpn6 table|import|export|mpls-label-policy-set NAME vrf|aggregate|mpls-label-policy-del NAME|debug-set NAME SPEC|debug-del NAME|mrtdump-set NAME SPEC|mrtdump-del NAME|generate|show}" >&2; exit 2 ;;
esac
