#!/bin/sh
# titian-mrt.sh — MRT intent (BIRD `protocol mrt`) untuk Titian/klish.
# Batch B8 program BIRD.
# Pola sama seperti titian-aggregator.sh: intent di /etc/titian/mrt.conf
# (tmpfs, dipersistenkan via titian-cfg.sh), generate menulis section
# BIRD /etc/titian/bird.d/mrt.conf lalu memanggil titian-bird.sh
# generate mrt (render + validasi + birdc). Section ditulis ulang
# UTUH tiap apply.
#
# Sintaks BIRD 2.16.1 yang dipakai (docs resmi bird.network,
# User's Guide 2.16.1, §6.10 MRT — RFC 6396 + ADD_PATH RFC 8050):
#   protocol mrt <name> {
#       table "tab*";
#       where source = RTS_BGP;
#       filename "/var/log/bird/%N_%F_%T.mrt";
#       period 300;
#       always add path yes;
#   }
# Dump periodik tabel routing ke file MRT (dianalisis belakangan tool
# lain). Murni lokal (file) — tidak butuh peer/server. Tidak memakai
# channel. Dua statement MANDATORY: `filename` dan `period` (ditolak
# saat generate bila kosong). Beberapa instance MRT independen =
# beberapa dump periodik independen.
# `table`: nama tabel atau pola wildcard ber-quote (mis. "tab*").
# Default master table bila tidak di-set.
# `filter { ... }` dan `where ...` adalah DUA CARA menulis filter
# yang sama — hanya satu yang boleh dipakai (ditolak saat generate
# bila keduanya di-set).
# `filename`: boleh sequence strftime(3) + `%N` (nama tabel yang
# di-dump — tiap tabel ke file berbeda).
# `always add path`: default disabled (RFC 8050); bila enabled, route
# ADD_PATH maupun non-ADD_PATH disimpan dalam record ADD_PATH dan
# urutan route per network dipertahankan.
# Opsi global `mrtdump` (menyimpan pesan BGP masuk) BUKAN bagian
# protokol MRT — sudah ada di global view (B6).
#
# TIDAK diimplementasi di batch ini:
#   - Dump on-demand `mrt dump table` dari birdc — SUDAH ada di B7
#     (titian-birdc.sh).
#   - Builder terstruktur untuk blok `filter { ... }`: isinya ditulis
#     sebagai baris kode BIRD mentah lewat `filter-line` (maks 8
#     kata/baris — sama seperti merge-line aggregator). Validasi
#     sintaks penuh oleh `bird -p` saat generate.
#
# Format mrt.conf (satu baris per fakta):
#   instance <NAME> table <TABEL|POLA>
#   instance <NAME> where <EKSPRESI>
#   instance <NAME> filter-line <BARIS KODE BIRD>
#   instance <NAME> filename <PATH>
#   instance <NAME> period <N>
#   instance <NAME> always-add-path <on|off>

STATE_ROOT="${TITIAN_STATE_ROOT:-/etc/titian}"
CONF="$STATE_ROOT/mrt.conf"
GLOBAL_CONF="$STATE_ROOT/bird-global.conf"
# Pager global: output show >1 layar lewat less (titian-page.sh).
# Prologue dipanggil SESUDAH setup warna/TTY bila ada, SEBELUM output pertama.
SBIN_DIR=$(dirname "$0")
. "$SBIN_DIR/titian-page.sh"
# Hanya subcommand baca yang dipager: set/generate/commit TIDAK —
# output-nya harus tetap streaming/langsung, bukan tertahan sampai EXIT.
case "${1:-}" in show) titian_page_begin ;; esac

SECTION_DIR="$STATE_ROOT/bird.d"
SECTION="$SECTION_DIR/mrt.conf"
PROG="titian-mrt"
err() { echo "Error($PROG): $*" >&2; exit 33; }
die() { echo "$PROG: $*" >&2; exit 1; }

touch_conf() {
    if [ ! -f "$CONF" ]; then
        mkdir -p "$(dirname "$CONF")" 2>/dev/null
        printf '# mrt.conf - generated by klish, do not edit by hand\n' > "$CONF" \
            || die "cannot create $CONF"
        chmod 600 "$CONF" 2>/dev/null || true
    fi
}

# upsert <regex-untuk-hapus> <baris-baru>
upsert() {
    _re="$1"; _line="$2"
    touch_conf
    _tmp="$CONF.tmp.$$"
    grep -v "$_re" "$CONF" > "$_tmp" 2>/dev/null || true
    printf '%s\n' "$_line" >> "$_tmp"
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
    chmod 600 "$CONF" 2>/dev/null || true
}

dellines() {
    _re="$1"
    touch_conf
    _tmp="$CONF.tmp.$$"
    grep -v "$_re" "$CONF" > "$_tmp" 2>/dev/null || true
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
}

has_facts() {
    [ -f "$CONF" ] || return 1
    grep -v '^[[:space:]]*#' "$CONF" 2>/dev/null | grep -q '[^[:space:]]'
}

# --- validasi ---
valid_name() {
    # $1=nama $2=konteks: simbol BIRD [A-Za-z_][A-Za-z0-9_]*.
    case "$1" in
        ''|*[!A-Za-z0-9_]*) err "$2 harus nama BIRD [A-Za-z0-9_]: $1" ;;
    esac
    case "$1" in [A-Za-z_]*) ;; *) err "$2 harus diawali huruf/underscore: $1" ;; esac
}

valid_table() {
    # $1=tabel|pola $2=konteks. Pola wildcard (*/?) dilewati tanpa cek
    # keberadaan (bisa cocok tabel yang dibuat belakangan). Nama polos:
    # master4/master6 selalu sah; selain itu harus terdefinisi di
    # bird-global.conf (B6: table-add).
    case "$1" in *\** | *\?*) return 0 ;; esac
    case "$1" in master4|master6) return 0 ;; esac
    valid_name "$1" "$2"
    [ -f "$GLOBAL_CONF" ] || err "$2 tabel $1 belum didefinisikan (bird-global.conf belum ada — definisikan dulu: global -> table-add ... $1)"
    grep -q "^table [^ ]* $1\$" "$GLOBAL_CONF" 2>/dev/null || \
        err "$2 tabel $1 belum didefinisikan (definisikan dulu: global -> table-add <nettype> $1)"
}

# inst_has <NAME>: exit 0 bila ada >=1 fakta instance itu.
inst_has() {
    grep -q "^instance $1 " "$CONF" 2>/dev/null
}

# join_words: gabung argumen tak-kosong dengan satu spasi.
join_words() {
    _out=""
    for _w in "$@"; do
        [ -n "$_w" ] || continue
        if [ -z "$_out" ]; then _out="$_w"; else _out="$_out $_w"; fi
    done
    printf '%s' "$_out"
}

# valid_codeline <TEKS> <label>: tolak karakter yang bisa membobol
# blok `filter { ... }` / statement `where`.
valid_codeline() {
    _t="$1"; _l="$2"
    [ -n "$_t" ] || err "$_l butuh isi (maks 8 kata; ekspresi panjang boleh dipecah)"
    case "$_t" in
        *\;*) err "$_l tidak boleh mengandung ';' (terminator ditambah generator): $_t" ;;
        *\{*|*\}*) err "$_l tidak boleh mengandung kurung kurawal: $_t" ;;
        *'/*'*|*'*/'*) err "$_l tidak boleh mengandung komentar /* */: $_t" ;;
        *\"*|*\\*|*'`'*|*'$'*) err "$_l tidak boleh mengandung \" \\ \` \$: $_t" ;;
    esac
}

cmd_mrt_touch() {
    _n="$1"
    [ -n "$_n" ] || err "mrt butuh NAMA instance"
    valid_name "$_n" "mrt"
    touch_conf
    echo "MRT $_n"
}

cmd_table_set() {
    _n="$1"; _t="$2"
    valid_name "$_n" "mrt"
    [ -n "$_t" ] || err "table butuh nama tabel atau pola (mis. tab*)"
    case "$_t" in *[!A-Za-z0-9_*?]*) err "table harus nama BIRD atau pola wildcard [A-Za-z0-9_*?]: $_t" ;; esac
    valid_table "$_t" "mrt table"
    upsert "^instance $_n table " "instance $_n table $_t"
    echo "MRT $_n table = $_t"
}

cmd_table_del() {
    _n="$1"
    valid_name "$_n" "mrt"
    dellines "^instance $_n table "
    echo "MRT $_n table dihapus (default master table)"
}

cmd_where_set() {
    # where-set <NAME> <W1..W8> — ekspresi filter satu baris.
    _n="$1"; shift
    valid_name "$_n" "mrt"
    _line=$(join_words "$@")
    valid_codeline "$_line" "where"
    upsert "^instance $_n where " "instance $_n where $_line"
    echo "MRT $_n where = $_line"
}

cmd_where_del() {
    _n="$1"
    valid_name "$_n" "mrt"
    dellines "^instance $_n where "
    echo "MRT $_n where dihapus"
}

cmd_filter_add() {
    # filter-line-add <NAME> <W1..W8> — satu baris kode blok filter.
    _n="$1"; shift
    valid_name "$_n" "mrt"
    _line=$(join_words "$@")
    valid_codeline "$_line" "filter-line"
    touch_conf
    printf 'instance %s filter-line %s\n' "$_n" "$_line" >> "$CONF"
    echo "MRT $_n filter-line: $_line"
}

cmd_filter_del() {
    # filter-line-del <NAME> <N>: hapus baris filter ke-N (1-based).
    _n="$1"; _no="$2"
    valid_name "$_n" "mrt"
    case "$_no" in ''|*[!0-9]*) err "filter-line-del butuh nomor baris (1..): $_no" ;; esac
    [ "$_no" -ge 1 ] 2>/dev/null || err "filter-line-del nomor harus >= 1: $_no"
    _tmp="$CONF.tmp.$$"
    awk -v n="$_no" -v inst="$_n" '
        $1=="instance" && $2==inst && $3=="filter-line" { c++; if (c==n) next }
        { print }
    ' "$CONF" > "$_tmp" 2>/dev/null || die "cannot write $CONF"
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
    echo "MRT $_n filter-line #$_no dihapus"
}

cmd_filter_clear() {
    _n="$1"
    valid_name "$_n" "mrt"
    dellines "^instance $_n filter-line "
    echo "MRT $_n filter-line dihapus semua"
}

cmd_filename_set() {
    _n="$1"; _f="$2"
    valid_name "$_n" "mrt"
    [ -n "$_f" ] || err "filename butuh path (mis. /var/log/bird/%N_%F_%T.mrt)"
    case "$_f" in
        /*) ;;
        *) err "filename harus path absolut: $_f" ;;
    esac
    case "$_f" in *\"*|*\\*|*\;*|*\ *|*\'*) err "filename tidak boleh mengandung spasi/\"/\\/'/;: $_f" ;; esac
    # Sequence %: tiap % harus diikuti huruf (strftime) atau % — %N
    # adalah sequence BIRD (nama tabel).
    _rest="$_f"
    while case "$_rest" in *%*) true ;; *) false ;; esac; do
        _rest=${_rest#*%}
        case "$_rest" in
            '') err "filename '%' di ujung tanpa kode: $_f" ;;
            [A-Za-z%]*) _rest=${_rest#?} ;;
            *) err "filename sequence '%' tidak valid (harus huruf strftime atau %N): $_f" ;;
        esac
    done
    upsert "^instance $_n filename " "instance $_n filename $_f"
    echo "MRT $_n filename = $_f"
}

cmd_filename_del() {
    _n="$1"
    valid_name "$_n" "mrt"
    dellines "^instance $_n filename "
    echo "MRT $_n filename dihapus (filename MANDATORY — generate akan menolak)"
}

cmd_period_set() {
    _n="$1"; _v="$2"
    valid_name "$_n" "mrt"
    [ -n "$_v" ] || err "period butuh nilai detik"
    case "$_v" in ''|*[!0-9]*) err "period harus bilangan 1..4294967295 (detik): $_v" ;; esac
    [ "$_v" -ge 1 ] 2>/dev/null || err "period harus >= 1 detik: $_v"
    [ "$_v" -le 4294967295 ] 2>/dev/null || err "period harus 1..4294967295 (detik): $_v"
    upsert "^instance $_n period " "instance $_n period $_v"
    echo "MRT $_n period = $_v"
}

cmd_period_del() {
    _n="$1"
    valid_name "$_n" "mrt"
    dellines "^instance $_n period "
    echo "MRT $_n period dihapus (period MANDATORY — generate akan menolak)"
}

cmd_aap_set() {
    _n="$1"; _v="$2"
    valid_name "$_n" "mrt"
    case "$_v" in
        on|off) upsert "^instance $_n always-add-path " "instance $_n always-add-path $_v" ;;
        *) err "always-add-path harus on|off: $_v" ;;
    esac
    echo "MRT $_n always-add-path = $_v"
}

cmd_aap_del() {
    _n="$1"
    valid_name "$_n" "mrt"
    dellines "^instance $_n always-add-path "
    echo "MRT $_n always-add-path dihapus (default BIRD disabled)"
}

# --- getters (untuk generate) ---
get_inst_field() {
    # $1=instance $2=field -> nilai (kolom 4)
    grep "^instance $1 $2 " "$CONF" 2>/dev/null | head -1 | awk '{print $4}'
}

# emit_instance <NAME>: cetak blok `protocol mrt <NAME> { ... }`.
emit_instance() {
    _n="$1"
    inst_has "$_n" || return 0
    _table=$(get_inst_field "$_n" table)
    _where=$(grep "^instance $_n where " "$CONF" 2>/dev/null | head -1 | sed "s/^instance $_n where //")
    _filters=$(grep "^instance $_n filter-line " "$CONF" 2>/dev/null | sed "s/^instance $_n filter-line //")
    _file=$(get_inst_field "$_n" filename)
    _period=$(get_inst_field "$_n" period)
    _aap=$(get_inst_field "$_n" always-add-path)
    [ -n "$_file" ] || err "mrt $_n tanpa filename — filename MANDATORY (docs §6.10)"
    [ -n "$_period" ] || err "mrt $_n tanpa period — period MANDATORY (docs §6.10)"
    if [ -n "$_where" ] && [ -n "$_filters" ]; then
        err "mrt $_n punya where DAN filter-line — hanya satu yang boleh dipakai (keduanya cara menulis filter yang sama, docs §6.10)"
    fi
    echo "protocol mrt $_n {"
    if [ -n "$_table" ]; then
        case "$_table" in *\** | *\?*) echo "    table \"$_table\";" ;; *) echo "    table $_table;" ;; esac
    fi
    if [ -n "$_filters" ]; then
        echo "    filter {"
        printf '%s\n' "$_filters" | sed 's/^/        /; s/$/;/'
        echo "    };"
    elif [ -n "$_where" ]; then
        echo "    where $_where;"
    fi
    echo "    filename \"$_file\";"
    echo "    period $_period;"
    case "$_aap" in
        on) echo "    always add path yes;" ;;
        off) echo "    always add path no;" ;;
    esac
    echo "}"
    echo ""
}

cmd_generate() {
    touch_conf
    set -f
    mkdir -p "$SECTION_DIR" 2>/dev/null || die "cannot mkdir $SECTION_DIR"
    _tmp="$SECTION.tmp.$$"
    if has_facts; then
        {
            echo "# mrt.conf - generated by titian-mrt.sh, do not edit by hand"
            for _n in $(grep '^instance ' "$CONF" 2>/dev/null | awk '{print $2}' | awk '!s[$0]++'); do
                emit_instance "$_n"
            done
        } > "$_tmp" || die "cannot write $_tmp"
    else
        {
            echo "# mrt.conf - generated by titian-mrt.sh, do not edit by hand"
            echo "# (tidak ada config MRT — protocol mrt tidak dibuat)"
        } > "$_tmp" || die "cannot write $_tmp"
    fi
    mv "$_tmp" "$SECTION" || die "cannot write $SECTION"
    chmod 644 "$SECTION" 2>/dev/null || true
    set +f
    echo "MRT section ditulis: $SECTION"
    _birdsh="$(dirname "$0")/titian-bird.sh"
    if [ -x "$_birdsh" ]; then
        "$_birdsh" generate mrt || exit 33
    else
        echo "Warning: $_birdsh tidak ditemukan; section hanya ditulis, belum di-apply" >&2
    fi
}

birdc_bin() {
    command -v birdc 2>/dev/null || { [ -x /usr/sbin/birdc ] && echo /usr/sbin/birdc; } || \
        { [ -x /usr/local/sbin/birdc ] && echo /usr/local/sbin/birdc; } || echo birdc
}
# birdc_sock — salinan titian-birdc.sh (BC8, B13): cetak "-s <path>" bila
# socket utama dikonfigurasi via klish ($STATE_ROOT/birdc.conf), kosong bila
# default. Dipakai semua pemanggilan birdc di file ini.
birdc_sock() {
    _s=$(grep '^socket ' "$STATE_ROOT/birdc.conf" 2>/dev/null | head -1 | cut -d' ' -f2-)
    [ -n "$_s" ] && printf '%s' "-s $_s"
}


cmd_show() {
    touch_conf
    echo "--- mrt.conf (intent) ---"
    cat "$CONF"
    echo "--- bird.d/mrt.conf (section, bila ada) ---"
    [ -f "$SECTION" ] && cat "$SECTION" || echo "(belum di-generate)"
    echo "--- birdc show protocol (mrt) ---"
    _birdc=$(birdc_bin)
    _done=0
    for _n in $(grep '^instance ' "$CONF" 2>/dev/null | awk '{print $2}' | awk '!s[$0]++'); do
        if grep -q "protocol mrt $_n" "$SECTION" 2>/dev/null; then
            if _out=$("$_birdc" $(birdc_sock) show protocol "$_n" 2>&1); then
                echo "$_out" | grep -v '^BIRD'
                _done=1
            fi
        fi
    done
    [ "$_done" = "0" ] && echo "(BIRD tidak jalan / belum ada instance MRT — birdc show protocol gagal)"
    return 0
}

case "$1" in
    mrt-touch) shift; cmd_mrt_touch "$@" ;;
    has-facts) has_facts ;;
    table-set) shift; cmd_table_set "$@" ;;
    table-del) shift; cmd_table_del "$@" ;;
    where-set) shift; cmd_where_set "$@" ;;
    where-del) shift; cmd_where_del "$@" ;;
    filter-line-add) shift; cmd_filter_add "$@" ;;
    filter-line-del) shift; cmd_filter_del "$@" ;;
    filter-line-clear) shift; cmd_filter_clear "$@" ;;
    filename-set) shift; cmd_filename_set "$@" ;;
    filename-del) shift; cmd_filename_del "$@" ;;
    period-set) shift; cmd_period_set "$@" ;;
    period-del) shift; cmd_period_del "$@" ;;
    always-add-path-set) shift; cmd_aap_set "$@" ;;
    always-add-path-del) shift; cmd_aap_del "$@" ;;
    generate) cmd_generate ;;
    show) cmd_show ;;
    *) echo "Usage: $0 {mrt-touch NAME|has-facts|table-set NAME TABEL|POLA|table-del NAME|where-set NAME W1..W8|where-del NAME|filter-line-add NAME W1..W8|filter-line-del NAME N|filter-line-clear NAME|filename-set NAME PATH|filename-del NAME|period-set NAME N|period-del NAME|always-add-path-set NAME on|off|always-add-path-del NAME|generate|show}" >&2; exit 2 ;;
esac
