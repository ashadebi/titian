#!/bin/sh
# TITIAN BSDRP — monitoring: snmpd / node_exporter / bird_exporter / nfacctd.
# Semua OFF by default (feature-list §9). `set` hanya mencatat niat di
# $STATE_ROOT/netstate/monitoring.intent + menandai dirty; service
# naik/berhenti saat `commit` (apply di sini). Community SNMP ditulis
# ke /usr/local/etc/snmp/snmpd.conf saat apply (rocommunity).
# Format intent:
#   snmp yes|no
#   node-exporter yes|no
#   bird-exporter yes|no
#   nfacctd yes|no
#   snmp-community <string>
# Nama rc script yang dipakai (snmpd, node_exporter, bird_exporter,
# nfacctd) + port default (161/udp, 9100, 9324, 2100) — verifikasi live
# di guest: nama service/port bisa berbeda menurut port yang terpasang.
# POSIX sh.
ROOT=${TITIAN_ROOT:-/opt/titian}
STATE_ROOT=${TITIAN_STATE_ROOT:-/etc/titian}
INTENT="$STATE_ROOT/netstate/monitoring.intent"
DIRTY=/var/run/monitoring.dirty
SNMP_CONF=/usr/local/etc/snmp/snmpd.conf
PROG="titian-monitoring"
err() { echo "Error($PROG): $*" >&2; exit 33; }
die() { echo "$PROG: $*" >&2; exit 1; }

svc_name() {
    case "$1" in
        snmp) echo "snmpd" ;;
        node-exporter) echo "node_exporter" ;;
        bird-exporter) echo "bird_exporter" ;;
        nfacctd) echo "nfacctd" ;;
        *) die "service tidak dikenal: $1 (snmp|node-exporter|bird-exporter|nfacctd)" ;;
    esac
}

svc_port() {
    case "$1" in
        snmp) echo "161/udp" ;;
        node-exporter) echo "9100" ;;
        bird-exporter) echo "9324" ;;
        nfacctd) echo "2100" ;;
    esac
}

touch_intent() {
    mkdir -p "$(dirname "$INTENT")" 2>/dev/null
    if [ ! -f "$INTENT" ]; then
        printf '# monitoring.intent - generated by klish, do not edit by hand\nsnmp no\nnode-exporter no\nbird-exporter no\nnfacctd no\nsnmp-community bsdrp-ro\n' > "$INTENT" \
            || die "cannot create $INTENT"
    fi
}

mark_dirty() { touch "$DIRTY" 2>/dev/null || true; }

intent_val() {
    touch_intent
    _v=$(sed -n "s/^$1 //p" "$INTENT" 2>/dev/null | head -1)
    printf '%s' "${_v:-unset}"
}

upsert() {
    touch_intent
    _tmp="$INTENT.tmp.$$"
    grep -v "^$1 " "$INTENT" > "$_tmp" 2>/dev/null || true
    printf '%s %s\n' "$1" "$2" >> "$_tmp"
    mv "$_tmp" "$INTENT" || die "cannot write $INTENT"
    mark_dirty
}

svc_running() {
    # $1 = nama service rc; cek proses dulu (nama proses ~= nama service),
    # lalu `service <name> status` bila ada.
    _proc="$1"
    case "$1" in snmpd) _proc="snmpd" ;; node_exporter) _proc="node_exporter" ;; bird_exporter) _proc="bird_exporter" ;; nfacctd) _proc="nfacctd" ;; esac
    if command -v pgrep >/dev/null 2>&1; then
        pgrep -x "$_proc" >/dev/null 2>&1 && return 0
    fi
    if command -v service >/dev/null 2>&1; then
        service "$1" status >/dev/null 2>&1 && return 0
    fi
    return 1
}

# --- read-only ---
cmd_check() { touch_intent; exit 0; }

cmd_show() {
    # $1 = kosong (semua) atau satu service
    touch_intent
    _list="snmp node-exporter bird-exporter nfacctd"
    [ -n "${1:-}" ] && _list="$1"
    for _s in $_list; do
        _name=$(svc_name "$_s")
        _want=$(intent_val "$_s")
        _rc=$(command -v sysrc >/dev/null 2>&1 && sysrc -n "${_name}_enable" 2>/dev/null || echo "?")
        if svc_running "$_name"; then _run="running"; else _run="not running"; fi
        _port=$(svc_port "$_s")
        if [ "$_s" = "snmp" ]; then
            _comm=$(intent_val snmp-community)
            echo "snmpd (port $_port): intent $_want, rc ${_rc:-?}, $_run, community ${_comm}"
        else
            echo "$_name (port $_port): intent $_want, rc ${_rc:-?}, $_run"
        fi
    done
    exit 0
}

# --- bandwidth (bwm-ng) ---
# Warna ANSI (hanya bila stdout terminal; bila di-pipe, output polos).
# _ESC = byte ESC asli (printf '%s' tidak menafsir \033, jadi konstanta
# harus berisi byte ESC, bukan string literal "\033").
_ESC=$(printf '\033')
_C_RED="${_ESC}[31m"; _C_GREEN="${_ESC}[32m"; _C_YELLOW="${_ESC}[33m"; _C_BOLD="${_ESC}[1m"; _C_RESET="${_ESC}[0m"
_bw_color() {
    # $1 = kode warna, $2 = teks. Cetak berwarna bila tty, polos bila bukan.
    if [ -t 1 ]; then printf '%s%s%s' "$1" "$2" "$_C_RESET"; else printf '%s' "$2"; fi
}

fmt_bps() {
    # $1 = bytes/detik (dari bwm-ng) -> bit/detik, tampil bps/Kbps/Mbps/Gbps (desimal, 1000)
    _v=${1:-0}
    awk -v v="$_v" 'BEGIN {
        b = v * 8
        if (b >= 1000000000) printf "%.2f Gbps", b/1000000000
        else if (b >= 1000000) printf "%.2f Mbps", b/1000000
        else if (b >= 1000) printf "%.2f Kbps", b/1000
        else printf "%.0f bps", b
    }'
}

_print_bw_table() {
    # $1 = judul. Data CSV bwm-ng dibaca dari stdin.
    # Baris selang-seling: ganjil merah, genap default; baris total tebal.
    _title=$1
    printf '%s\n' "$_title"
    printf '  %-12s %-12s %-12s %-12s\n' "Interface" "RX" "TX" "Total"
    _row=0
    while IFS=';' read -r _ts _iface _rx _tx _tot _rest; do
        [ -n "$_iface" ] || continue
        _row=$((_row + 1))
        _line=$(printf '  %-12s %-12s %-12s %-12s' "$_iface" "$(fmt_bps "$_rx")" "$(fmt_bps "$_tx")" "$(fmt_bps "$_tot")")
        if [ "$_iface" = "total" ]; then
            _bw_color "$_C_BOLD" "$_line"; printf '\n'
        elif [ $((_row % 2)) -eq 1 ]; then
            _bw_color "$_C_RED" "$_line"; printf '\n'
        else
            printf '%s\n' "$_line"
        fi
    done
    return 0
}

_last_bw_snapshot() {
    # $1 = file output bwm-ng. Cetak baris snapshot terakhir.
    # Timestamp bwm-ng per baris beda mikrodetik dalam satu snapshot,
    # jadi kelompokkan berdasarkan detik (bagian integer timestamp).
    _f=$1
    [ -s "$_f" ] || return 1
    _last_sec=$(tail -n 1 "$_f" 2>/dev/null | cut -d';' -f1 | cut -d'.' -f1)
    [ -n "$_last_sec" ] || return 1
    grep -F "${_last_sec}." "$_f" 2>/dev/null
    return 0
}

_live_bandwidth() {
    # $1 = durasi detik. Update tiap detik, q = berhenti lebih awal.
    _secs=$1
    _tmp=$(mktemp /tmp/titian-bwm.XXXXXX) || die "gagal buat temp file"
    _bwm_pid=""
    _saved_stty=""
    _is_tty=0
    [ -t 1 ] && _is_tty=1
    _cleanup_live() {
        [ -n "$_bwm_pid" ] && kill "$_bwm_pid" 2>/dev/null
        if [ -n "$_saved_stty" ]; then stty "$_saved_stty" < /dev/tty 2>/dev/null; fi
        rm -f "$_tmp"
    }
    trap _cleanup_live EXIT INT TERM
    bwm-ng -o csv -c 0 -t 1000 > "$_tmp" 2>/dev/null &
    _bwm_pid=$!
    # terminal ke mode non-canonical supaya 'q' terbaca tanpa Enter (hanya bila ada tty).
    # Bila tidak ada controlling terminal (/dev/tty tak bisa dibuka), lewati diam-diam.
    _saved_stty=$(stty -g < /dev/tty 2>/dev/null) 2>/dev/null || _saved_stty=""
    if [ -n "$_saved_stty" ]; then
        stty -icanon min 0 time 0 < /dev/tty 2>/dev/null
    fi
    _elapsed=0
    _stopped=""
    while [ "$_elapsed" -lt "$_secs" ]; do
        sleep 1
        _elapsed=$((_elapsed + 1))
        # cek tombol q (non-blocking, dari terminal; abaikan bila tidak ada tty)
        if [ -n "$_saved_stty" ]; then
            _ch=$(dd bs=1 count=1 < /dev/tty 2>/dev/null)
            case "$_ch" in
                q|Q) _stopped="q"; break ;;
            esac
        fi
        _snap=$(_last_bw_snapshot "$_tmp")
        if [ -n "$_snap" ]; then
            if [ "$_is_tty" -eq 1 ]; then printf '\033[2J\033[H'; fi
            printf '%s\n' "$_snap" | _print_bw_table "Bandwidth (bwm-ng, live, bps) — detik $_elapsed/$_secs (q = berhenti):"
        fi
    done
    _cleanup_live
    trap - EXIT INT TERM
    if [ -n "$_stopped" ]; then
        printf '\nBerhenti (q ditekan) setelah %s detik.\n' "$_elapsed"
    fi
    exit 0
}

cmd_bandwidth() {
    # $1 = durasi detik (opsional, default 1 = satu snapshot)
    _secs=${1:-1}
    case "$_secs" in
        ''|*[!0-9]*) die "waktu harus angka detik (>= 1), contoh: show monitoring bandwidth 10" ;;
    esac
    if [ "$_secs" -lt 1 ]; then die "waktu harus >= 1 detik"; fi
    if [ "$_secs" -gt 3600 ]; then die "waktu maksimal 3600 detik (1 jam)"; fi
    if ! command -v bwm-ng >/dev/null 2>&1; then
        die "bwm-ng tidak terpasang (FreeBSD: pkg install net-mgmt/bwm-ng; Debian: apt install bwm-ng)"
    fi
    if [ "$_secs" -eq 1 ]; then
        _out=$(bwm-ng -o csv -c 1 -t 1000 2>/dev/null) || die "bwm-ng gagal dijalankan"
        if [ -z "$_out" ]; then die "bwm-ng tidak mengembalikan data"; fi
        printf '%s\n' "$_out" | _print_bw_table "Bandwidth (bwm-ng, snapshot 1 detik, bps):"
        exit 0
    fi
    _live_bandwidth "$_secs"
}

# --- mutations ---
cmd_set() {
    # $1=service $2=yes|no
    svc_name "$1" >/dev/null
    case "$2" in yes|no) ;; *) die "set butuh yes|no" ;; esac
    upsert "$1" "$2"
    echo "monitoring $1 $2 (pending commit)"
    exit 0
}

cmd_set_community() {
    case "$1" in ''|*' '*) die "community tidak boleh kosong/berspasi" ;; esac
    upsert snmp-community "$1"
    echo "monitoring snmp community diubah (pending commit — berlaku saat snmpd at-apply)"
    exit 0
}

# --- apply (dipanggil commit) ---
cmd_apply() {
    touch_intent
    for _s in snmp node-exporter bird-exporter nfacctd; do
        _name=$(svc_name "$_s")
        _want=$(intent_val "$_s")
        [ "$_want" = "unset" ] && _want=no
        if [ "$_s" = "snmp" ] && [ "$_want" = "yes" ]; then
            _comm=$(intent_val snmp-community)
            mkdir -p "$(dirname "$SNMP_CONF")" 2>/dev/null
            {
                echo "# snmpd.conf - generated by titian-monitoring.sh"
                echo "rocommunity ${_comm:-bsdrp-ro}"
                echo "syslocation BSDRP"
                echo "syscontact admin"
            } > "$SNMP_CONF.tmp.$$" || die "cannot write $SNMP_CONF"
            mv "$SNMP_CONF.tmp.$$" "$SNMP_CONF" || die "cannot write $SNMP_CONF"
            chmod 600 "$SNMP_CONF" 2>/dev/null || true
        fi
        if command -v service >/dev/null 2>&1; then
            if [ "$_want" = "yes" ]; then
                if command -v sysrc >/dev/null 2>&1; then sysrc "${_name}_enable=YES" >/dev/null || err "sysrc ${_name}_enable gagal"; fi
                if svc_running "$_name"; then service "$_name" restart || err "service $_name restart gagal"
                else service "$_name" start || err "service $_name start gagal"; fi
                echo "monitoring: $_name enabled + running"
            else
                # Berhenti DULU — pakai `onestop` (FreeBSD) agar tetap berhenti
                # walau enable sudah NO. `onestop` gagal di Linux -> fallback `stop`.
                service "$_name" onestop 2>/dev/null || service "$_name" stop 2>/dev/null || true
                if command -v sysrc >/dev/null 2>&1; then sysrc "${_name}_enable=NO" >/dev/null || err "sysrc ${_name}_enable gagal"; fi
                echo "monitoring: $_name disabled + stopped"
            fi
        else
            echo "(service no  at host ini — lewati: $_name $_want)"
        fi
    done
    rm -f "$DIRTY"
    exit 0
}

case "${1:-}" in
    check) cmd_check ;;
    show) cmd_show "${2:-}" ;;
    bandwidth) cmd_bandwidth "${2:-}" ;;
    set) cmd_set "${2:-}" "${3:-}" ;;
    set-community) cmd_set_community "${2:-}" ;;
    apply) cmd_apply ;;
    apply-all) cmd_apply ;;
    *) echo "Usage: $0 {check|show [service]|bandwidth [detik]|set <service> yes|no|set-community <string>|apply} ..." >&2; exit 2 ;;
esac
