#!/bin/sh
# titian-rpki.sh — RPKI intent (BIRD `protocol rpki`) untuk Titian/klish.
# Batch B9 program BIRD (P3).
# Pola sama seperti titian-mrt.sh: intent di /etc/titian/rpki.conf
# (tmpfs, dipersistenkan via titian-cfg.sh), generate menulis section
# BIRD /etc/titian/bird.d/rpki.conf lalu memanggil titian-bird.sh
# generate rpki (render + validasi + birdc). Section ditulis ulang
# UTUH tiap apply.
#
# Sintaks BIRD 2.16.1 yang dipakai (docs resmi bird.network,
# User's Guide 2.16.1, §6.16 RPKI — RPKI-RTR RFC 6810/8210):
#   roa4 table r4;
#   roa6 table r6;
#   protocol rpki {
#       debug all;
#       roa4 { table r4; };
#       roa6 { table r6; };
#       remote "rpki-validator.realmv6.org" port 8282;
#       retry keep 5;
#       refresh keep 30;
#       expire 600;
#   }
#   protocol rpki {
#       roa4 { table r4; };
#       roa6 { table r6; };
#       remote 127.0.0.1 port 2345;
#       transport ssh {
#           bird private key "/home/birdgeek/.ssh/id_rsa";
#           remote public key "/home/birdgeek/.ssh/known_hosts";
#           user "birdgeek";
#       };
#   }
# Satu cache server per instance; boleh beberapa instance (satu per
# cache). Transport default TCP tanpa autentikasi (port 323) atau
# SSHv2 (port 22). Validasi route memakai roa_check()/aspa_check()
# di filter — SUDAH ada di B5/B6 (titian-bgp.sh, jangan duplikasi di
# sini). Tabel ROA/ASPA didefinisikan di bgp.conf (roa-table-add /
# aspa-table-add, B5) atau global (table-add roa4/roa6); channel di
# sini hanya merujuknya.
# Default BIRD (docs §6.16): port 323 (TCP) / 22 (SSH); refresh 3600
# (< 86400); retry 600 (maks 7200); expire 7200 (600..172800);
# ignore max length disabled; min version 0; max version 2;
# transport tcp tanpa autentikasi; local address TIDAK dinyatakan
# docs — opsional tanpa default palsu.
# `keep` di refresh/retry/expire = jangan biarkan cache server
# meng-update nilai ini (nilai lokal dipertahankan).
# TIDAK ADA perintah birdc `show rpki` (Bab 4.3 terkonfirmasi) —
# status instance dilihat lewat `show protocols [all]`.
# TIDAK diimplementasi di batch ini:
#   - ROA/ASPA statis di protocol static (`route <prefix> max .. as ..`,
#     `route aspa ..`) — itu di titian-static.sh (S8/S9, B9).
#   - `rpki reload` per-channel — SUDAH ada di BGP (B6, 3.5-7).
#
# Format rpki.conf (satu baris per fakta):
#   instance <NAME> roa4-table <TAB>
#   instance <NAME> roa6-table <TAB>
#   instance <NAME> aspa-table <TAB>
#   instance <NAME> remote <IP|DOMAIN>
#   instance <NAME> remote-port <N>
#   instance <NAME> port <N>
#   instance <NAME> local-address <IP>
#   instance <NAME> refresh <N>
#   instance <NAME> refresh-keep <on|off>
#   instance <NAME> retry <N>
#   instance <NAME> retry-keep <on|off>
#   instance <NAME> expire <N>
#   instance <NAME> expire-keep <on|off>
#   instance <NAME> ignore-max-length <on|off>
#   instance <NAME> min-version <N>
#   instance <NAME> max-version <N>
#   instance <NAME> transport <tcp|ssh>
#   instance <NAME> tcp-auth <none|md5>
#   instance <NAME> tcp-password <TEXT>
#   instance <NAME> ssh-bird-key <PATH>
#   instance <NAME> ssh-remote-key <PATH>
#   instance <NAME> ssh-user <NAME>
#   instance <NAME> debug <SPEC>
#   instance <NAME> mrtdump <SPEC>

STATE_ROOT="${TITIAN_STATE_ROOT:-/etc/titian}"
CONF="$STATE_ROOT/rpki.conf"
GLOBAL_CONF="$STATE_ROOT/bird-global.conf"
# Pager global: output show >1 layar lewat less (titian-page.sh).
# Prologue dipanggil SESUDAH setup warna/TTY bila ada, SEBELUM output pertama.
SBIN_DIR=$(dirname "$0")
. "$SBIN_DIR/titian-page.sh"
# Hanya subcommand baca yang dipager: set/generate/commit TIDAK —
# output-nya harus tetap streaming/langsung, bukan tertahan sampai EXIT.
case "${1:-}" in show) titian_page_begin ;; esac

BGP_CONF="$STATE_ROOT/bgp.conf"
SECTION_DIR="$STATE_ROOT/bird.d"
SECTION="$SECTION_DIR/rpki.conf"
PROG="titian-rpki"
err() { echo "Error($PROG): $*" >&2; exit 33; }
die() { echo "$PROG: $*" >&2; exit 1; }

touch_conf() {
    if [ ! -f "$CONF" ]; then
        mkdir -p "$(dirname "$CONF")" 2>/dev/null
        printf '# rpki.conf - generated by klish, do not edit by hand\n' > "$CONF" \
            || die "cannot create $CONF"
        chmod 600 "$CONF" 2>/dev/null || true
    fi
}

upsert() {
    _re="$1"; _line="$2"
    touch_conf
    _tmp="$CONF.tmp.$$"
    grep -v "$_re" "$CONF" > "$_tmp" 2>/dev/null || true
    printf '%s\n' "$_line" >> "$_tmp"
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
    chmod 600 "$CONF" 2>/dev/null || true
}

dellines() {
    _re="$1"
    touch_conf
    _tmp="$CONF.tmp.$$"
    grep -v "$_re" "$CONF" > "$_tmp" 2>/dev/null || true
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
}

has_facts() {
    [ -f "$CONF" ] || return 1
    grep -v '^[[:space:]]*#' "$CONF" 2>/dev/null | grep -q '[^[:space:]]'
}

valid_name() {
    case "$1" in
        ''|*[!A-Za-z0-9_]*) err "$2 harus nama BIRD [A-Za-z0-9_]: $1" ;;
    esac
    case "$1" in [A-Za-z_]*) ;; *) err "$2 harus diawali huruf/underscore: $1" ;; esac
}

valid_uint() { # <nilai> <label> — bilangan bulat >= 0
    case "$1" in ''|*[!0-9]*) err "$2 harus bilangan bulat >= 0: $1" ;; esac
}

valid_num() { # <nilai> <min> <max> <label>
    valid_uint "$1" "$4"
    [ "$1" -ge "$2" ] 2>/dev/null || err "$4 harus $2..$3: $1"
    [ "$1" -le "$3" ] 2>/dev/null || err "$4 harus $2..$3: $1"
}

valid_ipv4() {
    _v="$1"; _l="$2"
    case "$_v" in *:*|*[!0-9.]*) err "$_l harus alamat IPv4: $_v" ;; esac
    [ "$(printf '%s' "$_v" | awk -F. '{print NF}')" = "4" ] || err "$_l harus alamat IPv4 (4 oktet): $_v"
    for _o in $(printf '%s' "$_v" | tr '.' ' '); do
        case "$_o" in ''|*[!0-9]*) err "$_l harus alamat IPv4: $_v" ;; esac
        [ "$_o" -le 255 ] 2>/dev/null || err "$_l harus alamat IPv4 (oktet 0..255): $_v"
    done
}

valid_ipv6() {
    _v="$1"; _l="$2"
    case "$_v" in *:*) ;; *) err "$_l harus alamat IPv6: $_v" ;; esac
    case "$_v" in *[!0-9A-Fa-f:.]*) err "$_l harus alamat IPv6 (karakter tidak valid): $_v" ;; esac
    case "$_v" in *[!:]:) err "$_l harus alamat IPv6 (':' tunggal di akhir): $_v" ;; esac
    case "$_v" in :[!:]*) err "$_l harus alamat IPv6 (':' di awal tanpa '::'): $_v" ;; esac
    _t=${_v#*::}
    case "$_t" in *::*) err "$_l harus alamat IPv6 ('::' hanya boleh sekali): $_v" ;; esac
}

valid_ip_any() {
    case "$1" in *:*) valid_ipv6 "$1" "$2" ;; *) valid_ipv4 "$1" "$2" ;; esac
}

valid_remote() { # IP v4/v6 atau FQDN (satu token, tanpa spasi/kutip/;)
    _v="$1"
    [ -n "$_v" ] || err "remote butuh IP atau domain cache server"
    case "$_v" in *' '*|*\"*|*\;*|*\`*|*'$'*|*\\*) err "remote tidak boleh mengandung spasi/kutip/;/\$/\\\\: $_v" ;; esac
    case "$_v" in
        *:* ) valid_ipv6 "$_v" "remote" ; return 0 ;;
        *.*)
            _first=${_v%%.*}
            case "$_first" in ''|*[!0-9]*) return 0 ;; esac
            valid_ipv4 "$_v" "remote" ; return 0 ;;
        *) err "remote harus IP atau domain (mengandung '.' atau ':'): $_v" ;;
    esac
}

valid_roa_table() { # $1=tabel $2=v4|v6|aspa — harus terdefinisi (global atau bgp.conf)
    _t="$1"; _k="$2"
    valid_name "$_t" "tabel ROA/ASPA"
    if [ "$_k" = "aspa" ]; then
        grep -q "^table aspa $_t\$" "$GLOBAL_CONF" 2>/dev/null && return 0
        grep -q "^aspa-table $_t\$" "$BGP_CONF" 2>/dev/null && return 0
        err "aspa table $_t belum didefinisikan (global -> table-add aspa $_t, atau bgp -> aspa-table-add $_t)"
    fi
    case "$_k" in v4) _nt=roa4 ;; v6) _nt=roa6 ;; esac
    grep -q "^table $_nt $_t\$" "$GLOBAL_CONF" 2>/dev/null && return 0
    grep -q "^roa-table $_t $_k\$" "$BGP_CONF" 2>/dev/null && return 0
    grep -q "^roa-table $_t\$" "$BGP_CONF" 2>/dev/null && return 0
    err "$_nt table $_t belum didefinisikan (global -> table-add $_nt $_t, atau bgp -> roa-table-add $_t $_k)"
}

inst_has() {
    grep -q "^instance $1 " "$CONF" 2>/dev/null
}

get_inst_field() {
    grep "^instance $1 $2 " "$CONF" 2>/dev/null | head -1 | awk '{print $4}'
}

_rpki_valid_spec() { # <SPEC> <debug|mrtdump>
    _rp_spec="$1"; _rp_kind="$2"
    [ -n "$_rp_spec" ] || err "$_rp_kind butuh all|off|kelas,kelas,..."
    case "$_rp_spec" in all|off) return 0 ;; esac
    _rp_rest="$_rp_spec"
    while [ -n "$_rp_rest" ]; do
        case "$_rp_rest" in *,*) _rp_done=${_rp_rest%%,*}; _rp_rest=${_rp_rest#*,} ;; *) _rp_done="$_rp_rest"; _rp_rest="" ;; esac
        if [ "$_rp_kind" = "debug" ]; then
            case "$_rp_done" in states|routes|filters|interfaces|events|packets) ;; *) err "debug kelas tidak dikenal: $_rp_done (boleh: states|routes|filters|interfaces|events|packets)" ;; esac
        else
            case "$_rp_done" in states|messages) ;; *) err "mrtdump kelas tidak dikenal: $_rp_done (boleh: states|messages)" ;; esac
        fi
    done
}

cmd_rpki_touch() {
    _n="$1"
    [ -n "$_n" ] || err "rpki butuh NAMA instance"
    valid_name "$_n" "rpki"
    touch_conf
    echo "RPKI $_n"
}

cmd_chan_table_set() { # chan-table-set <NAME> <roa4|roa6|aspa> <TAB>
    _n="$1"; _c="$2"; _t="$3"
    valid_name "$_n" "rpki"
    case "$_c" in roa4|roa6|aspa) ;; *) err "channel harus roa4|roa6|aspa: $_c" ;; esac
    [ -n "$_t" ] || err "$_c table butuh nama tabel"
    case "$_c" in roa4) valid_roa_table "$_t" v4 ;; roa6) valid_roa_table "$_t" v6 ;; aspa) valid_roa_table "$_t" aspa ;; esac
    upsert "^instance $_n $_c-table " "instance $_n $_c-table $_t"
    echo "RPKI $_n $_c table = $_t"
}

cmd_chan_table_del() {
    _n="$1"; _c="$2"
    valid_name "$_n" "rpki"
    case "$_c" in roa4|roa6|aspa) ;; *) err "channel harus roa4|roa6|aspa: $_c" ;; esac
    dellines "^instance $_n $_c-table "
    echo "RPKI $_n $_c table dihapus"
}

