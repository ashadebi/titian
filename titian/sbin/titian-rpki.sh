# --- getters (untuk generate) ---
# emit_instance <NAME>: cetak blok `protocol rpki <NAME> { ... }`.
emit_instance() {
    _n="$1"
    inst_has "$_n" || return 0
    _remote=$(get_inst_field "$_n" remote)
    [ -n "$_remote" ] || err "rpki $_n tanpa remote — remote MANDATORY (docs §6.16, RK4)"
    _rport=$(get_inst_field "$_n" remote-port)
    _port=$(get_inst_field "$_n" port)
    _local=$(get_inst_field "$_n" local-address)
    _refresh=$(get_inst_field "$_n" refresh)
    _refreshk=$(get_inst_field "$_n" refresh-keep)
    _retry=$(get_inst_field "$_n" retry)
    _retryk=$(get_inst_field "$_n" retry-keep)
    _expire=$(get_inst_field "$_n" expire)
    _expirek=$(get_inst_field "$_n" expire-keep)
    _iml=$(get_inst_field "$_n" ignore-max-length)
    _minv=$(get_inst_field "$_n" min-version)
    _maxv=$(get_inst_field "$_n" max-version)
    _trans=$(get_inst_field "$_n" transport)
    _tauth=$(get_inst_field "$_n" tcp-auth)
    _tpw=$(get_inst_field "$_n" tcp-password)
    _bkey=$(get_inst_field "$_n" ssh-bird-key)
    _rkey=$(get_inst_field "$_n" ssh-remote-key)
    _suser=$(get_inst_field "$_n" ssh-user)
    _dbg=$(get_inst_field "$_n" debug)
    _mrt=$(get_inst_field "$_n" mrtdump)
    if [ -n "$_minv" ] && [ -n "$_maxv" ]; then
        [ "$_minv" -le "$_maxv" ] 2>/dev/null || err "rpki $_n min-version $_minv > max-version $_maxv"
    fi
    if [ "$_trans" = "ssh" ]; then
        [ -n "$_suser" ] || err "rpki $_n transport ssh tanpa user — user REQUIRED di transport SSH (docs §6.16, RK19)"
        [ -n "$_tauth" ] || [ -n "$_tpw" ] || true
        if [ -n "$_tauth" ] || [ -n "$_tpw" ]; then
            err "rpki $_n transport ssh tidak boleh punya opsi TCP (tcp-auth/tcp-password) — hapus dulu"
        fi
    fi
    if [ "$_trans" = "tcp" ] || [ -z "$_trans" ]; then
        if [ -n "$_bkey" ] || [ -n "$_rkey" ] || [ -n "$_suser" ]; then
            err "rpki $_n transport tcp (atau default) tidak boleh punya opsi SSH (ssh-bird-key/ssh-remote-key/ssh-user) — set transport ssh dulu atau hapus"
        fi
    fi
    # B9: password TCP tanpa authentication md5 tidak bermakna (BIRD akan
    # menolak / mengabaikan) — tolak di generate.
    if [ -n "$_tpw" ] && [ "$_tauth" != "md5" ]; then
        err "rpki $_n tcp-password tanpa tcp-auth md5 — set dulu tcp-auth md5 (atau hapus password)"
    fi
    echo "protocol rpki $_n {"
    if [ -n "$_dbg" ]; then
        case "$_dbg" in all|off) echo "    debug $_dbg;" ;; *) echo "    debug { $(echo "$_dbg" | sed 's/,/, /g') };" ;; esac
    fi
    if [ -n "$_mrt" ]; then
        case "$_mrt" in all|off) echo "    mrtdump $_mrt;" ;; *) echo "    mrtdump { $(echo "$_mrt" | sed 's/,/, /g') };" ;; esac
    fi
    _t4=$(get_inst_field "$_n" roa4-table)
    _t6=$(get_inst_field "$_n" roa6-table)
    _ta=$(get_inst_field "$_n" aspa-table)
    [ -n "$_t4" ] && echo "    roa4 { table $_t4; };"
    [ -n "$_t6" ] && echo "    roa6 { table $_t6; };"
    [ -n "$_ta" ] && echo "    aspa { table $_ta; };"
    case "$_remote" in
        *:* ) _rem="$_remote" ;;
        *.*) case "${_remote%%.*}" in ''|*[!0-9]*) _rem="\"$_remote\"" ;; *) _rem="$_remote" ;; esac ;;
        *) _rem="\"$_remote\"" ;;
    esac
    if [ -n "$_rport" ]; then
        echo "    remote $_rem port $_rport;"
    else
        echo "    remote $_rem;"
    fi
    [ -n "$_port" ] && echo "    port $_port;"
    [ -n "$_local" ] && echo "    local address $_local;"
    if [ -n "$_retry" ]; then
        case "$_retryk" in on) echo "    retry keep $_retry;" ;; *) echo "    retry $_retry;" ;; esac
    fi
    if [ -n "$_refresh" ]; then
        case "$_refreshk" in on) echo "    refresh keep $_refresh;" ;; *) echo "    refresh $_refresh;" ;; esac
    fi
    if [ -n "$_expire" ]; then
        case "$_expirek" in on) echo "    expire keep $_expire;" ;; *) echo "    expire $_expire;" ;; esac
    fi
    case "$_iml" in
        on) echo "    ignore max length yes;" ;;
        off) echo "    ignore max length no;" ;;
    esac
    [ -n "$_minv" ] && echo "    min version $_minv;"
    [ -n "$_maxv" ] && echo "    max version $_maxv;"
    if [ "$_trans" = "tcp" ]; then
        if [ -n "$_tauth" ] || [ -n "$_tpw" ]; then
            echo "    transport tcp {"
            [ -n "$_tauth" ] && echo "        authentication $_tauth;"
            [ -n "$_tpw" ] && echo "        password \"$_tpw\";"
            echo "    };"
        else
            echo "    transport tcp;"
        fi
    elif [ "$_trans" = "ssh" ]; then
        echo "    transport ssh {"
        [ -n "$_bkey" ] && echo "        bird private key \"$_bkey\";"
        [ -n "$_rkey" ] && echo "        remote public key \"$_rkey\";"
        [ -n "$_suser" ] && echo "        user \"$_suser\";"
        echo "    };"
    fi
    echo "}"
    echo ""
}

cmd_generate() {
    touch_conf
    # B.2: tabel ROA/ASPA yang dirujuk section ini DIDEFINISIKAN di
    # section global — generate global DULU bila intent RPKI merujuk
    # tabel (r4/r6/aspa). Tanpa ini, generate RPKI langsung (di luar
    # commit — yang apply-nya global-dulu, lihat titian-commit.sh
    # apply_global) merender bird.conf dengan tabel tak-terdefinisi
    # -> bird -p gagal "undefined table" (rc 33). Setter chan-table-set
    # sudah memvalidasi tabel ada di intent global saat set
    # (valid_roa_table); yang diperbaiki di sini adalah URUTAN generate.
    if grep -q -e ' roa4-table ' -e ' roa6-table ' -e ' aspa-table ' "$CONF" 2>/dev/null; then
        if [ -f "$GLOBAL_CONF" ]; then
            _gsh="$(dirname "$0")/titian-global.sh"
            if [ -x "$_gsh" ]; then
                # JANGAN exit 33 bila generate global gagal: section
                # global sudah tertulis SEBELUM titian-global.sh memanggil
                # titian-bird.sh (yang gagal rc 33 di mock tanpa bird);
                # lanjut generate RPKI — validasi bird -p di akhir yang
                # menangkap tabel tak-terdefinisi bila ada.
                "$_gsh" generate || echo "Warning: titian-global.sh generate gagal — lanjut generate RPKI" >&2
            fi
        fi
    fi
    set -f
    mkdir -p "$SECTION_DIR" 2>/dev/null || die "cannot mkdir $SECTION_DIR"
    _tmp="$SECTION.tmp.$$"
    if has_facts; then
        {
            echo "# rpki.conf - generated by titian-rpki.sh, do not edit by hand"
            for _n in $(grep '^instance ' "$CONF" 2>/dev/null | awk '{print $2}' | awk '!s[$0]++'); do
                emit_instance "$_n"
            done
        } > "$_tmp" || die "cannot write $_tmp"
    else
        {
            echo "# rpki.conf - generated by titian-rpki.sh, do not edit by hand"
            echo "# (tidak ada config RPKI — protocol rpki tidak dibuat)"
        } > "$_tmp" || die "cannot write $_tmp"
    fi
    mv "$_tmp" "$SECTION" || die "cannot write $SECTION"
    chmod 644 "$SECTION" 2>/dev/null || true
    set +f
    echo "RPKI section ditulis: $SECTION"
    _birdsh="$(dirname "$0")/titian-bird.sh"
    if [ -x "$_birdsh" ]; then
        "$_birdsh" generate rpki || exit 33
    else
        echo "Warning: $_birdsh tidak ditemukan; section hanya ditulis, belum di-apply" >&2
    fi
}

birdc_bin() {
    command -v birdc 2>/dev/null || { [ -x /usr/sbin/birdc ] && echo /usr/sbin/birdc; } || \
        { [ -x /usr/local/sbin/birdc ] && echo /usr/local/sbin/birdc; } || echo birdc
}
# birdc_sock — salinan titian-birdc.sh (BC8, B13): cetak "-s <path>" bila
# socket utama dikonfigurasi via klish ($STATE_ROOT/birdc.conf), kosong bila
# default. Dipakai semua pemanggilan birdc di file ini.
birdc_sock() {
    _s=$(grep '^socket ' "$STATE_ROOT/birdc.conf" 2>/dev/null | head -1 | cut -d' ' -f2-)
    [ -n "$_s" ] && printf '%s' "-s $_s"
}


cmd_show() {
    touch_conf
    echo "--- rpki.conf (intent) ---"
    cat "$CONF"
    echo "--- bird.d/rpki.conf (section, bila ada) ---"
    [ -f "$SECTION" ] && cat "$SECTION" || echo "(belum di-generate)"
    echo "--- birdc show protocol (rpki; TIDAK ADA show rpki khusus — via show protocols) ---"
    _birdc=$(birdc_bin)
    _done=0
    for _n in $(grep '^instance ' "$CONF" 2>/dev/null | awk '{print $2}' | awk '!s[$0]++'); do
        if grep -q "protocol rpki $_n" "$SECTION" 2>/dev/null; then
            if _out=$("$_birdc" $(birdc_sock) show protocol "$_n" 2>&1); then
                echo "$_out" | grep -v '^BIRD'
                _done=1
            fi
        fi
    done
    [ "$_done" = "0" ] && echo "(BIRD tidak jalan / belum ada instance RPKI — birdc show protocol gagal)"
    return 0
}

