#!/bin/sh
# TITIAN BSDRP — PPPoE server (mpd5 5.9, netgraph).
# State klish: /usr/local/etc/pppoe.conf (mode 600 — berisi password
# user + radius secret). Config mpd5 yang dihasilkan:
#   /usr/local/etc/mpd5/mpd.conf + mpd.secret (mode 600).
# Format state (satu baris per item):
#   enable yes|no
#   interface <if>
#   pool <start-ip> <end-ip>
#   radius-server <ip>
#   radius-secret <secret>
#   user <name> <password> <ip|->            (password tanpa spasi)
# `enable` hanya mencatat niat + dirty; service mpd5 naik/berhenti
# saat `commit` (titian-commit.sh -> apply di sini).
# Sintaks mpd.conf di bawah ditulis dari dokumentasi mpd5 — BELUM
# teruji live di guest; verifikasi live wajib sebelum produksi.
# POSIX sh.
ROOT=${TITIAN_ROOT:-/opt/titian}
CONF="${PPPOE_CONF:-/usr/local/etc/pppoe.conf}"
MPD_DIR="${PPPOE_MPD_DIR:-/usr/local/etc/mpd5}"
MPD_CONF="$MPD_DIR/mpd.conf"
MPD_SECRET="$MPD_DIR/mpd.secret"
DIRTY=/var/run/pppoe.dirty
PROG="titian-pppoe"
err() { echo "Error($PROG): $*" >&2; exit 33; }
die() { echo "$PROG: $*" >&2; exit 1; }

touch_conf() {
    if [ ! -f "$CONF" ]; then
        mkdir -p "$(dirname "$CONF")" 2>/dev/null
        printf '# pppoe.conf - generated by klish, do not edit by hand\nenable no\n' > "$CONF" \
            || die "cannot create $CONF"
        chmod 600 "$CONF" 2>/dev/null || true
    fi
}

mark_dirty() { touch "$DIRTY" 2>/dev/null || true; }

upsert() {
    _re="$1"; _line="$2"
    touch_conf
    _tmp="$CONF.tmp.$$"
    grep -v "$_re" "$CONF" > "$_tmp" 2>/dev/null || true
    printf '%s\n' "$_line" >> "$_tmp"
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
    chmod 600 "$CONF" 2>/dev/null || true
    mark_dirty
}

dellines() {
    _re="$1"; _what="$2"
    touch_conf
    grep -q "$_re" "$CONF" 2>/dev/null || die "$_what not found"
    _tmp="$CONF.tmp.$$"
    grep -v "$_re" "$CONF" > "$_tmp" || true
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
    chmod 600 "$CONF" 2>/dev/null || true
    mark_dirty
}

valid_v4() {
    _a="$1"
    case "$_a" in *.*.*.*) ;; *) return 1 ;; esac
    _o1=${_a%%.*}; _r=${_a#*.}; _o2=${_r%%.*}; _r=${_r#*.}; _o3=${_r%%.*}; _o4=${_r#*.}
    case "$_o4" in *.*) return 1 ;; esac
    for _o in "$_o1" "$_o2" "$_o3" "$_o4"; do
        case "$_o" in ''|*[!0-9]*) return 1 ;; esac
        [ "$_o" -ge 0 ] 2>/dev/null && [ "$_o" -le 255 ] 2>/dev/null || return 1
    done
    return 0
}

iface_exists() {
    ifconfig "$1" >/dev/null 2>&1 || die "interface $1 not found (see 'show interfaces')"
}

user_exists() { grep -q "^user $1 " "$CONF" 2>/dev/null; }

# --- read-only ---
cmd_check() { touch_conf; exit 0; }

cmd_show() {
    touch_conf
    _en=$(sed -n 's/^enable //p' "$CONF" | head -1)
    _if=$(sed -n 's/^interface //p' "$CONF" | head -1)
    _pool=$(sed -n 's/^pool //p' "$CONF" | head -1)
    _rs=$(sed -n 's/^radius-server //p' "$CONF" | head -1)
    _n=$(grep -c '^user ' "$CONF" 2>/dev/null || echo 0)
    echo "pppoe-server: ${_en:-no}"
    echo "interface: ${_if:-unset}"
    echo "pool: ${_pool:-unset}"
    echo "radius-server: ${_rs:-local auth}"
    echo "users: $_n"
    if command -v service >/dev/null 2>&1; then
        service mpd5 status 2>&1 | sed 's/^/  /' || true
    elif pgrep -x mpd5 >/dev/null 2>&1; then
        echo "  mpd5 running (pid $(pgrep -x mpd5 | head -1))"
    else
        echo "  mpd5 not running"
    fi
    exit 0
}

cmd_show_users() {
    touch_conf
    if ! grep -q '^user ' "$CONF" 2>/dev/null; then echo "(no users)"; exit 0; fi
    printf '%-20s %s\n' "USER" "STATIC-IP"
    grep '^user ' "$CONF" | while read -r _u _n _p _ip; do
        printf '%-20s %s\n' "$_n" "${_ip:-pool}"
    done
    exit 0
}

cmd_show_sessions() {
    # Sesi PPPoE = interface netgraph ng* yang dibuat mpd5. Best-effort:
    # tanpa mpd5 control socket, yang bisa ditampilkan adalah ng* yang ada.
    _found=0
    for _if in $(ifconfig -l 2>/dev/null); do
        case "$_if" in
            ng*) _found=1; ifconfig "$_if" 2>/dev/null | head -3 | sed 's/^/  /' ;;
        esac
    done
    [ "$_found" = "1" ] || echo "(no active PPPoE sessions / no ng* interfaces)"
    exit 0
}

# --- mutations ---
cmd_set_enable() {
    case "$1" in yes|no) upsert '^enable ' "enable $1" ;; *) die "enable takes yes|no" ;; esac
    echo "pppoe-server $1 (pending commit)"
    exit 0
}

cmd_set_interface() {
    iface_exists "$1"
    upsert '^interface ' "interface $1"
    echo "pppoe-server interface $1 (pending commit)"
    exit 0
}

cmd_del_interface() { dellines '^interface ' "interface"; echo "pppoe-server interface dihapus"; exit 0; }

cmd_set_pool() {
    valid_v4 "$1" || die "pool start harus IPv4: $1"
    valid_v4 "$2" || die "pool end harus IPv4: $2"
    upsert '^pool ' "pool $1 $2"
    echo "pppoe-server pool $1 - $2 (pending commit)"
    exit 0
}

cmd_del_pool() { dellines '^pool ' "pool"; echo "pppoe-server pool dihapus"; exit 0; }

cmd_user_add() {
    case "$1" in ''|*[!A-Za-z0-9_-]*) die "nama user tidak valid: $1" ;; esac
    touch_conf
    user_exists "$1" && { echo "pppoe user $1 sudah ada"; exit 0; }
    printf 'user %s %s -\n' "$1" "changeme" >> "$CONF" || die "cannot write $CONF"
    chmod 600 "$CONF" 2>/dev/null || true
    mark_dirty
    echo "pppoe user $1 added (password default 'changeme' — segera set via password)"
    exit 0
}

cmd_user_del() {
    dellines "^user $1 " "user $1"
    echo "pppoe user $1 deleted"
    exit 0
}

cmd_user_set_password() {
    # $1=user $2=password (tanpa spasi — format state satu baris)
    _name="$1"; _pass="$2"
    case "$_pass" in *' '*) die "password tidak boleh mengandung spasi" ;; '' ) die "password tidak boleh kosong" ;; esac
    touch_conf
    user_exists "$_name" || die "user $_name tidak ada (buat dulu: user $_name)"
    _line=$(grep "^user $_name " "$CONF" | head -1)
    set -- $_line
    _ip="${4:--}"
    upsert "^user $_name " "user $_name $_pass $_ip"
    echo "pppoe user $_name: password diubah"
    exit 0
}

cmd_user_set_ip() {
    _name="$1"; _addr="$2"
    valid_v4 "$_addr" || die "IP harus IPv4: $_addr"
    touch_conf
    user_exists "$_name" || die "user $_name tidak ada"
    _line=$(grep "^user $_name " "$CONF" | head -1)
    set -- $_line
    _pw="${3:-changeme}"
    upsert "^user $_name " "user $_name $_pw $_addr"
    echo "pppoe user $_name: static IP $_addr"
    exit 0
}

cmd_user_del_ip() {
    _name="$1"
    touch_conf
    user_exists "$_name" || die "user $_name tidak ada"
    _line=$(grep "^user $_name " "$CONF" | head -1)
    set -- $_line
    _pw="${3:-changeme}"
    upsert "^user $_name " "user $_name $_pw -"
    echo "pppoe user $_name: IP statis deleted (back to pool)"
    exit 0
}

cmd_set_radius_server() {
    valid_v4 "$1" || die "radius-server harus IPv4: $1"
    upsert '^radius-server ' "radius-server $1"
    echo "pppoe radius-server $1 (pending commit)"
    exit 0
}

cmd_del_radius_server() { dellines '^radius-server ' "radius-server"; echo "radius-server dihapus (auth lokal)"; exit 0; }

cmd_set_radius_secret() {
    case "$1" in ''|*' '*) die "radius-secret tidak boleh kosong/berspasi" ;; esac
    upsert '^radius-secret ' "radius-secret $1"
    echo "pppoe radius-secret diubah (pending commit)"
    exit 0
}

cmd_del_radius_secret() { dellines '^radius-secret ' "radius-secret"; echo "radius-secret dihapus"; exit 0; }

cmd_flush() {
    printf '# pppoe.conf - generated by klish, do not edit by hand\nenable no\n' > "$CONF" \
        || die "cannot write $CONF"
    chmod 600 "$CONF" 2>/dev/null || true
    mark_dirty
    echo "pppoe-server: all konfigurasi deleted (pending commit)"
    exit 0
}

# --- apply (dipanggil commit) ---
cmd_apply() {
    touch_conf
    _en=$(sed -n 's/^enable //p' "$CONF" | head -1)
    _if=$(sed -n 's/^interface //p' "$CONF" | head -1)
    _pool=$(sed -n 's/^pool //p' "$CONF" | head -1)
    _rs=$(sed -n 's/^radius-server //p' "$CONF" | head -1)
    _rsec=$(sed -n 's/^radius-secret //p' "$CONF" | head -1)
    if [ "$_en" != "yes" ]; then
        # Berhenti DULU — pakai `onestop` (FreeBSD) agar tetap berhenti
        # walau mpd_enable sudah NO. `onestop` gagal di Linux -> fallback `stop`.
        if command -v service >/dev/null 2>&1; then service mpd5 onestop 2>/dev/null || service mpd5 stop 2>/dev/null || true; fi
        if command -v sysrc >/dev/null 2>&1; then sysrc mpd_enable="NO" >/dev/null; fi
        echo "pppoe-server: disabled + stopped"
        return 0
    fi
    [ -n "$_if" ] || die "pppoe-server enable tapi interface belum di-set (interface <if>)"
    [ -n "$_pool" ] || die "pppoe-server enable tapi pool belum di-set (pool <start> <end>)"
    set -- $_pool; _pstart="$1"; _pend="$2"
    mkdir -p "$MPD_DIR" 2>/dev/null || die "cannot mkdir $MPD_DIR"
    {
        echo "# mpd.conf - generated by titian-pppoe.sh, do not edit by hand"
        echo "startup:"
        echo "    set console ip 127.0.0.1 5005"
        echo "    set console open"
        echo "default:"
        echo "    load pppoe_server"
        echo "pppoe_server:"
        echo "    create bundle template B"
        echo "    set bundle enable compression"
        echo "    set iface enable proxy-arp"
        echo "    set ipcp ranges 10.254.254.1/32 ${_pstart}-${_pend}"
        echo "    create link template L pppoe"
        echo "    set link action bundle B"
        echo "    set pppoe service \"*\""
        echo "    set pppoe iface ${_if}"
        if [ -n "$_rs" ]; then
            echo "    set radius server ${_rs} ${_rsec:-secret} 1812 1813"
            echo "    set radius retries 3"
            echo "    set radius timeout 3"
            echo "    set auth enable radius"
        else
            echo "    set auth enable local"
        fi
        echo "    set link enable incoming"
    } > "$MPD_CONF.tmp.$$" || die "cannot write $MPD_CONF"
    mv "$MPD_CONF.tmp.$$" "$MPD_CONF" || die "cannot write $MPD_CONF"
    : > "$MPD_SECRET.tmp.$$" || die "cannot write $MPD_SECRET"
    grep '^user ' "$CONF" 2>/dev/null | while read -r _u _n _p _ip; do
        if [ "$_ip" = "-" ] || [ -z "$_ip" ]; then
            printf '%s "%s"\n' "$_n" "$_p" >> "$MPD_SECRET.tmp.$$"
        else
            printf '%s "%s" %s\n' "$_n" "$_p" "$_ip" >> "$MPD_SECRET.tmp.$$"
        fi
    done
    mv "$MPD_SECRET.tmp.$$" "$MPD_SECRET" || die "cannot write $MPD_SECRET"
    chmod 600 "$MPD_CONF" "$MPD_SECRET" 2>/dev/null || true
    if command -v sysrc >/dev/null 2>&1; then sysrc mpd_enable="YES" >/dev/null || die "sysrc mpd_enable gagal"; fi
    if command -v service >/dev/null 2>&1; then
        if pgrep -x mpd5 >/dev/null 2>&1; then service mpd5 restart || die "service mpd5 restart gagal"
        else service mpd5 start || die "service mpd5 start gagal"; fi
    else
        echo "(service no  at host ini — lewati start mpd5; config tertulis at $MPD_CONF)"
    fi
    echo "pppoe-server: enabled + applied (iface $_if, pool $_pstart-$_pend)"
    return 0
}

case "${1:-}" in
    check) cmd_check ;;
    show) cmd_show ;;
    show-users) cmd_show_users ;;
    show-sessions) cmd_show_sessions ;;
    set-enable) cmd_set_enable "${2:-}" ;;
    set-interface) cmd_set_interface "${2:-}" ;;
    del-interface) cmd_del_interface ;;
    set-pool) cmd_set_pool "${2:-}" "${3:-}" ;;
    del-pool) cmd_del_pool ;;
    user-add) cmd_user_add "${2:-}" ;;
    user-del) cmd_user_del "${2:-}" ;;
    user-set-password) cmd_user_set_password "${2:-}" "${3:-}" ;;
    user-set-ip) cmd_user_set_ip "${2:-}" "${3:-}" ;;
    user-del-ip) cmd_user_del_ip "${2:-}" ;;
    set-radius-server) cmd_set_radius_server "${2:-}" ;;
    del-radius-server) cmd_del_radius_server ;;
    set-radius-secret) cmd_set_radius_secret "${2:-}" ;;
    del-radius-secret) cmd_del_radius_secret ;;
    flush) cmd_flush ;;
    apply) cmd_apply ;;
    apply-all) cmd_apply ;;
    *) echo "Usage: $0 {check|show|show-users|show-sessions|set-enable|set-interface|del-interface|set-pool|del-pool|user-add|user-del|user-set-password|user-set-ip|user-del-ip|set-radius-server|del-radius-server|set-radius-secret|del-radius-secret|flush|apply} ..." >&2; exit 2 ;;
esac
