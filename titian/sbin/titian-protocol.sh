            valid_spec "$_v" "mrtdump"
            upsert_file "$DCONF" '^mrtdump ' "mrtdump $_v" ;;
        disabled)
            case "$_v" in
                on|off) upsert_file "$DCONF" '^disabled ' "disabled $_v" ;;
                *) err "disabled harus on|off: $_v" ;;
            esac ;;
        *) err "field device tidak dikenal: $_f (debug|mrtdump|disabled)" ;;
