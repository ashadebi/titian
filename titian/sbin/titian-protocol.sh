}

cmd_device_set() { # device-set <debug|mrtdump|disabled> <nilai> (Bab 3.4-2/3/1)
    _f="$1"; _v="$2"; _ff="$_f" # _ff: upsert_file menimpa $_f (path file)
    [ -n "$_f" ] && [ -n "$_v" ] || err "device-set butuh FIELD VALUE"
    touch_dconf
    case "$_f" in
        debug)
            valid_spec "$_v" "debug"
            upsert_file "$DCONF" '^debug ' "debug $_v" ;;
