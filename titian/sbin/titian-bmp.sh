#!/bin/sh
# titian-bmp.sh — BMP intent (BIRD `protocol bmp`) untuk Titian/klish.
# Batch B9 program BIRD (P3).
# Pola sama seperti titian-radv.sh (satu instance tetap): intent di
# /etc/titian/bmp.conf (tmpfs, dipersistenkan via titian-cfg.sh),
# generate menulis section BIRD /etc/titian/bird.d/bmp.conf lalu
# memanggil titian-bird.sh generate bmp (render + validasi + birdc).
# Section ditulis ulang UTUH tiap apply.
#
# Sintaks BIRD 2.16.1 yang dipakai (docs resmi bird.network,
# User's Guide 2.16.1, §6.5 BMP — BGP Monitoring Protocol RFC 7854):
#   protocol bmp {
#       station address ip 198.51.100.10 port 1790;
#       monitoring rib in pre_policy;
#       monitoring rib in post_policy;
#       tx buffer limit 64;
#   }
# Implementasi BIRD saat ini PRELIMINARY, feature set terbatas, TIDAK
# siap produksi, dan TIDAK dikompilasi secara default — harus diaktifkan
# saat instalasi via configure option `--with-protocols=`. Semua
# protokol BGP dimonitor OTOMATIS. Butuh BMP station (collector)
# eksternal — tanpa station, tidak ada yang menerima data. Judul
# sub-bab docs: "Configuration (incomplete)".
# Hanya `tx buffer limit` yang dijelaskan di teks docs (default 1024 MB);
# `station address ip ... port ...`, `monitoring rib in pre_policy`,
# `monitoring rib in post_policy` HANYA muncul di contoh tanpa penjelasan
# teks — klish hanya memetakan 4 item itu, TANPA menebak varian lain
# (multi-station? retry? TLS? varian rib lain? TIDAK diketahui docs).
# TIDAK ADA perintah birdc `show bmp` (Bab 4.3 terkonfirmasi) — status
# dilihat lewat `show protocols [all]`.
#
# Format bmp.conf (satu baris per fakta):
#   station <IP> <PORT>
#   monitoring-rib-in <pre_policy|post_policy>
#   tx-buffer-limit <N>
#   debug <SPEC>
#   mrtdump <SPEC>

STATE_ROOT="${TITIAN_STATE_ROOT:-/etc/titian}"
CONF="$STATE_ROOT/bmp.conf"
SECTION_DIR="$STATE_ROOT/bird.d"
SECTION="$SECTION_DIR/bmp.conf"
PROG="titian-bmp"
err() { echo "Error($PROG): $*" >&2; exit 33; }
die() { echo "$PROG: $*" >&2; exit 1; }

touch_conf() {
    if [ ! -f "$CONF" ]; then
        mkdir -p "$(dirname "$CONF")" 2>/dev/null
        printf '# bmp.conf - generated by klish, do not edit by hand\n' > "$CONF" \
            || die "cannot create $CONF"
        chmod 600 "$CONF" 2>/dev/null || true
    fi
}

upsert() {
    _re="$1"; _line="$2"
    touch_conf
    _tmp="$CONF.tmp.$$"
    grep -v "$_re" "$CONF" > "$_tmp" 2>/dev/null || true
    printf '%s\n' "$_line" >> "$_tmp"
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
    chmod 600 "$CONF" 2>/dev/null || true
}

dellines() {
    _re="$1"
    touch_conf
    _tmp="$CONF.tmp.$$"
    grep -v "$_re" "$CONF" > "$_tmp" 2>/dev/null || true
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
}

has_facts() {
    [ -f "$CONF" ] || return 1
    grep -v '^[[:space:]]*#' "$CONF" 2>/dev/null | grep -q '[^[:space:]]'
}

valid_ipv4() {
    _v="$1"; _l="$2"
    case "$_v" in *:*|*[!0-9.]*) err "$_l harus alamat IPv4: $_v" ;; esac
    [ "$(printf '%s' "$_v" | awk -F. '{print NF}')" = "4" ] || err "$_l harus alamat IPv4 (4 oktet): $_v"
    for _o in $(printf '%s' "$_v" | tr '.' ' '); do
        case "$_o" in ''|*[!0-9]*) err "$_l harus alamat IPv4: $_v" ;; esac
        [ "$_o" -le 255 ] 2>/dev/null || err "$_l harus alamat IPv4 (oktet 0..255): $_v"
    done
}

valid_ipv6() {
    _v="$1"; _l="$2"
    case "$_v" in *:*) ;; *) err "$_l harus alamat IPv6: $_v" ;; esac
    case "$_v" in *[!0-9A-Fa-f:.]*) err "$_l harus alamat IPv6 (karakter tidak valid): $_v" ;; esac
    case "$_v" in *[!:]:) err "$_l harus alamat IPv6 (':' tunggal di akhir): $_v" ;; esac
    case "$_v" in :[!:]*) err "$_l harus alamat IPv6 (':' di awal tanpa '::'): $_v" ;; esac
    _t=${_v#*::}
    case "$_t" in *::*) err "$_l harus alamat IPv6 ('::' hanya boleh sekali): $_v" ;; esac
}

valid_ip_any() {
    case "$1" in *:*) valid_ipv6 "$1" "$2" ;; *) valid_ipv4 "$1" "$2" ;; esac
}

_bmp_valid_spec() {
    _bp_spec="$1"; _bp_kind="$2"
    [ -n "$_bp_spec" ] || err "$_bp_kind butuh all|off|kelas,kelas,..."
    case "$_bp_spec" in all|off) return 0 ;; esac
    _bp_rest="$_bp_spec"
    while [ -n "$_bp_rest" ]; do
        case "$_bp_rest" in *,*) _bp_done=${_bp_rest%%,*}; _bp_rest=${_bp_rest#*,} ;; *) _bp_done="$_bp_rest"; _bp_rest="" ;; esac
        if [ "$_bp_kind" = "debug" ]; then
            case "$_bp_done" in states|routes|filters|interfaces|events|packets) ;; *) err "debug kelas tidak dikenal: $_bp_done (boleh: states|routes|filters|interfaces|events|packets)" ;; esac
        else
            case "$_bp_done" in states|messages) ;; *) err "mrtdump kelas tidak dikenal: $_bp_done (boleh: states|messages)" ;; esac
        fi
    done
}

cmd_bmp_touch() {
    touch_conf
    echo "BMP"
}

cmd_station_set() {
    _ip="$1"; _port="$2"
    [ -n "$_ip" ] && [ -n "$_port" ] || err "station butuh IP + PORT (mis. 198.51.100.10 1790)"
    valid_ip_any "$_ip" "station address"
    case "$_port" in ''|*[!0-9]*) err "station port harus bilangan 1..65535: $_port" ;; esac
    [ "$_port" -ge 1 ] 2>/dev/null && [ "$_port" -le 65535 ] 2>/dev/null || err "station port harus 1..65535: $_port"
    upsert '^station ' "station $_ip $_port"
    echo "BMP station = $_ip port $_port"
}

cmd_station_del() {
    dellines '^station '
    echo "BMP station dihapus (tanpa station, tidak ada tujuan — generate akan menolak)"
}

cmd_mon_set() {
    _v="$1"
    case "$_v" in pre_policy|post_policy) ;; *) err "monitoring-rib-in harus pre_policy|post_policy: $_v" ;; esac
    upsert "^monitoring-rib-in $_v\$" "monitoring-rib-in $_v"
    echo "BMP monitoring-rib-in = $_v"
}

cmd_mon_del() {
    _v="$1"
    case "$_v" in pre_policy|post_policy) ;; *) err "monitoring-rib-in harus pre_policy|post_policy: $_v" ;; esac
    dellines "^monitoring-rib-in $_v\$"
    echo "BMP monitoring-rib-in $_v dihapus"
}

cmd_tx_set() {
    _v="$1"
    case "$_v" in ''|*[!0-9]*) err "tx-buffer-limit harus bilangan 1..4294967295 (MB): $_v" ;; esac
    [ "$_v" -ge 1 ] 2>/dev/null && [ "$_v" -le 4294967295 ] 2>/dev/null || err "tx-buffer-limit harus 1..4294967295 (MB): $_v"
    upsert '^tx-buffer-limit ' "tx-buffer-limit $_v"
    echo "BMP tx-buffer-limit = $_v MB"
}

cmd_tx_del() {
    dellines '^tx-buffer-limit '
    echo "BMP tx-buffer-limit dihapus (default BIRD 1024 MB)"
}

cmd_debug_set() {
    _bmp_valid_spec "$1" debug
    upsert '^debug ' "debug $1"
    echo "BMP debug = $1"
}

cmd_debug_del() {
    dellines '^debug '
    echo "BMP debug dihapus (default BIRD off)"
}

cmd_mrtdump_set() {
    _bmp_valid_spec "$1" mrtdump
    upsert '^mrtdump ' "mrtdump $1"
    echo "BMP mrtdump = $1"
}

cmd_mrtdump_del() {
    dellines '^mrtdump '
    echo "BMP mrtdump dihapus (default BIRD off)"
}

cmd_generate() {
    touch_conf
    set -f
    mkdir -p "$SECTION_DIR" 2>/dev/null || die "cannot mkdir $SECTION_DIR"
    _tmp="$SECTION.tmp.$$"
    if has_facts; then
        _station=$(grep '^station ' "$CONF" 2>/dev/null | head -1)
        [ -n "$_station" ] || err "BMP tanpa station — station MANDATORY (tanpa ini tidak ada tujuan, docs §6.5)"
        _dbg=$(grep '^debug ' "$CONF" 2>/dev/null | head -1 | awk '{print $2}')
        _mrt=$(grep '^mrtdump ' "$CONF" 2>/dev/null | head -1 | awk '{print $2}')
        _tx=$(grep '^tx-buffer-limit ' "$CONF" 2>/dev/null | head -1 | awk '{print $2}')
        _sip=$(echo "$_station" | awk '{print $2}')
        _sport=$(echo "$_station" | awk '{print $3}')
        {
            echo "# bmp.conf - generated by titian-bmp.sh, do not edit by hand"
            echo "protocol bmp {"
            if [ -n "$_dbg" ]; then
                case "$_dbg" in all|off) echo "    debug $_dbg;" ;; *) echo "    debug { $(echo "$_dbg" | sed 's/,/, /g') };" ;; esac
            fi
            if [ -n "$_mrt" ]; then
                case "$_mrt" in all|off) echo "    mrtdump $_mrt;" ;; *) echo "    mrtdump { $(echo "$_mrt" | sed 's/,/, /g') };" ;; esac
            fi
            echo "    station address ip $_sip port $_sport;"
            grep '^monitoring-rib-in ' "$CONF" 2>/dev/null | awk '{print "    monitoring rib in " $2 ";"}'
            [ -n "$_tx" ] && echo "    tx buffer limit $_tx;"
            echo "}"
            echo ""
        } > "$_tmp" || die "cannot write $_tmp"
    else
        {
            echo "# bmp.conf - generated by titian-bmp.sh, do not edit by hand"
            echo "# (tidak ada config BMP — protocol bmp tidak dibuat)"
        } > "$_tmp" || die "cannot write $_tmp"
    fi
    mv "$_tmp" "$SECTION" || die "cannot write $SECTION"
    chmod 644 "$SECTION" 2>/dev/null || true
    set +f
    echo "BMP section ditulis: $SECTION"
    _birdsh="$(dirname "$0")/titian-bird.sh"
    if [ -x "$_birdsh" ]; then
        "$_birdsh" generate bmp || exit 33
    else
        echo "Warning: $_birdsh tidak ditemukan; section hanya ditulis, belum di-apply" >&2
    fi
}

birdc_bin() {
    command -v birdc 2>/dev/null || { [ -x /usr/sbin/birdc ] && echo /usr/sbin/birdc; } || \
        { [ -x /usr/local/sbin/birdc ] && echo /usr/local/sbin/birdc; } || echo birdc
}
# birdc_sock — salinan titian-birdc.sh (BC8, B13): cetak "-s <path>" bila
# socket utama dikonfigurasi via klish ($STATE_ROOT/birdc.conf), kosong bila
# default. Dipakai semua pemanggilan birdc di file ini.
birdc_sock() {
    _s=$(grep '^socket ' "$STATE_ROOT/birdc.conf" 2>/dev/null | head -1 | cut -d' ' -f2-)
    [ -n "$_s" ] && printf '%s' "-s $_s"
}


cmd_show() {
    touch_conf
    echo "--- bmp.conf (intent) ---"
    cat "$CONF"
    echo "--- bird.d/bmp.conf (section, bila ada) ---"
    [ -f "$SECTION" ] && cat "$SECTION" || echo "(belum di-generate)"
    echo "--- birdc show protocol (bmp; TIDAK ADA show bmp khusus — via show protocols) ---"
    _birdc=$(birdc_bin)
    if _out=$("$_birdc" $(birdc_sock) show protocol bmp 2>&1); then
        echo "$_out" | grep -v '^BIRD'
    else
        echo "(BIRD tidak jalan / protocol bmp belum ada — birdc show protocol bmp gagal)"
    fi
    return 0
}

case "$1" in
    bmp-touch) cmd_bmp_touch ;;
    has-facts) has_facts ;;
    station-set) shift; cmd_station_set "$@" ;;
    station-del) cmd_station_del ;;
    monitoring-rib-in-set) shift; cmd_mon_set "$@" ;;
    monitoring-rib-in-del) shift; cmd_mon_del "$@" ;;
    tx-buffer-limit-set) shift; cmd_tx_set "$@" ;;
    tx-buffer-limit-del) cmd_tx_del ;;
    debug-set) shift; cmd_debug_set "$@" ;;
    debug-del) cmd_debug_del ;;
    mrtdump-set) shift; cmd_mrtdump_set "$@" ;;
    mrtdump-del) cmd_mrtdump_del ;;
    generate) cmd_generate ;;
    show) cmd_show ;;
    *) echo "Usage: $0 {bmp-touch|has-facts|station-set IP PORT|station-del|monitoring-rib-in-set pre_policy|post_policy|monitoring-rib-in-del pre_policy|post_policy|tx-buffer-limit-set N|tx-buffer-limit-del|debug-set SPEC|debug-del|mrtdump-set SPEC|mrtdump-del|generate|show}" >&2; exit 2 ;;
esac
