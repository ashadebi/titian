#!/bin/sh
# titian-aggregator.sh — Aggregator intent (BIRD `protocol aggregator`)
# untuk Titian/klish. Batch B8 program BIRD.
# CATATAN F3.2: `protocol aggregator` TIDAK ada di BIRD 2.20.0 (bird -p
# menolak: CF_SYM_UNDEFINED) — fitur BIRD 3. Generator ini dipertahankan
# untuk BIRD 3; JANGAN dipakai di BIRD 2.20 (config yang dihasilkan
# ditolak bird -p). Item AG1-AG6 di BIRD-COVERAGE.md = N/A untuk BIRD 2.20.
# Pola sama seperti titian-rip.sh: intent di /etc/titian/aggregator.conf
# (tmpfs, dipersistenkan via titian-cfg.sh), generate menulis section
# BIRD /etc/titian/bird.d/aggregator.conf lalu memanggil titian-bird.sh
# generate aggregator (render + validasi + birdc). Section ditulis ulang
# UTUH tiap apply.
#
# Sintaks BIRD 2.16.1 yang dipakai (docs resmi bird.network,
# User's Guide 2.16.1, §6.1 Aggregator):
#   protocol aggregator <name> {
#       table <table>;
#       export where defined(bgp_path);
#       aggregate on net, bgp_path.len;
#       merge by {
#           for route r in routes do {
#               if ! defined(bgp_path) then { bgp_path = r.bgp_path }
#               bgp_community = bgp_community.add(r.bgp_community);
#           }
#           accept;
#       };
#       import all;
#       peer table agr_result;
#   }
# Protokol EKSPERIMENTAL ("use with caution" — docs). Empat fase:
# (1) filter route (export), (2) sortir ke bucket (aggregate on),
# (3) merge bucket (merge by), (4) filter hasil sekali lagi (import).
# Meng-aggregate route yang sudah hasil agregasi DILARANG (docs).
# `aggregate on`: `net` saat ini MANDATORY ("we can't merge prefixes
# yet" — docs); ekspresi/atribut harus bertipe compact (integer,
# community BGP std/ext/large, IP address).
# `merge by`: blok filter INLINE — TIDAK bisa pakai named filter
# (docs); simbol khusus `routes`; route harus difinalisasi `accept`.
# `import` (sesudah merge by) BOLEH pakai named filter.
# `peer table` boleh sama dengan `table`.
# Default BIRD yang TIDAK dinyatakan docs (JANGAN ditebak): `table`
# dan `peer table` dibiarkan kosong bila tidak di-set (BIRD yang
# memakai defaultnya); `export`/`import` default `all` bila tidak
# di-set (sama seperti pola klish RIP/OSPF — default klish, bukan
# klaim default BIRD).
#
# TIDAK diimplementasi di batch ini:
#   - Builder terstruktur untuk isi `merge by` (if/for/set per
#     perintah klish): isi merge-by ditulis sebagai baris kode BIRD
#     mentah lewat `merge-line` (maks 8 kata/baris di klish — BIRD
#     tidak peduli spasi/baris baru, jadi baris panjang boleh
#     dipecah). Validasi: tanpa `/*`, `"`, `\`, backtick, `$`;
#     kurung kurawal harus seimbang; wajib mengandung `accept`.
#     Validasi sintaks penuh oleh `bird -p` saat generate.
#   - `aggregate on` dengan ekspresi compound bebas (mis. fungsi):
#     hanya atribut dari daftar putih + atribut int kustom.
#
# Format aggregator.conf (satu baris per fakta):
#   instance <NAME> table <TABEL>
#   instance <NAME> export <all|none|filter NAMA>
#   instance <NAME> import <all|none|filter NAMA>
#   instance <NAME> aggregate-on <net[,ATTR...]>   (tanpa spasi)
#   instance <NAME> merge <BARIS KODE BIRD>
#   instance <NAME> peer-table <TABEL>

STATE_ROOT="${TITIAN_STATE_ROOT:-/etc/titian}"
CONF="$STATE_ROOT/aggregator.conf"
GLOBAL_CONF="$STATE_ROOT/bird-global.conf"
SECTION_DIR="$STATE_ROOT/bird.d"
SECTION="$SECTION_DIR/aggregator.conf"
PROG="titian-aggregator"
err() { echo "Error($PROG): $*" >&2; exit 33; }
die() { echo "$PROG: $*" >&2; exit 1; }

touch_conf() {
    if [ ! -f "$CONF" ]; then
        mkdir -p "$(dirname "$CONF")" 2>/dev/null
        printf '# aggregator.conf - generated by klish, do not edit by hand\n' > "$CONF" \
            || die "cannot create $CONF"
        chmod 600 "$CONF" 2>/dev/null || true
    fi
}

# upsert <regex-untuk-hapus> <baris-baru>
upsert() {
    _re="$1"; _line="$2"
    touch_conf
    _tmp="$CONF.tmp.$$"
    grep -v "$_re" "$CONF" > "$_tmp" 2>/dev/null || true
    printf '%s\n' "$_line" >> "$_tmp"
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
    chmod 600 "$CONF" 2>/dev/null || true
}

dellines() {
    _re="$1"
    touch_conf
    _tmp="$CONF.tmp.$$"
    grep -v "$_re" "$CONF" > "$_tmp" 2>/dev/null || true
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
}

has_facts() {
    [ -f "$CONF" ] || return 1
    grep -v '^[[:space:]]*#' "$CONF" 2>/dev/null | grep -q '[^[:space:]]'
}

# --- validasi ---
valid_name() {
    # $1=nama $2=konteks: simbol BIRD [A-Za-z_][A-Za-z0-9_]*.
    case "$1" in
        ''|*[!A-Za-z0-9_]*) err "$2 harus nama BIRD [A-Za-z0-9_]: $1" ;;
    esac
    case "$1" in [A-Za-z_]*) ;; *) err "$2 harus diawali huruf/underscore: $1" ;; esac
}

valid_table() {
    # $1=nama tabel $2=konteks: master4/master6 selalu sah; selain itu
    # harus terdefinisi di bird-global.conf (B6: table-add). Bila
    # bird-global.conf belum ada, hanya master yang diterima.
    case "$1" in master4|master6) return 0 ;; esac
    valid_name "$1" "$2"
    [ -f "$GLOBAL_CONF" ] || err "$2 tabel $1 belum didefinisikan (bird-global.conf belum ada — definisikan dulu: global -> table-add ... $1)"
    grep -q "^table [^ ]* $1\$" "$GLOBAL_CONF" 2>/dev/null || \
        err "$2 tabel $1 belum didefinisikan (definisikan dulu: global -> table-add <nettype> $1)"
}

# inst_has <NAME>: exit 0 bila ada >=1 fakta instance itu.
inst_has() {
    grep -q "^instance $1 " "$CONF" 2>/dev/null
}

cmd_agg_touch() {
    _n="$1"
    [ -n "$_n" ] || err "aggregator butuh NAMA instance"
    valid_name "$_n" "aggregator"
    touch_conf
    echo "Aggregator $_n"
}

cmd_table_set() {
    _n="$1"; _t="$2"
    valid_name "$_n" "aggregator"
    [ -n "$_t" ] || err "table butuh nama tabel"
    valid_table "$_t" "aggregator table"
    upsert "^instance $_n table " "instance $_n table $_t"
    echo "Aggregator $_n table = $_t"
}

cmd_table_del() {
    _n="$1"
    valid_name "$_n" "aggregator"
    dellines "^instance $_n table "
    echo "Aggregator $_n table dihapus (default BIRD)"
}

cmd_chan_set() {
    # chan-set <NAME> <import|export> <all|none|filter NAMA>
    _n="$1"; _d="$2"; _v="$3"; _fn="$4"
    valid_name "$_n" "aggregator"
    case "$_d" in import|export) ;; *) err "channel harus import|export: $_d" ;; esac
    case "$_v" in
        all|none) upsert "^instance $_n $_d " "instance $_n $_d $_v" ;;
        filter)
            [ -n "$_fn" ] || err "$_d filter butuh NAMA filter"
            valid_name "$_fn" "nama filter"
            upsert "^instance $_n $_d " "instance $_n $_d filter $_fn" ;;
        *) err "$_d harus all|none|filter NAMA: $_v" ;;
    esac
    echo "Aggregator $_n $_d = $_v${_fn:+ $_fn}"
}

# aggregate-on: daftar dipisah koma tanpa spasi, elemen pertama WAJIB
# `net` (docs §6.1: mandatory saat ini). Elemen lain: atribut compact
# dari daftar putih, atau atribut int kustom (attribute-int bgp.conf).
valid_agg_attr() {
    _a="$1"
    case "$_a" in
        net|bgp_path.len|bgp_path.first|bgp_path.last|bgp_path.last_nonaggregated|\
        bgp_local_pref|bgp_med|bgp_origin|bgp_community|bgp_ext_community|\
        bgp_large_community|bgp_next_hop|bgp_path|source|preference|\
        igp_metric|weight|net.len|net.ip|net.type|net.rd|net.maxlen|net.asn|\
        ra_preference|ra_lifetime|rip_metric|ospf_metric1|ospf_metric2|ospf_tag)
            return 0 ;;
    esac
    # Atribut int kustom (B5 attribute-int di bgp.conf).
    [ -f "$STATE_ROOT/bgp.conf" ] && \
        grep -q "^attribute-int $_a\$" "$STATE_ROOT/bgp.conf" 2>/dev/null && return 0
    err "aggregate-on atribut tidak dikenal / bukan compact: $_a (boleh: net, bgp_path.len, bgp_local_pref, bgp_med, bgp_origin, bgp_community, bgp_ext_community, bgp_large_community, bgp_next_hop, source, preference, igp_metric, weight, net.len, net.ip, net.type, net.rd, net.maxlen, net.asn, ra_preference, ra_lifetime, rip_metric, ospf_metric1/2, ospf_tag, atau attribute-int kustom)"
}

cmd_agg_on_set() {
    _n="$1"; _list="$2"
    valid_name "$_n" "aggregator"
    [ -n "$_list" ] || err "aggregate-on butuh daftar (mis. net,bgp_path.len)"
    case "$_list" in
        net|net,*) ;;
        *) err "aggregate-on elemen pertama WAJIB net (docs §6.1: 'we can't merge prefixes yet'): $_list" ;;
    esac
    case "$_list" in *[[:space:]]*|*\;*|*\{*|*\}*) err "aggregate-on daftar tanpa spasi/;/{} (dipisah koma, mis. net,bgp_path.len): $_list" ;; esac
    _rest="$_list"
    while [ -n "$_rest" ]; do
        case "$_rest" in *,*) _one=${_rest%%,*}; _rest=${_rest#*,} ;; *) _one="$_rest"; _rest="" ;; esac
        [ -n "$_one" ] || err "aggregate-on ada elemen kosong: $_list"
        valid_agg_attr "$_one"
    done
    upsert "^instance $_n aggregate-on " "instance $_n aggregate-on $_list"
    echo "Aggregator $_n aggregate-on = $_list"
}

cmd_agg_on_del() {
    _n="$1"
    valid_name "$_n" "aggregator"
    dellines "^instance $_n aggregate-on "
    echo "Aggregator $_n aggregate-on dihapus"
}

# join_words: gabung argumen tak-kosong dengan satu spasi.
join_words() {
    _out=""
    for _w in "$@"; do
        [ -n "$_w" ] || continue
        if [ -z "$_out" ]; then _out="$_w"; else _out="$_out $_w"; fi
    done
    printf '%s' "$_out"
}

# valid_merge_line <TEKS>: tolak karakter yang bisa membobol blok
# `merge by { ... }` (komentar, string, escape, substitusi shell).
valid_merge_line() {
    _t="$1"
    [ -n "$_t" ] || err "merge-line butuh isi (maks 8 kata/baris; baris panjang boleh dipecah — BIRD tidak peduli baris baru)"
    case "$_t" in
        *'/*'*|*'*/'*) err "merge-line tidak boleh mengandung komentar /* */: $_t" ;;
        *\"*|*\\*|*'`'*|*'$'*) err "merge-line tidak boleh mengandung \" \\ \` \$: $_t" ;;
    esac
}

cmd_merge_add() {
    # merge-line-add <NAME> <W1..W8> (kata kosong dari PARAM optional
    # klish dilewati join_words).
    _n="$1"; shift
    valid_name "$_n" "aggregator"
    _line=$(join_words "$@")
    valid_merge_line "$_line"
    touch_conf
    printf 'instance %s merge %s\n' "$_n" "$_line" >> "$CONF"
    echo "Aggregator $_n merge-line: $_line"
}

cmd_merge_del() {
    # merge-line-del <NAME> <N>: hapus baris merge ke-N (1-based).
    _n="$1"; _no="$2"
    valid_name "$_n" "aggregator"
    case "$_no" in ''|*[!0-9]*) err "merge-line-del butuh nomor baris (1..): $_no" ;; esac
    [ "$_no" -ge 1 ] 2>/dev/null || err "merge-line-del nomor harus >= 1: $_no"
    _tmp="$CONF.tmp.$$"
    awk -v n="$_no" -v inst="$_n" '
        $1=="instance" && $2==inst && $3=="merge" { c++; if (c==n) next }
        { print }
    ' "$CONF" > "$_tmp" 2>/dev/null || die "cannot write $CONF"
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
    echo "Aggregator $_n merge-line #$_no dihapus"
}

cmd_merge_clear() {
    _n="$1"
    valid_name "$_n" "aggregator"
    dellines "^instance $_n merge "
    echo "Aggregator $_n merge-line dihapus semua (merge by kosong — set ulang sebelum generate)"
}

cmd_peer_table_set() {
    _n="$1"; _t="$2"
    valid_name "$_n" "aggregator"
    [ -n "$_t" ] || err "peer-table butuh nama tabel"
    valid_table "$_t" "aggregator peer-table"
    upsert "^instance $_n peer-table " "instance $_n peer-table $_t"
    echo "Aggregator $_n peer-table = $_t"
}

cmd_peer_table_del() {
    _n="$1"
    valid_name "$_n" "aggregator"
    dellines "^instance $_n peer-table "
    echo "Aggregator $_n peer-table dihapus (default BIRD)"
}

# --- getters (untuk generate) ---
get_inst_field() {
    # $1=instance $2=field -> nilai (kolom 4; import/export filter nama
    # ada di kolom 4, lihat get_chan di bawah)
    grep "^instance $1 $2 " "$CONF" 2>/dev/null | head -1 | awk '{print $4}'
}

get_chan() {
    # $1=instance $2=import|export -> "all"|"none"|"filter NAME"
    grep "^instance $1 $2 " "$CONF" 2>/dev/null | head -1 | awk '{$1=""; $2=""; $3=""; sub(/^ +/, ""); print}'
}

# emit_instance <NAME>: cetak blok `protocol aggregator <NAME> { ... }`.
emit_instance() {
    _n="$1"
    inst_has "$_n" || return 0
    _table=$(get_inst_field "$_n" table)
    _export=$(get_chan "$_n" export)
    _aggon=$(get_inst_field "$_n" aggregate-on)
    _import=$(get_chan "$_n" import)
    _peer=$(get_inst_field "$_n" peer-table)
    [ -n "$_export" ] || _export="all"
    [ -n "$_import" ] || _import="all"
    [ -n "$_aggon" ] || err "aggregator $_n tanpa aggregate-on — set dulu (aggregate-on wajib, docs §6.1; mis. net,bgp_path.len)"
    # Merge lines: wajib ada, kurawal seimbang, mengandung `accept`.
    _merges=$(grep "^instance $_n merge " "$CONF" 2>/dev/null | sed "s/^instance $_n merge //")
    [ -n "$_merges" ] || err "aggregator $_n tanpa merge-by — tambah dulu merge-line (merge by wajib, docs §6.1)"
    _opens=$(printf '%s' "$_merges" | tr -cd '{' | wc -c)
    _closes=$(printf '%s' "$_merges" | tr -cd '}' | wc -c)
    [ "$_opens" = "$_closes" ] || err "aggregator $_n merge-by kurung kurawal tidak seimbang (buka $_opens, tutup $_closes) — rapikan merge-line"
    case "$_merges" in
        *accept*) ;;
        *) err "aggregator $_n merge-by tanpa accept — route hasil merge harus difinalisasi accept (docs §6.1)" ;;
    esac
    echo "protocol aggregator $_n {"
    [ -n "$_table" ] && echo "    table $_table;"
    echo "    export $_export;"
    echo "    aggregate on $(printf '%s' "$_aggon" | sed 's/,/, /g');"
    echo "    merge by {"
    printf '%s\n' "$_merges" | sed 's/^/        /'
    echo "    };"
    echo "    import $_import;"
    [ -n "$_peer" ] && echo "    peer table $_peer;"
    echo "}"
    echo ""
}

cmd_generate() {
    touch_conf
    set -f
    mkdir -p "$SECTION_DIR" 2>/dev/null || die "cannot mkdir $SECTION_DIR"
    _tmp="$SECTION.tmp.$$"
    if has_facts; then
        {
            echo "# aggregator.conf - generated by titian-aggregator.sh, do not edit by hand"
            for _n in $(grep '^instance ' "$CONF" 2>/dev/null | awk '{print $2}' | awk '!s[$0]++'); do
                emit_instance "$_n"
            done
        } > "$_tmp" || die "cannot write $_tmp"
    else
        {
            echo "# aggregator.conf - generated by titian-aggregator.sh, do not edit by hand"
            echo "# (tidak ada config aggregator — protocol aggregator tidak dibuat)"
        } > "$_tmp" || die "cannot write $_tmp"
    fi
    mv "$_tmp" "$SECTION" || die "cannot write $SECTION"
    chmod 644 "$SECTION" 2>/dev/null || true
    set +f
    echo "Aggregator section ditulis: $SECTION"
    _birdsh="$(dirname "$0")/titian-bird.sh"
    if [ -x "$_birdsh" ]; then
        "$_birdsh" generate aggregator || exit 33
    else
        echo "Warning: $_birdsh tidak ditemukan; section hanya ditulis, belum di-apply" >&2
    fi
}

birdc_bin() {
    command -v birdc 2>/dev/null || { [ -x /usr/sbin/birdc ] && echo /usr/sbin/birdc; } || \
        { [ -x /usr/local/sbin/birdc ] && echo /usr/local/sbin/birdc; } || echo birdc
}

cmd_show() {
    touch_conf
    echo "--- aggregator.conf (intent) ---"
    cat "$CONF"
    echo "--- bird.d/aggregator.conf (section, bila ada) ---"
    [ -f "$SECTION" ] && cat "$SECTION" || echo "(belum di-generate)"
    echo "--- birdc show protocol (aggregator) ---"
    _birdc=$(birdc_bin)
    _done=0
    for _n in $(grep '^instance ' "$CONF" 2>/dev/null | awk '{print $2}' | awk '!s[$0]++'); do
        if grep -q "protocol aggregator $_n" "$SECTION" 2>/dev/null; then
            if _out=$("$_birdc" show protocol "$_n" 2>&1); then
                echo "$_out" | grep -v '^BIRD'
                _done=1
            fi
        fi
    done
    [ "$_done" = "0" ] && echo "(BIRD tidak jalan / belum ada instance aggregator — birdc show protocol gagal)"
    return 0
}

case "$1" in
    aggregator-touch) shift; cmd_agg_touch "$@" ;;
    has-facts) has_facts ;;
    table-set) shift; cmd_table_set "$@" ;;
    table-del) shift; cmd_table_del "$@" ;;
    chan-set) shift; cmd_chan_set "$@" ;;
    aggregate-on-set) shift; cmd_agg_on_set "$@" ;;
    aggregate-on-del) shift; cmd_agg_on_del "$@" ;;
    merge-line-add) shift; cmd_merge_add "$@" ;;
    merge-line-del) shift; cmd_merge_del "$@" ;;
    merge-line-clear) shift; cmd_merge_clear "$@" ;;
    peer-table-set) shift; cmd_peer_table_set "$@" ;;
    peer-table-del) shift; cmd_peer_table_del "$@" ;;
    generate) cmd_generate ;;
    show) cmd_show ;;
    *) echo "Usage: $0 {aggregator-touch NAME|has-facts|table-set NAME TABEL|table-del NAME|chan-set NAME import|export all|none|filter NAMA|aggregate-on-set NAME net[,ATTR...]|aggregate-on-del NAME|merge-line-add NAME W1..W8|merge-line-del NAME N|merge-line-clear NAME|peer-table-set NAME TABEL|peer-table-del NAME|generate|show}" >&2; exit 2 ;;
esac
