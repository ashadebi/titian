#!/bin/sh
# titian-bfd.sh — BFD intent (BIRD) untuk Titian/klish.
# Pola sama seperti titian-bgp.sh: intent di /etc/titian/bfd.conf
# (tmpfs, dipersistenkan via titian-cfg.sh), generate menulis section
# BIRD /etc/titian/bird.d/bfd.conf lalu memanggil titian-bird.sh
# generate bfd (render + validasi + birdc). Section ditulis ulang
# UTUH tiap apply (pola policy object FRR).
#
# Sintaks BIRD 2.20 yang dipakai (docs resmi bird.network,
# User's Guide 2.20, §6.3 BFD + §6.4 BGP `bfd` option):
#   protocol bfd {
#       interface "<pattern>" {
#           interval <time>; min rx interval <time>;
#           min tx interval <time>; idle tx interval <time>;
#           multiplier <num>; passive;
#       };
#       multihop {
#           interval <time>; min rx interval <time>;
#           min tx interval <time>; idle tx interval <time>;
#           multiplier <num>; passive;
#       };
#       neighbor <ip> [dev "<iface>"] [local <ip>] [multihop];
#   }
#   Di dalam protocol bgp (per neighbor, via titian-bgp.sh):
#       bfd on;            (atau `bfd graceful;`)
# Default BIRD: min rx 10 ms, min tx 100 ms, idle tx 1 s,
# multiplier 5, passive off, auth none. Satu instance protocol bfd
# (tanpa nama) — BIRD hanya mendukung satu instance non-VRF.
#
# Format bfd.conf (satu baris per fakta):
#   interface <PATTERN> interval <MS>
#   interface <PATTERN> min-rx <MS>
#   interface <PATTERN> min-tx <MS>
#   interface <PATTERN> idle-tx <MS>
#   interface <PATTERN> multiplier <N>
#   interface <PATTERN> passive <on|off>
#   multihop interval <MS>
#   multihop min-rx <MS>
#   multihop min-tx <MS>
#   multihop idle-tx <MS>
#   multihop multiplier <N>
#   multihop passive <on|off>
#   neighbor <IP> dev <IFACE>
#   neighbor <IP> local <IP>
#   neighbor <IP> multihop <on|off>
#
# Urutan apply (titian-commit.sh): apply_bfd WAJIB sebelum apply_bgp —
# birdc configure gagal bila neighbor BGP pakai `bfd on;` tanpa
# `protocol bfd` di bird.conf.

STATE_ROOT="${TITIAN_STATE_ROOT:-/etc/titian}"
CONF="$STATE_ROOT/bfd.conf"
BGP_CONF="$STATE_ROOT/bgp.conf"
SECTION_DIR="$STATE_ROOT/bird.d"
SECTION="$SECTION_DIR/bfd.conf"
PROG="titian-bfd"
err() { echo "Error($PROG): $*" >&2; exit 33; }
die() { echo "$PROG: $*" >&2; exit 1; }

touch_conf() {
    if [ ! -f "$CONF" ]; then
        mkdir -p "$(dirname "$CONF")" 2>/dev/null
        printf '# bfd.conf - generated by klish, do not edit by hand\n' > "$CONF" \
            || die "cannot create $CONF"
        chmod 600 "$CONF" 2>/dev/null || true
    fi
}

# re_esc <teks> — escape karakter regex (untuk pola interface yang
# boleh mengandung `*`, mis. "ge*") agar grep -v tidak salah hapus.
re_esc() {
    printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/\./\\./g' -e 's/\*/\\*/g' \
        -e 's/\[/\\[/g' -e 's/\]/\\]/g' -e 's/\^/\\^/g' -e 's/\$/\\$/g'
}

# upsert <regex-untuk-hapus> <baris-baru>
upsert() {
    _re="$1"; _line="$2"
    touch_conf
    _tmp="$CONF.tmp.$$"
    grep -v "$_re" "$CONF" > "$_tmp" 2>/dev/null || true
    printf '%s\n' "$_line" >> "$_tmp"
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
    chmod 600 "$CONF" 2>/dev/null || true
}

dellines() {
    _re="$1"
    touch_conf
    _tmp="$CONF.tmp.$$"
    grep -v "$_re" "$CONF" > "$_tmp" 2>/dev/null || true
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
}

# has_facts: exit 0 bila bfd.conf punya >=1 baris fakta (bukan
# komentar/kosong), 1 bila tidak. Dipakai titian-bgp.sh generate.
has_facts() {
    [ -f "$CONF" ] || return 1
    grep -v '^[[:space:]]*#' "$CONF" 2>/dev/null | grep -q '[^[:space:]]'
}

# validasi interval (ms): bilangan 1..60000
valid_ms() {
    # $1 = nilai, $2 = nama field
    case "$1" in ''|*[!0-9]*) err "$2 harus bilangan ms 1..60000: $1" ;; esac
    [ "$1" -ge 1 ] 2>/dev/null && [ "$1" -le 60000 ] 2>/dev/null || \
        err "$2 harus bilangan ms 1..60000: $1"
}

# validasi multiplier: bilangan 1..255
valid_mult() {
    case "$1" in ''|*[!0-9]*) err "multiplier harus bilangan 1..255: $1" ;; esac
    [ "$1" -ge 1 ] 2>/dev/null && [ "$1" -le 255 ] 2>/dev/null || \
        err "multiplier harus bilangan 1..255: $1"
}

cmd_bfd_touch() {
    touch_conf
    echo "BFD"
}

# --- interface ---
cmd_interface_add() {
    _pat="$1"
    [ -n "$_pat" ] || err "interface-add butuh pola interface (mis. bridge0)"
    touch_conf
    echo "BFD interface $_pat"
}

cmd_interface_del() {
    _pat="$1"
    [ -n "$_pat" ] || err "interface-del butuh pola interface"
    _re=$(re_esc "$_pat")
    dellines "^interface $_re "
    echo "BFD interface $_pat dihapus"
}

cmd_interface_set() {
    # interface-set <PATTERN> <field> <value>
    # field: interval|min-rx|min-tx|idle-tx|multiplier|passive
    _pat="$1"; _f="$2"; _v="$3"
    [ -n "$_pat" ] && [ -n "$_f" ] && [ -n "$_v" ] || \
        err "interface-set butuh PATTERN FIELD VALUE"
    _re=$(re_esc "$_pat")
    case "$_f" in
        interval|min-rx|min-tx|idle-tx)
            valid_ms "$_v" "$_f"
            upsert "^interface $_re $_f " "interface $_pat $_f $_v" ;;
        multiplier)
            valid_mult "$_v"
            upsert "^interface $_re $_f " "interface $_pat $_f $_v" ;;
        passive)
            case "$_v" in
                on|off) upsert "^interface $_re passive " "interface $_pat passive $_v" ;;
                *) err "passive harus on|off: $_v" ;;
            esac ;;
        *) err "field interface BFD tidak dikenal: $_f (interval|min-rx|min-tx|idle-tx|multiplier|passive)" ;;
    esac
    echo "BFD interface $_pat $_f = $_v"
}

# --- multihop ---
cmd_multihop_touch() {
    touch_conf
    echo "BFD multihop"
}

cmd_multihop_set() {
    # multihop-set <field> <value> (field sama seperti interface-set)
    _f="$1"; _v="$2"
    [ -n "$_f" ] && [ -n "$_v" ] || err "multihop-set butuh FIELD VALUE"
    case "$_f" in
        interval|min-rx|min-tx|idle-tx)
            valid_ms "$_v" "$_f"
            upsert "^multihop $_f " "multihop $_f $_v" ;;
        multiplier)
            valid_mult "$_v"
            upsert "^multihop $_f " "multihop $_f $_v" ;;
        passive)
            case "$_v" in
                on|off) upsert "^multihop passive " "multihop passive $_v" ;;
                *) err "passive harus on|off: $_v" ;;
            esac ;;
        *) err "field multihop BFD tidak dikenal: $_f (interval|min-rx|min-tx|idle-tx|multiplier|passive)" ;;
    esac
    echo "BFD multihop $_f = $_v"
}

# --- neighbor ---
cmd_neighbor_add() {
    _ip="$1"
    [ -n "$_ip" ] || err "neighbor-add butuh IP"
    touch_conf
    echo "BFD neighbor $_ip"
}

cmd_neighbor_del() {
    _ip="$1"
    [ -n "$_ip" ] || err "neighbor-del butuh IP"
    dellines "^neighbor $_ip "
    echo "BFD neighbor $_ip dihapus"
}

cmd_neighbor_set() {
    # neighbor-set <IP> <field> <value>
    # field: dev|local|multihop
    _ip="$1"; _f="$2"; _v="$3"
    [ -n "$_ip" ] && [ -n "$_f" ] && [ -n "$_v" ] || \
        err "neighbor-set butuh IP FIELD VALUE"
    case "$_f" in
        dev) upsert "^neighbor $_ip dev " "neighbor $_ip dev $_v" ;;
        local) upsert "^neighbor $_ip local " "neighbor $_ip local $_v" ;;
        multihop)
            case "$_v" in
                on|off) upsert "^neighbor $_ip multihop " "neighbor $_ip multihop $_v" ;;
                *) err "multihop harus on|off: $_v" ;;
            esac ;;
        *) err "field neighbor BFD tidak dikenal: $_f (dev|local|multihop)" ;;
    esac
    echo "BFD neighbor $_ip $_f = $_v"
}

# --- getters (untuk generate) ---
get_iface_field() {
    # $1=pattern $2=field -> nilai (atau kosong)
    _re=$(re_esc "$1")
    grep "^interface $_re $2 " "$CONF" 2>/dev/null | head -1 | awk '{print $4}'
}

get_mh_field() {
    # $1=field -> nilai (atau kosong)
    grep "^multihop $1 " "$CONF" 2>/dev/null | head -1 | awk '{print $3}'
}

get_nbr_field() {
    # $1=IP $2=field -> nilai (atau kosong)
    grep "^neighbor $1 $2 " "$CONF" 2>/dev/null | head -1 | awk '{print $4}'
}

# --- generate: intent -> bird.d/bfd.conf (sintaks BIRD) ---
cmd_generate() {
    touch_conf
    # Pola interface boleh mengandung `*` (mis. "ge*") — matikan glob
    # agar word-splitting hasil grep tidak mengembang ke nama file.
    set -f
    mkdir -p "$SECTION_DIR" 2>/dev/null || die "cannot mkdir $SECTION_DIR"
    _tmp="$SECTION.tmp.$$"
    if has_facts; then
        {
            echo "# bfd.conf - generated by titian-bfd.sh, do not edit by hand"
            echo "protocol bfd {"
            # --- interface blocks (urut, unik) ---
            for _pat in $(grep '^interface ' "$CONF" 2>/dev/null | awk '{print $2}' | sort -u); do
                _iv=$(get_iface_field "$_pat" interval)
                _rx=$(get_iface_field "$_pat" min-rx)
                _tx=$(get_iface_field "$_pat" min-tx)
                _idle=$(get_iface_field "$_pat" idle-tx)
                _mult=$(get_iface_field "$_pat" multiplier)
                _pas=$(get_iface_field "$_pat" passive)
                echo "    interface \"$_pat\" {"
                [ -n "$_iv" ] && echo "        interval $_iv ms;"
                [ -n "$_rx" ] && echo "        min rx interval $_rx ms;"
                [ -n "$_tx" ] && echo "        min tx interval $_tx ms;"
                [ -n "$_idle" ] && echo "        idle tx interval $_idle ms;"
                [ -n "$_mult" ] && echo "        multiplier $_mult;"
                [ "$_pas" = "on" ] && echo "        passive;"
                echo "    };"
            done
            # --- multihop block ---
            _miv=$(get_mh_field interval)
            _mrx=$(get_mh_field min-rx)
            _mtx=$(get_mh_field min-tx)
            _midle=$(get_mh_field idle-tx)
            _mmult=$(get_mh_field multiplier)
            _mpas=$(get_mh_field passive)
            if [ -n "$_miv" ] || [ -n "$_mrx" ] || [ -n "$_mtx" ] || [ -n "$_midle" ] || [ -n "$_mmult" ] || [ "$_mpas" = "on" ]; then
                echo "    multihop {"
                [ -n "$_miv" ] && echo "        interval $_miv ms;"
                [ -n "$_mrx" ] && echo "        min rx interval $_mrx ms;"
                [ -n "$_mtx" ] && echo "        min tx interval $_mtx ms;"
                [ -n "$_midle" ] && echo "        idle tx interval $_midle ms;"
                [ -n "$_mmult" ] && echo "        multiplier $_mmult;"
                [ "$_mpas" = "on" ] && echo "        passive;"
                echo "    };"
            fi
            # --- explicit neighbors (urut, unik) ---
            for _nip in $(grep '^neighbor ' "$CONF" 2>/dev/null | awk '{print $2}' | sort -u); do
                _dev=$(get_nbr_field "$_nip" dev)
                _loc=$(get_nbr_field "$_nip" local)
                _mh=$(get_nbr_field "$_nip" multihop)
                _line="    neighbor $_nip"
                [ -n "$_dev" ] && _line="$_line dev \"$_dev\""
                [ -n "$_loc" ] && _line="$_line local $_loc"
                [ "$_mh" = "on" ] && _line="$_line multihop"
                echo "$_line;"
            done
            echo "}"
        } > "$_tmp" || die "cannot write $_tmp"
    else
        # Tidak ada fakta BFD: section jadi komentar saja (tidak ada
        # instance protocol bfd). Tapi bila neighbor BGP masih pakai
        # `bfd on;`, config BIRD akan gagal — tolak dengan pesan jelas.
        if [ -f "$BGP_CONF" ] && grep -q '^neighbor .* bfd ' "$BGP_CONF" 2>/dev/null; then
            _who=$(grep '^neighbor .* bfd ' "$BGP_CONF" 2>/dev/null | head -1 | awk '{print $2}')
            err "BFD masih dipakai neighbor BGP $_who (bfd on) tapi tidak ada config BFD — hapus dulu \`no bfd\` di neighbor itu, atau isi config BFD (router bird -> bfd -> interface ...)"
        fi
        {
            echo "# bfd.conf - generated by titian-bfd.sh, do not edit by hand"
            echo "# (tidak ada config BFD — protocol bfd tidak dibuat)"
        } > "$_tmp" || die "cannot write $_tmp"
    fi
    mv "$_tmp" "$SECTION" || die "cannot write $SECTION"
    chmod 644 "$SECTION" 2>/dev/null || true
    set +f
    echo "BFD section ditulis: $SECTION"
    # render ke bird.conf + birdc configure (pakai mekanisme titian-bird.sh)
    _birdsh="$(dirname "$0")/titian-bird.sh"
    if [ -x "$_birdsh" ]; then
        "$_birdsh" generate bfd || exit 33
    else
        echo "Warning: $_birdsh tidak ditemukan; section hanya ditulis, belum di-apply" >&2
    fi
}

birdc_bin() {
    command -v birdc 2>/dev/null || { [ -x /usr/sbin/birdc ] && echo /usr/sbin/birdc; } || \
        { [ -x /usr/local/sbin/birdc ] && echo /usr/local/sbin/birdc; } || echo birdc
}

cmd_show() {
    touch_conf
    echo "--- bfd.conf (intent) ---"
    cat "$CONF"
    echo "--- bird.d/bfd.conf (section, bila ada) ---"
    [ -f "$SECTION" ] && cat "$SECTION" || echo "(belum di-generate)"
    echo "--- birdc show bfd sessions ---"
    _birdc=$(birdc_bin)
    if _out=$("$_birdc" show bfd sessions 2>&1); then
        echo "$_out" | grep -v '^BIRD'
    else
        echo "(BFD tidak jalan / bird tidak jalan — birdc show bfd sessions gagal)"
    fi
}

cmd_show_sessions() {
    _birdc=$(birdc_bin)
    if _out=$("$_birdc" show bfd sessions 2>&1); then
        echo "$_out" | grep -v '^BIRD'
    else
        echo "(BFD tidak jalan / bird tidak jalan — birdc show bfd sessions gagal)"
    fi
}

case "$1" in
    bfd-touch) cmd_bfd_touch ;;
    has-facts) has_facts ;;
    interface-add) shift; cmd_interface_add "$@" ;;
    interface-del) shift; cmd_interface_del "$@" ;;
    interface-set) shift; cmd_interface_set "$@" ;;
    multihop-touch) cmd_multihop_touch ;;
    multihop-set) shift; cmd_multihop_set "$@" ;;
    neighbor-add) shift; cmd_neighbor_add "$@" ;;
    neighbor-del) shift; cmd_neighbor_del "$@" ;;
    neighbor-set) shift; cmd_neighbor_set "$@" ;;
    generate) cmd_generate ;;
    show) cmd_show ;;
    show-sessions) cmd_show_sessions ;;
    *) echo "Usage: $0 {bfd-touch|has-facts|interface-add PATTERN|interface-del PATTERN|interface-set PATTERN FIELD VALUE|multihop-touch|multihop-set FIELD VALUE|neighbor-add IP|neighbor-del IP|neighbor-set IP FIELD VALUE|generate|show|show-sessions}" >&2; exit 2 ;;
esac
