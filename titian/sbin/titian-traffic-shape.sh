#!/bin/sh
# titian-traffic-shape.sh — klish helper: edit + apply /usr/local/etc/traffic-shape.conf
# BSDRP_klish, prepared 2026-11-08 (completed 2026-11-08 ~18:00 WIB).
# POSIX sh, no bashisms. Syntax verified against FreeBSD 16 ipfw.8
# (obj/FreeBSD/sbin/ipfw/ipfw.8) + sbin/ipfw/dummynet.c.
#
# Config format (one object per line; written by klish, read by
# traffic-shape-apply):
#   enable yes|no
#   pipe <name> bw <rate> queue <n> delay <ms> plr <x> burst <n>
#        [aqm <clause...>]
#   sched <name> type <t> [bw <rate>] [quantum <n>] [limit <n>] [flows <n>]
#   queue <name> <pipe|sched> <parent> mask <spec> <val> weight <n>
#         queue <n> [aqm <clause...>]
#   rule <name> <in|out> on <if> {pipe|queue} <ref> [src <a>] [dst <a>]
#        [proto <p>] [dport <n>]
#
# Mask specifiers (ipfw.8): dst-ip, src-ip, dst-ip6, src-ip6, dst-port,
# src-port, proto, flow-id, all. Values are /N bit counts (preferred) or
# numbers (0x.../decimal). Full masks: dst-ip /32, dst-ip6 /128,
# dst-port /16, src-port /16, proto /8, flow-id /32. `all` takes no value
# (stored as `-`).
# AQM clause (verbatim ipfw tokens, must come last on the line):
#   aqm droptail | aqm red <wq> <min_th> <max_th> <max_p>
#   | aqm gred <wq> <min_th> <max_th> <max_p>
#   | aqm codel [target <ms>] [interval <ms>]
#   | aqm pie [target <ms>] [tupdate <ms>]
#
# Every mutation touches /var/run/traffic-shape.dirty so the klish commit
# hook knows to run `service traffic-shape restart` (or stop).
set -u

CONF="${TS_CONF:-/usr/local/etc/traffic-shape.conf}"
DIRTY=/var/run/traffic-shape.dirty
PROG="titian-traffic-shape"

die() { echo "$PROG: $*" >&2; exit 1; }

touch_conf() {
    if [ ! -f "$CONF" ]; then
        printf '# traffic-shape.conf - generated by klish, do not edit by hand\nenable no\n' > "$CONF" \
            || die "cannot create $CONF"
    fi
}

mark_dirty() { touch "$DIRTY" 2>/dev/null || true; }

# upsert <grep-regex-anchored> <new-line>
upsert() {
    _re="$1"; _line="$2"
    touch_conf
    _tmp="$CONF.tmp.$$"
    grep -v "$_re" "$CONF" > "$_tmp" 2>/dev/null || true
    printf '%s\n' "$_line" >> "$_tmp"
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
    mark_dirty
}

# delete lines matching regex; fail if none matched
dellines() {
    _re="$1"; _what="$2"
    touch_conf
    if ! grep -q "$_re" "$CONF" 2>/dev/null; then
        die "$_what not found"
    fi
    _tmp="$CONF.tmp.$$"
    grep -v "$_re" "$CONF" > "$_tmp" || true
    mv "$_tmp" "$CONF" || die "cannot write $CONF"
    mark_dirty
}

# --- validation helpers -------------------------------------------------
valid_name() {
    case "$1" in
        *[!A-Za-z0-9_-]*|"") die "bad name: $1 (use [A-Za-z0-9_-]+)" ;;
    esac
}

pipe_exists()  { grep -q "^pipe $1 " "$CONF" 2>/dev/null; }
sched_exists() { grep -q "^sched $1 " "$CONF" 2>/dev/null; }
queue_exists() { grep -q "^queue $1 " "$CONF" 2>/dev/null; }
rule_exists()  { grep -q "^rule $1 " "$CONF" 2>/dev/null; }

iface_exists() {
    ifconfig "$1" >/dev/null 2>&1 || die "interface $1 not found (see 'show interfaces')"
}

# Full mask value (bit-count form) for a mask specifier.
default_mask_val() {
    case "$1" in
        dst-ip|src-ip) echo "/32" ;;
        dst-ip6|src-ip6) echo "/128" ;;
        dst-port|src-port) echo "/16" ;;
        proto) echo "/8" ;;
        flow-id) echo "/32" ;;
        all) echo "-" ;;
        *) die "unknown mask specifier: $1" ;;
    esac
}

# Validate a mask value for a specifier. Accepts /N (bit count) or a
# number (0x.../decimal). Dies on out-of-range bit counts.
valid_mask_val() {
    _spec="$1"; _val="$2"
    case "$_val" in
        /*)
            _n="${_val#/}"
            case "$_n" in *[!0-9]*|"") die "bad mask value: $_val" ;; esac
            case "$_spec" in
                dst-ip|src-ip|flow-id) _max=32 ;;
                dst-ip6|src-ip6) _max=128 ;;
                dst-port|src-port) _max=16 ;;
                proto) _max=8 ;;
                *) die "unknown mask specifier: $_spec" ;;
            esac
            [ "$_n" -le "$_max" ] || die "mask $_spec: /$_n exceeds /$_max"
            ;;
        0x*|[0-9]*)
            case "$_val" in
                0x*[!0-9a-fA-F]*|*[!0-9]*) die "bad mask value: $_val" ;;
            esac
            ;;
        *) die "bad mask value: $_val (use /N or a number)" ;;
    esac
}

# Validate an AQM clause (single string, e.g. "aqm codel target 5").
valid_aqm_clause() {
    set -- $1
    [ "$1" = "aqm" ] || die "bad aqm clause: $1"
    case "${2:-}" in
        droptail) [ "$#" -eq 2 ] || die "aqm droptail takes no arguments" ;;
        red|gred) [ "$#" -eq 6 ] || die "aqm $2 needs: <wq> <min_th> <max_th> <max_p>" ;;
        codel|pie) ;;  # optional key/value params, checked by ipfw at apply
        *) die "unknown aqm: ${2:-} (droptail|red|gred|codel|pie)" ;;
    esac
}

