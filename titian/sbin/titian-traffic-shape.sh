}

# traffic-shape-apply — apply /usr/local/etc/traffic-shape.conf to the kernel
# BSDRP_klish, prepared 2026-11-08 (completed 2026-11-08 ~18:00 WIB).
# POSIX sh, no bashisms. Syntax verified against FreeBSD 16 ipfw.8
# (obj/FreeBSD/sbin/ipfw/ipfw.8) + sbin/ipfw/dummynet.c.
#
# Usage (merged): titian-traffic-shape.sh apply [config-file] | apply --flush
#
# Objects (number ranges are reserved for this subsystem):
#   pipes  1-99    — bandwidth cap (bw, delay, burst, plr, queue, aqm)
#   queues 100-199 — per-flow split of a pipe OR sched (mask, weight, aqm)
#   scheds 200-299 — scheduling algorithm (type, bw, quantum/limit/flows)
# Pipes are created with `ipfw pipe`; scheds with `ipfw sched`; queues
# attach to either via `pipe N` or `sched N`. The dnctl(8) utility does
# NOT exist in this FreeBSD tree, so ipfw is the only pipe/sched creator.
# Rules divert traffic via pf anchor "traffic-shape" (dnpipe/dnqueue).
# The anchor only takes effect if /etc/pf.conf references it:
#     anchor "traffic-shape"
# (integration step — see README.md; the apply step warns if missing.)
# Idempotent: flushes only its own number ranges before re-applying.
# Exit 0 on success (including disabled / no config). Non-zero with a
# clear message on bad config, so a klish commit can fail loudly.

ANCHOR_FILE=/etc/pf-traffic-shape.conf
ANCHOR=traffic-shape

warn() {
    if [ -t 2 ]; then printf '%s: \033[33mwarning:\033[0m %s\n' "$PROG" "$*" >&2
    else echo "$PROG: warning: $*" >&2; fi
}

pf_enabled() {
    pfctl -s info 2>/dev/null | grep -q "Status: Enabled"
}

flush_all() {
    # Only our own ranges: pipes 1-99, queues 100-199, scheds 200-299.
    _n=1
    while [ "$_n" -le 99 ]; do
        ipfw pipe "$_n" delete >/dev/null 2>&1 || true
        _n=$((_n + 1))
    done
    _n=100
    while [ "$_n" -le 199 ]; do
        ipfw queue "$_n" delete >/dev/null 2>&1 || true
        _n=$((_n + 1))
    done
    _n=200
    while [ "$_n" -le 299 ]; do
        ipfw sched "$_n" delete >/dev/null 2>&1 || true
        _n=$((_n + 1))
    done
    if pf_enabled; then
        pfctl -a "$ANCHOR" -F rules >/dev/null 2>&1 || true
    fi
    rm -f "$ANCHOR_FILE"
}

# --- name -> number maps (kept in shell vars; all passes run in this shell)
_pipes=""    # "name:num name:num ..."
_scheds=""   # "name:num name:num ..."
_queues=""   # "name:num name:num ..."

lookup() {
    # lookup <map> <name> -> prints number or empty
    _map="$1"; _want="$2"
    for _e in $_map; do
        case "$_e" in
            "$_want":*) echo "${_e#*:}"; return 0 ;;
        esac
    done
    return 1
}

# emit_aqm <clause> — sets _aqm_toks to the ipfw tokens for an AQM clause
# ("" for none/droptail). Dies on a bad clause. Runs in the main shell.
emit_aqm() {
    case "$1" in
        ""|"aqm droptail") _aqm_toks="" ;;
        "aqm red "*|"aqm gred "*|"aqm codel"|"aqm codel "*|"aqm pie"|"aqm pie "*)
            _aqm_toks="${1#aqm }" ;;
        *) die "bad aqm clause: $1" ;;
    esac
}

# --- apply (was traffic-shape-apply, standalone) --------------------
cmd_apply() {
    # $1 = optional config path, or --flush
    if [ "${1:-}" = "--flush" ]; then
        kldstat -q -m dummynet 2>/dev/null || exit 0
        flush_all
        exit 0
    fi
    [ -n "${1:-}" ] && CONF="$1"
    # --- load modules -------------------------------------------------------
    kldstat -q -m dummynet 2>/dev/null || kldload dummynet \
        || die "cannot load dummynet module"
    kldstat -q -m ipfw 2>/dev/null || kldload ipfw \
        || die "cannot load ipfw module"

    # --- no config yet = nothing to do --------------------------------------
    [ -f "$CONF" ] || { flush_all; exit 0; }

    # --- disabled = flush everything and stop -------------------------------
    _en=$(sed -n 's/^enable //p' "$CONF" | head -1)
    if [ "$_en" != "yes" ]; then
        flush_all
        exit 0
    fi

    flush_all

    # --- pass 1: pipes ------------------------------------------------------
    _pipeno=0
    while read -r _line; do
        case "$_line" in
            pipe\ *)
                set -- $_line
                [ "$#" -ge 12 ] || die "corrupt pipe line: $_line"
                # $1=pipe $2=name $3=bw $4=rate $5=queue $6=n $7=delay $8=ms
                # $9=plr ${10}=x $11=burst ${12}=n ; $13+ = aqm clause
                _pname="$2"; _bw="$4"; _q="$6"; _d="$8"; _plr="${10}"; _burst="${12}"
                [ "$_bw" != "unset" ] || die "pipe $_pname has no bandwidth (set it first)"
                shift 12
                _aqm="$*"
                _pipeno=$((_pipeno + 1))
                [ "$_pipeno" -le 99 ] || die "too many pipes (max 99)"
                _pipes="$_pipes $_pname:$_pipeno"
                _burst_opt=""
                [ "$_burst" -gt 0 ] 2>/dev/null && _burst_opt="burst $_burst"
                emit_aqm "$_aqm"
                # shellcheck disable=SC2086 (intentional word-splitting)
                ipfw pipe "$_pipeno" config bw "$_bw" queue "$_q" delay "$_d" \
                    plr "$_plr" $_burst_opt $_aqm_toks \
                    || die "ipfw pipe $_pipeno (name $_pname) failed"
                ;;
        esac
    done < "$CONF"

    # --- pass 1b: schedulers ------------------------------------------------
    _schedno=199
    while read -r _line; do
        case "$_line" in
            sched\ *)
                set -- $_line
                _sname="$2"
                shift 2
                _type=""; _bw=""; _quantum=""; _limit=""; _flows=""
                while [ $# -gt 0 ]; do
                    case "$1" in
                        type)    _type="${2:-}"; shift 2 ;;
                        bw)      _bw="${2:-}"; shift 2 ;;
                        quantum) _quantum="${2:-}"; shift 2 ;;
                        limit)   _limit="${2:-}"; shift 2 ;;
                        flows)   _flows="${2:-}"; shift 2 ;;
                        *) die "cannot parse sched line: $_line" ;;
                    esac
                done
                [ -n "$_type" ] || die "sched $_sname has no type (set it first)"
                case "$_type" in
                    fifo|wf2q+|rr|qfq|fq_codel|fq_pie) ;;
                    *) die "sched $_sname: bad type $_type" ;;
                esac
                case "$_type" in
                    fq_codel|fq_pie) ;;
                    *)
                        [ -z "$_quantum$_limit$_flows" ] \
                            || die "sched $_sname: quantum/limit/flows need type fq_codel|fq_pie"
                        ;;
                esac
                _schedno=$((_schedno + 1))
                [ "$_schedno" -le 299 ] || die "too many schedulers (max 100)"
                _scheds="$_scheds $_sname:$_schedno"
                # bw (a non-fq option) goes BEFORE the type token; fq params
                # go AFTER it (ipfw.8: tokens after fq_codel/fq_pie belong to it).
                _scfg="type $_type"
                [ -n "$_bw" ] && _scfg="bw $_bw $_scfg"
                [ -n "$_quantum" ] && _scfg="$_scfg quantum $_quantum"
                [ -n "$_limit" ] && _scfg="$_scfg limit $_limit"
                [ -n "$_flows" ] && _scfg="$_scfg flows $_flows"
                # shellcheck disable=SC2086 (intentional word-splitting)
                ipfw sched "$_schedno" config $_scfg \
                    || die "ipfw sched $_schedno (name $_sname) failed"
                ;;
        esac
    done < "$CONF"

    # --- pass 2: queues -----------------------------------------------------
    _queueno=99
    while read -r _line; do
        case "$_line" in
            queue\ *)
                set -- $_line
                [ "$#" -ge 11 ] || die "corrupt queue line: $_line"
                # $1=queue $2=name $3=kind $4=parent $5=mask $6=spec $7=val
                # $8=weight $9=w $10=queue $11=n ; $12+ = aqm clause
                _qname="$2"; _kind="$3"; _parent="$4"
                _spec="$6"; _val="$7"; _w="$9"; _q="${11}"
                [ "$_parent" != "unset" ] || die "queue $_qname has no parent (set pipe or sched first)"
                shift 11
                _aqm="$*"
                case "$_kind" in
                    pipe)
                        _pno=$(lookup "$_pipes" "$_parent") \
                            || die "queue $_qname refers to unknown pipe $_parent"
                        _parent_opt="pipe $_pno" ;;
                    sched)
                        _sno=$(lookup "$_scheds" "$_parent") \
                            || die "queue $_qname refers to unknown sched $_parent"
                        _parent_opt="sched $_sno" ;;
                    *) die "queue $_qname: bad parent kind $_kind" ;;
                esac
                case "$_spec" in
                    all) _mask="mask all" ;;
                    dst-ip|src-ip|dst-ip6|src-ip6|dst-port|src-port|proto|flow-id)
                        _mask="mask $_spec $_val" ;;
                    *) die "queue $_qname: bad mask $_spec" ;;
                esac
                _queueno=$((_queueno + 1))
                [ "$_queueno" -le 199 ] || die "too many queues (max 100)"
                _queues="$_queues $_qname:$_queueno"
                emit_aqm "$_aqm"
                # shellcheck disable=SC2086 (intentional word-splitting)
                ipfw queue "$_queueno" config $_parent_opt $_mask \
                    weight "$_w" queue "$_q" $_aqm_toks \
                    || die "ipfw queue $_queueno (name $_qname) failed"
                ;;
        esac
    done < "$CONF"

    # --- pass 3: rules -> pf anchor file ------------------------------------
    _anchor_tmp="$ANCHOR_FILE.tmp.$$"
    : > "$_anchor_tmp" || die "cannot write $ANCHOR_FILE"
    while read -r _line; do
        case "$_line" in
            rule\ *)
                set -- $_line
                [ "$#" -ge 7 ] || die "corrupt rule line: $_line"
                # $1=rule $2=name $3=dir $4=on $5=if $6=kind $7=ref $8..=filters
                _rname="$2"; _dir="$3"; _if="$5"; _kind="$6"; _ref="$7"
                shift 7
                _src=""; _dst=""; _proto=""; _dport=""
                while [ $# -gt 0 ]; do
                    case "$1" in
                        src)   _src="${2:-}"; shift 2 ;;
                        dst)   _dst="${2:-}"; shift 2 ;;
                        proto) _proto="${2:-}"; shift 2 ;;
                        dport) _dport="${2:-}"; shift 2 ;;
                        *) die "cannot parse rule line: $_line" ;;
                    esac
                done
                case "$_kind" in
                    pipe)
                        _no=$(lookup "$_pipes" "$_ref") \
                            || die "rule $_rname refers to unknown pipe $_ref"
                        _act="dnpipe $_no" ;;
                    queue)
                        _no=$(lookup "$_queues" "$_ref") \
                            || die "rule $_rname refers to unknown queue $_ref"
                        _act="dnqueue $_no" ;;
                    *) die "rule $_rname: bad target kind $_kind" ;;
                esac
                _rule="pass $_dir on $_if"
                case "$_proto" in
                    ""|all) ;;
                    tcp|udp|icmp) _rule="$_rule proto $_proto" ;;
                    *) die "rule $_rname: bad proto $_proto" ;;
                esac
                case "$_src" in
                    ""|any) ;;
                    *) _rule="$_rule from $_src" ;;
                esac
                case "$_dst" in
                    ""|any) ;;
                    *) _rule="$_rule to $_dst" ;;
                esac
                if [ -n "$_dport" ]; then
                    case "$_proto" in
                        tcp|udp) _rule="$_rule port $_dport" ;;
                        *) die "rule $_rname: dport needs proto tcp|udp" ;;
                    esac
                fi
                printf '%s %s\n' "$_rule" "$_act" >> "$_anchor_tmp"
                ;;
        esac
    done < "$CONF"
    mv "$_anchor_tmp" "$ANCHOR_FILE" || die "cannot write $ANCHOR_FILE"

    # --- load the anchor into pf --------------------------------------------
    if pf_enabled; then
        if grep -q "anchor \"$ANCHOR\"" /etc/pf.conf 2>/dev/null; then
            pfctl -a "$ANCHOR" -f "$ANCHOR_FILE" \
                || die "pfctl failed to load anchor $ANCHOR"
        else
            warn "/etc/pf.conf does not reference anchor \"$ANCHOR\" — add this line (after scrub, before filter rules):"
            warn "    anchor \"$ANCHOR\""
            warn "pipes/queues are created, but no traffic is diverted until then"
        fi
    else
        warn "pf is disabled — anchor not loaded (pipes/queues created anyway)"
    fi

    exit 0
}

