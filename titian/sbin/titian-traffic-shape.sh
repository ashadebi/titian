    touch_conf
    _en=$(sed -n 's/^enable //p' "$CONF" | head -1)
    echo "traffic-shape: ${_en:-no}"
    echo "pipes:"
    grep '^pipe ' "$CONF" 2>/dev/null | sed 's/^/  /' || true
    echo "schedulers:"
    grep '^sched ' "$CONF" 2>/dev/null | sed 's/^/  /' || true
    echo "queues:"
    grep '^queue ' "$CONF" 2>/dev/null | sed 's/^/  /' || true
    echo "rules:"
    grep '^rule ' "$CONF" 2>/dev/null | sed 's/^/  /' || true
