    if ! kldstat -q -m dummynet 2>/dev/null; then
        echo "dummynet not loaded (traffic-shape never applied?)" >&2
        exit 0
    fi
    echo "== pipes =="
    ipfw pipe show 2>/dev/null || echo "(no pipes in kernel)"
    echo "== schedulers =="
    ipfw sched show 2>/dev/null || echo "(no schedulers in kernel)"
    echo "== queues =="
    ipfw queue show 2>/dev/null || echo "(no queues in kernel)"
    exit 0
}

# --- mutations ----------------------------------------------------------
cmd_set_enable() {
    case "$1" in
        yes|no) upsert '^enable ' "enable $1" ;;
        *) die "enable takes yes|no" ;;
    esac
    case "$1" in
        yes) echo "traffic-shape enabled" ;;
        no)  echo "traffic-shape disabled" ;;
    esac
    exit 0
}

# set-pipe-field <name> <field> [value...]
# Fields: bw, queue, delay, plr, burst, aqm-clause (one arg: full clause).
cmd_set_pipe_field() {
    _name="$1"; _field="$2"; shift 2
    _value="$1"
    valid_name "$_name"
    touch_conf
    _line=$(grep "^pipe $_name " "$CONF" 2>/dev/null | head -1)
    if [ -z "$_line" ]; then
        _line="pipe $_name bw unset queue 50 delay 0 plr 0 burst 0"
    fi
    set -- $_line
    [ "$#" -ge 12 ] || die "corrupt pipe line: $_line"
    # $1=pipe $2=name $3=bw $4=rate $5=queue $6=n $7=delay $8=ms $9=plr
    # ${10}=x $11=burst $12=n ; $13+ = aqm clause
    _bw="$4"; _q="$6"; _d="$8"; _plr="${10}"; _burst="${12}"
    shift 12
    _aqm="$*"
    case "$_field" in
        bw)    _bw="$_value" ;;
        queue) _q="$_value" ;;
        delay) _d="$_value" ;;
        plr)   _plr="$_value" ;;
        burst) _burst="$_value" ;;
        aqm-clause)
            valid_aqm_clause "$_value"
            _aqm="$_value" ;;
        *) die "unknown pipe field: $_field" ;;
    esac
    _line="pipe $_name bw $_bw queue $_q delay $_d plr $_plr burst $_burst"
    [ -n "$_aqm" ] && _line="$_line $_aqm"
    upsert "^pipe $_name " "$_line"
    echo "pipe $_name: $_field = $_value"
    exit 0
}

# set-sched-field <name> <field> <value>
# Fields: type, bw, quantum, limit, flows.
# Line format: sched <name> type <t> [bw <rate>] [quantum <n>]
#              [limit <n>] [flows <n>]  (key/value pairs after the name)
cmd_set_sched_field() {
    _name="$1"; _field="$2"; _value="${3:-}"
    valid_name "$_name"
    touch_conf
    _line=$(grep "^sched $_name " "$CONF" 2>/dev/null | head -1)
    _type=""; _bw=""; _quantum=""; _limit=""; _flows=""
    if [ -n "$_line" ]; then
        set -- $_line
        shift 2  # drop "sched NAME"
        while [ $# -gt 0 ]; do
            case "$1" in
                type)    _type="${2:-}"; shift 2 ;;
                bw)      _bw="${2:-}"; shift 2 ;;
                quantum) _quantum="${2:-}"; shift 2 ;;
                limit)   _limit="${2:-}"; shift 2 ;;
                flows)   _flows="${2:-}"; shift 2 ;;
                *) die "cannot parse sched line: $_line" ;;
            esac
        done
    fi
    case "$_field" in
        type)
            case "$_value" in
                fifo|wf2q+|rr|qfq|fq_codel|fq_pie) _type="$_value" ;;
                *) die "sched type must be fifo|wf2q+|rr|qfq|fq_codel|fq_pie" ;;
            esac
            ;;
        bw) _bw="$_value" ;;
        quantum|limit|flows)
            case "$_type" in
                fq_codel|fq_pie) ;;
                *) die "$_field needs sched type fq_codel|fq_pie (current: ${_type:-unset})" ;;
            esac
            case "$_value" in *[!0-9]*|"") die "$_field must be a number" ;; esac
            case "$_field" in
                quantum) _quantum="$_value" ;;
                limit)   _limit="$_value" ;;
                flows)   _flows="$_value" ;;
            esac
            ;;
        *) die "unknown sched field: $_field" ;;
    esac
    _line="sched $_name"
    [ -n "$_type" ] && _line="$_line type $_type"
    [ -n "$_bw" ] && _line="$_line bw $_bw"
    [ -n "$_quantum" ] && _line="$_line quantum $_quantum"
    [ -n "$_limit" ] && _line="$_line limit $_limit"
    [ -n "$_flows" ] && _line="$_line flows $_flows"
    upsert "^sched $_name " "$_line"
    echo "sched $_name: $_field = $_value"
    exit 0
}

# set-queue-field <name> <field> [value...]
# Fields: pipe <pname> | sched <sname> | mask <spec> [val] |
#         weight <n> | queue <n> | aqm-clause <clause>.
cmd_set_queue_field() {
    _name="$1"; _field="$2"; shift 2
    _a1="${1:-}"; _a2="${2:-}"
    valid_name "$_name"
    touch_conf
    _line=$(grep "^queue $_name " "$CONF" 2>/dev/null | head -1)
    if [ -z "$_line" ]; then
        _line="queue $_name pipe unset mask all - weight 1 queue 50"
    fi
    set -- $_line
    [ "$#" -ge 11 ] || die "corrupt queue line: $_line"
    # $1=queue $2=name $3=kind $4=parent $5=mask $6=spec $7=val $8=weight
    # $9=w $10=queue $11=n ; $12+ = aqm clause
    _kind="$3"; _parent="$4"; _spec="$6"; _val="$7"; _w="$9"; _q="${11}"
    shift 11
    _aqm="$*"
    case "$_field" in
        pipe)
            valid_name "$_a1"
            pipe_exists "$_a1" || die "pipe $_a1 not found (create it first)"
            _kind="pipe"; _parent="$_a1" ;;
        sched)
            valid_name "$_a1"
            sched_exists "$_a1" || die "sched $_a1 not found (create it first)"
            _kind="sched"; _parent="$_a1" ;;
        mask)
            case "$_a1" in
                dst-ip|src-ip|dst-ip6|src-ip6|dst-port|src-port|proto|flow-id|all)
                    _spec="$_a1" ;;
                *) die "mask must be dst-ip|src-ip|dst-ip6|src-ip6|dst-port|src-port|proto|flow-id|all" ;;
            esac
            if [ "$_spec" = "all" ]; then
                _val="-"
            else
                _val="$_a2"
                [ -n "$_val" ] || _val=$(default_mask_val "$_spec")
                valid_mask_val "$_spec" "$_val"
            fi
            ;;
        weight)
            case "$_a1" in *[!0-9]*|"") die "weight must be 1-100" ;; esac
            [ "$_a1" -ge 1 ] && [ "$_a1" -le 100 ] || die "weight must be 1-100"
            _w="$_a1" ;;
        queue)
            case "$_a1" in *[!0-9]*|"") die "queue must be a number" ;; esac
            _q="$_a1" ;;
        aqm-clause)
            valid_aqm_clause "$_a1"
            _aqm="$_a1" ;;
        *) die "unknown queue field: $_field" ;;
    esac
    _line="queue $_name $_kind $_parent mask $_spec $_val weight $_w queue $_q"
    [ -n "$_aqm" ] && _line="$_line $_aqm"
    upsert "^queue $_name " "$_line"
    echo "queue $_name: $_field updated"
    exit 0
}

# set-rule-field <name> <field> [value...]
#   interface <if> <dir> | target pipe|queue <ref> | src|dst <addr> |
#   proto <p> | dport <n>
cmd_set_rule_field() {
    _name="$1"; _field="$2"; shift 2
    _a1="${1:-}"; _a2="${2:-}"
    valid_name "$_name"
    touch_conf
    _line=$(grep "^rule $_name " "$CONF" 2>/dev/null | head -1)
    if [ -z "$_line" ]; then
        # Fresh rule: interface must come first (it carries dir + if).
        [ "$_field" = "interface" ] || die "rule $_name not found (set interface first)"
        _line="rule $_name $_a2 on $_a1 pipe unset"
    fi
    # Tokenise the current line into positional fields.
    set -- $_line
    [ "$#" -ge 7 ] || die "corrupt rule line: $_line"
    # $1=rule $2=name $3=dir $4=on $5=if $6=kind $7=ref $8..=optional filters
    _dir="$3"; _if="$5"; _kind="$6"; _ref="$7"
    shift 7
    _src=""; _dst=""; _proto=""; _dport=""
    while [ $# -gt 0 ]; do
        case "$1" in
            src)   _src="${2:-}"; shift 2 ;;
            dst)   _dst="${2:-}"; shift 2 ;;
            proto) _proto="${2:-}"; shift 2 ;;
            dport) _dport="${2:-}"; shift 2 ;;
            *) die "cannot parse rule line: $_line" ;;
        esac
    done
    case "$_field" in
        interface)
            _if="$_a1"; _dir="$_a2"
            iface_exists "$_if"
            case "$_dir" in in|out) ;; *) die "direction must be in|out" ;; esac
            ;;
        target)
            _kind="$_a1"; _ref="$_a2"
            case "$_kind" in
                pipe)  pipe_exists "$_ref" || die "pipe $_ref not found (create it first)" ;;
                queue) queue_exists "$_ref" || die "queue $_ref not found (create it first)" ;;
                *) die "target must be pipe|queue" ;;
            esac
            ;;
        src)   _src="$_a1" ;;
        dst)   _dst="$_a1" ;;
        proto)
            case "$_a1" in tcp|udp|icmp|all) _proto="$_a1" ;; *) die "proto must be tcp|udp|icmp|all" ;; esac
            ;;
        dport)
            case "$_proto" in
                tcp|udp) ;;
                *) die "dport needs proto tcp|udp (current proto: ${_proto:-unset})" ;;
            esac
            case "$_a1" in
                *[!0-9]*|"") die "dport must be 1-65535" ;;
            esac
            [ "$_a1" -ge 1 ] && [ "$_a1" -le 65535 ] || die "dport must be 1-65535"
            _dport="$_a1"
            ;;
        *) die "unknown rule field: $_field" ;;
    esac
    _line="rule $_name $_dir on $_if $_kind $_ref"
    [ -n "$_src" ] && _line="$_line src $_src"
    [ -n "$_dst" ] && _line="$_line dst $_dst"
    [ -n "$_proto" ] && _line="$_line proto $_proto"
    [ -n "$_dport" ] && _line="$_line dport $_dport"
    upsert "^rule $_name " "$_line"
    echo "rule $_name updated"
    exit 0
}

cmd_del_pipe() {
    _name="$1"; valid_name "$_name"
    touch_conf
    _dep=$(grep -E "^queue [^ ]+ pipe $_name( |\$)" "$CONF" 2>/dev/null | awk '{print $2}' | tr '\n' ' ')
    _dep2=$(grep -E "^rule [^ ]+ .* pipe $_name( |\$)" "$CONF" 2>/dev/null | awk '{print $2}' | tr '\n' ' ')
    if [ -n "$_dep$_dep2" ]; then
        die "pipe $_name still used by: queues [${_dep:-none}] rules [${_dep2:-none}] (delete them first)"
    fi
    dellines "^pipe $_name " "pipe $_name"
    echo "pipe $_name deleted"
    exit 0
}

cmd_del_sched() {
    _name="$1"; valid_name "$_name"
    touch_conf
    _dep=$(grep -E "^queue [^ ]+ sched $_name( |\$)" "$CONF" 2>/dev/null | awk '{print $2}' | tr '\n' ' ')
    if [ -n "$_dep" ]; then
        die "sched $_name still used by queues: [$_dep] (delete them first)"
    fi
    dellines "^sched $_name " "sched $_name"
    echo "sched $_name deleted"
    exit 0
}

cmd_del_queue() {
    _name="$1"; valid_name "$_name"
    touch_conf
    _dep=$(grep -E "^rule [^ ]+ .* queue $_name( |\$)" "$CONF" 2>/dev/null | awk '{print $2}' | tr '\n' ' ')
