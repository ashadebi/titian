#!/bin/sh
# FW-APPLY-MOCK.sh — bukti staging `titian-fw.sh apply` (firewall/NAT pf,
# 23 Nov 2026). Inventaris Item 10: firewall/NAT via klish SUDAH
# terintegrasi penuh di repo (conf-fw.xml: filter/snat/dnat/
# protect-interface/show; backend titian-fw.sh apply; hook commit di
# titian-commit.sh; hook boot di titian-boot.sh; panduan §8) — yang
# belum pernah ada adalah (a) bukti apply di luar mesin test dan
# (b) uji live (BLOKIR sejak 13 Nov, §14 baris 12). Mock ini menutup
# (a); (b) tetap butuh gelombang live (rencana di laporan).
#
# Membuktikan TANPA mesin test (semua di-stub):
#   (a) apply config berisi filter permit+deny, snat masquerade, dnat
#       -> file anchor pf yang benar (pass/block + nat + rdr + trailing
#       `block in quick ... all` untuk forward default DENY);
#   (b) parse-check pfctl jalan SEBELUM file live disentuh (urutan log);
#   (c) rule dengan interface yang tidak ada di-SKIP + peringatan,
#       bukan gagal total;
#   (d) enable no -> anchor di-flush + file anchor dihapus;
#   (e) `show` / `show-filter` / `show-nat` menampilkan rule.
# POSIX sh. Keluar 0 bila semua PASS.
STAGE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
FW_SH="$STAGE/titian/sbin/titian-fw.sh"
PASS=0; FAIL=0
ok()   { PASS=$((PASS+1)); echo "PASS: $1"; }
bad()  { FAIL=$((FAIL+1)); echo "FAIL: $1"; }

MOCKROOT=$(mktemp -d /tmp/fw-apply-mock.XXXXXX) || { echo "FAIL: mktemp"; exit 1; }
trap 'if [ "$FAIL" -gt 0 ]; then echo "MOCKROOT (dipertahankan untuk inspeksi): $MOCKROOT"; else rm -rf "$MOCKROOT"; fi' EXIT

FAKEBIN="$MOCKROOT/bin"
mkdir -p "$FAKEBIN"
export FW_MOCK_LOG="$MOCKROOT/calls.log"
: > "$FW_MOCK_LOG"

cat > "$FAKEBIN/kldstat" <<'EOF'
#!/bin/sh
echo "kldstat $*" >> "$FW_MOCK_LOG"
exit 0
EOF
cat > "$FAKEBIN/kldload" <<'EOF'
#!/bin/sh
echo "kldload $*" >> "$FW_MOCK_LOG"
exit 0
EOF
cat > "$FAKEBIN/pfctl" <<'EOF'
#!/bin/sh
echo "pfctl $*" >> "$FW_MOCK_LOG"
# pfctl -s info / -s Running: pf jalan
if [ "$1" = "-s" ] && [ "$2" = "info" ]; then echo "Status: Enabled"; exit 0; fi
if [ "$1" = "-s" ]; then exit 0; fi
exit 0
EOF
cat > "$FAKEBIN/ifconfig" <<'EOF'
#!/bin/sh
echo "ifconfig $*" >> "$FW_MOCK_LOG"
# hanya em1 yang "ada" di mesin mock ini
if [ "$1" = "em1" ]; then exit 0; else exit 1; fi
EOF
chmod +x "$FAKEBIN"/*
export PATH="$FAKEBIN:$PATH"

CONF="$MOCKROOT/firewall.conf"
PF_CONF="$MOCKROOT/pf.conf"
FW_FILE="$MOCKROOT/pf-firewall.conf"
NAT_FILE="$MOCKROOT/pf-nat.conf"
cat > "$PF_CONF" <<'EOF'
nat-anchor "nat"
rdr-anchor "nat"
anchor "firewall"
pass all
EOF
export FW_CONF="$CONF" PF_CONF="$PF_CONF" PF_FW_FILE="$FW_FILE" PF_NAT_FILE="$NAT_FILE"

cat > "$CONF" <<'EOF'
# firewall.conf - generated by klish, do not edit by hand
enable yes
protected ge0
filter forward permit proto tcp src any dst any sport any dport any in em1 out any
filter forward deny proto all src any dst any sport any dport any in em1 out any
filter forward permit proto udp src any dst any sport any dport any in em9 out any
snat 10.99.44.0/24 to masquerade out em1
dnat tcp in em1 dport 8080 to 10.0.0.5 port same
EOF

# --- (a)+(b)+(c) apply-all ---
if sh "$FW_SH" apply-all >"$MOCKROOT/apply.out" 2>&1; then ok "apply-all rc=0"; else bad "apply-all rc!=0"; cat "$MOCKROOT/apply.out"; fi
grep -q "pass in quick on em1 inet proto tcp from any to any" "$FW_FILE" 2>/dev/null && ok "anchor fw: pass tcp em1" || { bad "anchor fw: pass tcp em1 hilang"; cat "$FW_FILE" 2>/dev/null; }
grep -q "block in quick on em1 inet from any to any" "$FW_FILE" 2>/dev/null && ok "anchor fw: block all em1" || bad "anchor fw: block all em1 hilang"
grep -q "block in quick on em1 all" "$FW_FILE" 2>/dev/null && ok "anchor fw: trailing block forward default DENY" || bad "anchor fw: trailing block hilang"
if grep -q "em9" "$FW_FILE" 2>/dev/null; then bad "rule iface em9 (tidak ada) ikut masuk anchor"; else ok "rule iface em9 di-SKIP (tidak ada di anchor)"; fi
grep -qi "SKIP.*em9" "$MOCKROOT/apply.out" && ok "peringatan SKIP em9 tampil" || bad "peringatan SKIP em9 tidak tampil"
grep -q "nat on em1 from 10.99.44.0/24 to any -> (em1)" "$NAT_FILE" 2>/dev/null && ok "anchor nat: masquerade em1" || { bad "anchor nat: masquerade hilang"; cat "$NAT_FILE" 2>/dev/null; }
grep -q "rdr on em1 proto tcp from any to any port 8080 -> 10.0.0.5" "$NAT_FILE" 2>/dev/null && ok "anchor nat: rdr 8080 -> 10.0.0.5" || bad "anchor nat: rdr hilang"
# (b) urutan: parse-check (-n -f) SEBELUM load (-f) untuk kedua anchor
_NAT_CHECK=$(grep -n "pfctl -a nat -n -f" "$FW_MOCK_LOG" | head -1 | cut -d: -f1)
_NAT_LOAD=$(grep -n "pfctl -a nat -f" "$FW_MOCK_LOG" | head -1 | cut -d: -f1)
_FW_CHECK=$(grep -n "pfctl -a firewall -n -f" "$FW_MOCK_LOG" | head -1 | cut -d: -f1)
_FW_LOAD=$(grep -n "pfctl -a firewall -f" "$FW_MOCK_LOG" | head -1 | cut -d: -f1)
if [ -n "$_NAT_CHECK" ] && [ -n "$_NAT_LOAD" ] && [ "$_NAT_CHECK" -lt "$_NAT_LOAD" ] && \
   [ -n "$_FW_CHECK" ] && [ -n "$_FW_LOAD" ] && [ "$_FW_CHECK" -lt "$_FW_LOAD" ]; then
    ok "parse-check mendahului load (nat + firewall)"
else
    bad "urutan parse-check/load salah"; cat "$FW_MOCK_LOG"
fi

# --- (d) enable no -> flush ---
sed -i 's/^enable yes/enable no/' "$CONF"
if sh "$FW_SH" apply-all >"$MOCKROOT/apply-off.out" 2>&1; then ok "apply-all (enable no) rc=0"; else bad "apply-all (enable no) rc!=0"; cat "$MOCKROOT/apply-off.out"; fi
if [ ! -e "$FW_FILE" ] && [ ! -e "$NAT_FILE" ]; then ok "enable no: file anchor dihapus"; else bad "enable no: file anchor masih ada"; fi
if grep -q "pfctl -a firewall -F rules" "$FW_MOCK_LOG" && grep -q "pfctl -a nat -F rules" "$FW_MOCK_LOG"; then
    ok "enable no: anchor di-flush (pfctl -F)"
else
    bad "enable no: flush tidak tercatat"; cat "$FW_MOCK_LOG"
fi

# --- (e) show menampilkan rule ---
sed -i 's/^enable no/enable yes/' "$CONF"
if sh "$FW_SH" show >"$MOCKROOT/show.out" 2>&1; then ok "show rc=0"; else bad "show rc!=0"; cat "$MOCKROOT/show.out"; fi
grep -q "filter forward permit proto tcp" "$MOCKROOT/show.out" && ok "show: rule filter tampil" || bad "show: rule filter hilang"
if sh "$FW_SH" show-filter >"$MOCKROOT/showf.out" 2>&1 && grep -q "filter forward deny" "$MOCKROOT/showf.out"; then ok "show-filter tampil"; else bad "show-filter gagal/hilang"; fi
if sh "$FW_SH" show-nat >"$MOCKROOT/shown.out" 2>&1 && grep -q "snat 10.99.44.0/24" "$MOCKROOT/shown.out" && grep -q "dnat tcp" "$MOCKROOT/shown.out"; then ok "show-nat tampil (snat+dnat)"; else bad "show-nat gagal/hilang"; fi

echo "HASIL: PASS=$PASS FAIL=$FAIL"
[ "$FAIL" -eq 0 ] || exit 1
exit 0
